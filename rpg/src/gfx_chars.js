  // ===========================================================================
  // CharArt - procedurally assembled 16x16 top-down character sprites
  // (16-bit era chibi style: big heads, 1px dark outline, light from top-left).
  //
  //   CharArt.get(kind, dir, frame) -> HTMLCanvasElement (16x16, transparent bg)
  //       dir:   'down' | 'left' | 'up' | 'right'   (anything else -> 'down')
  //       frame: 0 | 1 walk cycle (any integer is taken modulo 2)
  //       unknown kind -> the 'man' sprite.  Never throws.  Results are cached,
  //       so the same canvas object is returned for the same arguments.
  //   CharArt.kinds -> array of all kind ids
  //
  // Every pixel is either fully opaque or fully transparent.  Adult sprites
  // stand with feet on row 15; 'boy' and 'girl' are drawn smaller (head starts
  // at row 3 instead of row 1); 'ghost' floats (bobs 1px between frames) and
  // 'coffin' hops 1px on frame 1.
  //
  // How the art is built: small ASCII templates (one char per pixel) are
  // merged into "parts" (e.g. body, head, held item); each part is outlined
  // automatically (4-neighbour, colour OUTLINE) and parts are composited in
  // order, so e.g. a head always gets a clean chin line over the body.
  // 'right' is the horizontal mirror of 'left'.
  //
  // Template letters (resolved per kind through its palette):
  //   k outline/eyes   S s L skin (base/shadow/light)   H h I hair
  //   A a Y main cloth (base/shadow/highlight)          B b secondary cloth
  //   C belt/trim   D d shoes   E e F f headwear   G g gold   M m n metal
  //   W w white   R r red/cape   T t wood   V v apron/vest/overlay
  //   others (J X x N O P p Q) are kind-specific accents.
  // ===========================================================================

  const OUTLINE = '#181018';

  // ---------------------------------------------------------------------------
  // Template helpers.  A template is an array of 16 strings of 16 chars.
  // '.' = leave as is, '_' = erase (within the current part), 'k' = outline
  // colour, anything else = palette key.  A line '@N' moves to row N.
  // ---------------------------------------------------------------------------
  const EMPTY_ROW = '................';
  const badTemplates = [];
  function tpl(src) {
    const rows = new Array(16).fill(EMPTY_ROW);
    let y = 0;
    for (const raw of src.split('\n')) {
      const line = raw.trim();
      if (!line) continue;
      if (line[0] === '@') { y = parseInt(line.slice(1), 10); continue; }
      if (line.length !== 16) badTemplates.push('row ' + y + ' len ' + line.length + ': ' + line);
      if (y > 15) break;
      rows[y] = (line + EMPTY_ROW).slice(0, 16);
      y++;
    }
    return rows;
  }
  function mirror(t) { return t.map(r => r.split('').reverse().join('')); }
  function shift(t, dx, dy) {
    if (!dx && !dy) return t;
    const out = new Array(16).fill(EMPTY_ROW);
    for (let y = 0; y < 16; y++) {
      const sy = y - dy;
      if (sy < 0 || sy > 15) continue;
      let row = '';
      for (let x = 0; x < 16; x++) {
        const sx = x - dx;
        row += sx >= 0 && sx < 16 ? t[sy][sx] : '.';
      }
      out[y] = row;
    }
    return out;
  }

  // ---------------------------------------------------------------------------
  // Rendering: a sprite is a list of parts; each part is a list of templates
  // merged in order, then auto-outlined (4-neighbour) and composited.
  // ---------------------------------------------------------------------------
  function renderParts(parts, pal) {
    const out = new Array(256).fill(null);
    for (const part of parts) {
      const g = new Array(256).fill(null);
      for (const t of part.t) {
        for (let y = 0; y < 16; y++) {
          const row = t[y];
          for (let x = 0; x < 16; x++) {
            const ch = row[x];
            if (ch === '.') continue;
            g[y * 16 + x] = ch === '_' ? null : ch;
          }
        }
      }
      const res = new Array(256).fill(null);
      const solid = (xx, yy) => xx >= 0 && xx < 16 && yy >= 0 && yy < 16 && g[yy * 16 + xx] && g[yy * 16 + xx] !== 'k';
      for (let i = 0; i < 256; i++) {
        const ch = g[i];
        if (ch) {
          if (ch === 'k') { res[i] = OUTLINE; continue; }
          const col = pal[ch];
          if (!col) throw new Error('palette key "' + ch + '" missing');
          res[i] = col;
        } else if (part.ol !== false) {
          const x = i & 15, y = i >> 4;
          if (solid(x - 1, y) || solid(x + 1, y) || solid(x, y - 1) || solid(x, y + 1)) res[i] = OUTLINE;
        }
      }
      for (let i = 0; i < 256; i++) if (res[i]) out[i] = res[i];
    }
    return out;
  }

  function newCanvas() {
    if (typeof document !== 'undefined' && document.createElement) return document.createElement('canvas');
    return new OffscreenCanvas(16, 16);
  }
  function toCanvas(pix) {
    const c = newCanvas();
    c.width = 16; c.height = 16;
    const g = c.getContext('2d');
    const img = g.createImageData(16, 16);
    for (let i = 0; i < 256; i++) {
      const col = pix[i];
      if (!col) continue;
      const v = parseInt(col.slice(1), 16);
      img.data[i * 4] = (v >> 16) & 255;
      img.data[i * 4 + 1] = (v >> 8) & 255;
      img.data[i * 4 + 2] = v & 255;
      img.data[i * 4 + 3] = 255;
    }
    g.putImageData(img, 0, 0);
    return c;
  }

