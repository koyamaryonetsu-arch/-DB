  // ---------------------------------------------------------------------------
  function layer(name, dir, frame) {
    const e = L[name];
    if (!e) throw new Error('unknown layer ' + name);
    const v = e[dir];
    if (!v) return null;
    return typeof v[0] === 'string' ? v : v[frame];
  }

  function build(kind, dir, frame) {
    const k = KINDS[kind];
    const pal = mix(DEFAULT_PAL, k.pal);
    const baseDir = dir === 'right' ? 'left' : dir;
    const parts = [];
    for (const p of k.parts) {
      const spec = Array.isArray(p) ? { l: p } : p;
      const sh = spec.shift && spec.shift[baseDir];
      const t = spec.l.map(n => layer(n, baseDir, frame)).filter(Boolean).map(tt => sh ? shift(tt, sh[0], sh[1]) : tt);
      if (t.length) parts.push({ t, ol: spec.ol });
    }
    let pix = renderParts(parts, pal);
    if (dir === 'right') {
      const m = new Array(256);
      for (let i = 0; i < 256; i++) m[i] = pix[(i & ~15) + (15 - (i & 15))];
      pix = m;
    }
    return pix;
  }

  const DIRS = ['down', 'left', 'up', 'right'];
  const cache = new Map();
  function get(kind, dir, frame) {
    if (typeof kind !== 'string' || !Object.prototype.hasOwnProperty.call(KINDS, kind)) kind = 'man';
    if (DIRS.indexOf(dir) < 0) dir = 'down';
    frame = (Number(frame) || 0) & 1;
    const key = kind + '|' + dir + '|' + frame;
    let c = cache.get(key);
    if (c) return c;
    try {
      c = toCanvas(build(kind, dir, frame));
    } catch (e) {
      if (typeof console !== 'undefined') console.error('CharArt: failed to build ' + key + ': ' + (e && e.message));
      if (kind !== 'man') c = get('man', dir, frame);
      else {
        try { c = toCanvas(new Array(256).fill(null)); } catch (e2) { c = null; }
      }
    }
    if (c) cache.set(key, c);
    return c;
  }

  if (badTemplates.length && typeof console !== 'undefined') console.error('CharArt: bad template rows:\n' + badTemplates.join('\n'));

  return { get, kinds: Object.keys(KINDS) };
