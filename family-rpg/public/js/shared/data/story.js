function sageHints(x) {
  const c = x.c;
  const learned = new Set(learnedAbilities(c));
  const hints = [];
  for (const [id, text] of Object.entries(COMBO_HINTS)) {
    if (learned.has(id)) continue;
    hints.push(text);
  }
  const lines = [
    ...S('ひらめきの けんじゃ', 'ほっほっほ。わしは ひらめきの けんじゃ。',
      'ちがう しょくぎょうで おぼえた わざを くみあわせると、\n「掛け合わせ技」を ひらめくことが ある。',
      'じゃが ひらめいても、すぐには つかえん。\nもとに なった しょくぎょうを あわせもつ 上級職に ならねばな。',
      'たとえば メラと ヒャドの メドロなら 魔法使いの 上級職（賢者・魔法戦士・忍者・占い師）…\n大地斬と メラの まほうけんなら 戦士と 魔法使いを あわせた 魔法戦士じゃ。'),
  ];
  const have = [...learned].filter((id) => ABILITIES[id]?.kind === 'combo');
  if (have.length) lines.push(...S('ひらめきの けんじゃ', `おぬしは すでに ${have.map((id) => ABILITIES[id].name).join('・')}を ひらめいて おるな。みごとじゃ。`));
  if (hints.length) {
    const pick = hints.slice(0, 2);
    lines.push(...S('ひらめきの けんじゃ', ...pick));
  } else {
    lines.push(...S('ひらめきの けんじゃ', 'もう わしが おしえる ことは ない。おぬしこそ ほんとうの けんじゃじゃ。'));
  }
  lines.push(...S('ひらめきの けんじゃ', 'メニューの「じゅもん・とくぎ」から「掛け合わせ」の いちらんも みられるぞ。'));
  return lines;
}

