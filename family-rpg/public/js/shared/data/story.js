// ものがたりの だいほん
//
// だいほんは「ステップ」の ならび。サーバーが じゅんばんに すすめる。
//   ['say', はなす人, 'ことば']        {name} は はなしかけた人の なまえ
//   ['choice', 'しつもん', ['はい','いいえ'], [はいの ステップ, いいえの ステップ]]
//   ['if', (x) => じょうけん, [そうなら], [ちがうなら]]
//   ['flag', 'フラグ']  ['item', 'どうぐ', こすう]  ['takeItem', 'どうぐ', こすう]  ['gold', ゴールド]
//   ['objective', 'つぎの もくひょう']  ['battle', 'たたかいID']  ['guest', 'ルカ' or null]
//   ['shop', 'みせID']  ['inn', ねだん]  ['church']  ['jobChange']  ['tavern']  ['board']  ['starTrade']
//   ['fade', 'out'|'in']  ['flash']  ['shake']  ['night', true|false]  ['bgm', 'きょく'|null]  ['sfx', 'おと']  ['wait', ミリびょう]
//   ['actor', ID, {sprite, x, y, dir}]  ['move', ID, [[x,y],...]]  ['face', ID, 'up']  ['remove', ID]
//   ['teleport', 'map', x, y, 'dir']  ['spawn', 'map', x, y]  ['chapter', 'だい1しょう', 'サブタイトル']
//
// x（じょうほう）: x.name x.flag('f') x.has('item') x.count('item') x.kills('monster') x.quest('key')
