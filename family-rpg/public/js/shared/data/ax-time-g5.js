const L = (ms, hit, len, o = {}) => ({ ...B(ms, hit, len, o), tier: 'legend', charge: { kind: o.kind || 'holy', ms } });
const P = { party: true };
const I = { kind: 'idol' }, IP = { kind: 'idol', party: true };
const ICE = { kind: 'ice' }, ICEP = { kind: 'ice', party: true };

