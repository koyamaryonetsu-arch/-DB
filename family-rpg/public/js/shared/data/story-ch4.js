// key … sun / sand / moon / star。intro … 歌う 前、outro … 歌った あと（つぎの 子の いる 所）
function kidSong(x, key, who, intro, outro) {
  const flag = `c4_song_${key}`;
  const first = !x.flag(flag);
  const total = SONG_FLAGS.filter((f) => f === flag || x.flag(f)).length;
  const steps = [...S(who, ...intro), ['sfx', 'sparkle'], ...S(who, SONG_LINES[key])];
  if (!first) return [...steps, ...S(who, ...outro)];
  steps.push(['flag', flag], ...N(`（わらべ歌の${SONG_ORDER[key]}を覚えた！\n「${SONG_LINES[key]}」）`));
  if (total >= SONG_FLAGS.length) return [...steps, ...N('わらべ歌を、4人ぶん、全部聞いた！', `「${SONG_FULL}」`), ...songDone(x)];
  return [...steps, ...S(who, ...outro)];
}

