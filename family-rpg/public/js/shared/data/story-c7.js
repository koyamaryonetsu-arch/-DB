// ───────────── 6階: 2つの 時代の 水の ふむ石 ─────────────
// a … 今の 石（6階 今）/ b … 千年前の 石。家族なら 1人ずつ 別の 時代で 同時に。ひとりなら カリムに 千年前の 石で 待ってもらう
async function plateCheck(run, side) {
  const w = run.world;
  const owner = run.owner;
  const has = w.hasFlagFn(owner);
  if (has(OPEN6)) return;
  const P = C7T_POS[6];
  const p = partyOf(w, run.init);
  const people = [...new Set([run.init, owner, ...(p ? p.members.map((id) => w.sessions.get(id)) : [])])].filter((m) => m?.inWorld);
  const at = (m, map, q) => m.map === map && Math.floor(m.x) === q.x && Math.floor(m.y) === q.y;
  const onA = people.some((m) => at(m, c7tMapId(6, true), P.plate1));
  const onB = people.some((m) => at(m, c7tMapId(6), P.plate2));
  const waiting = has(WAIT6);
  if (onA && (onB || waiting)) {
    await run.runSteps([
      ['sfx', 'rumble'], ['flag', OPEN6], ['unflag', WAIT6], ['sync'], ['shake'], ['flash'],
      ...N('ザアァ…！', '2つの時代の水の石から、同じ時に、水がふき上がった！', '近道の石のとびらが、今も、千年前も、開いた！'),
      ...(waiting && !onB ? S('カリム', 'やったね！\n（カリムは、砂時計の光にのって、すぐにもどってきた）') : []),
      ['objective', C7_OBJ.open6],
    ]);
    return;
  }
  if (side === 'a') {
    await run.runSteps(N('足もとの水の石が、ぼんやりと光った…。', '…しかし、何もおこらない。\n（千年前の、もう1つの水の石も、同じ時にふまれていれば…？）'));
    return;
  }
  const karim = (owner.char.guests || []).includes('karim');
  if (waiting) {
    await run.runSteps(S('カリム', 'ぼくは、ここで待っているよ。\n今の時代の水の石を、ふんで！'));
    return;
  }
  if (!karim) {
    await run.runSteps(N('足もとの水の石が、ぼんやりと光った…。', '（今の時代の水の石は、だれもふんでいないようだ…）'));
    return;
  }
  await run.runSteps([
    ...N('足もとの水の石が、ぼんやりと光った…。', '（今の時代の水の石は、だれもふんでいないようだ…）'),
    ...S('カリム', 'ぼくが、この石の上で待っていようか？\nその間に、今の時代の水の石をふんで！'),
    ['choice', 'カリムに待ってもらう？', ['たのむ', 'やめる'], [
      [['flag', WAIT6], ['sync'], ...S('カリム', 'まかせて！\n騎士は、待つのも仕事のうちさ。'), ...N('（カリムが、千年前の水の石の上で待っている。今の時代の水の石をふもう）')],
      [],
    ]],
  ]);
}
const plateScript = (side) => Object.assign(() => [['call', (run) => plateCheck(run, side)]], { sameMap: true });

