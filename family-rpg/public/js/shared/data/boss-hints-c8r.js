// 今の 段の ヒント（n … 何回目〈1〜3〉・flags … リーダーの しるし）。ない ときは null
export function c8rBossHint(id, n, flags = {}) {
  let list = C8R_BOSS_HINTS[id];
  if (id === 'c8_solitus') list = C8R_SOLITUS_HINTS[flags?.c8s_p3 ? 3 : flags?.c8s_p2 ? 2 : 1];
  if (!list) return null;
  return list[Math.max(0, Math.min(list.length - 1, (n || 1) - 1))];
}
