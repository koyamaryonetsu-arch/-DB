// 第5章 Step 5「ノクトの思い出の迷宮」の レイアウト（1文字 = 1マス。文字の いみは maps/memory.js の MEMORY_LEGEND）
// 6階。1つの 階が 1つの 思い出の 年（5さい・7さい・9さい・11さい・13さい・今）。下へ 下へ（> … 下の 階へ / < … 上の 階へ）
// #=思い出の かべ .=ゆか ~=思い出の とぎれた ところ（もや。歩けない）O=思い出の 柱（ランプの 光で 影が のびる）
// 1〜4=ランプ台（しらべると 星読みの ランプの 光を うつす。光る ランプ台は 1つの 階に 1つだけ）
// a〜d=影の 道（ランプ台 1〜4 が 光っている ときだけ 見える・歩ける）A〜D=ゆかに おちた 影（ランプ台 1〜4 が 光っている とき）
// S=思い出の かけら X=思い出の 出口（1階。星読みの 里へ）F=休み所の 星の いずみ（3階）
// 影の 道は、ランプ台から 見て 柱の うしろへ まっすぐ のびる（柱の 向こうがわに だけ できる）

function sheet(w, h) {
  const g = Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => (x === 0 || y === 0 || x === w - 1 || y === h - 1 ? '#' : '~')));
  const ok = (x, y) => x > 0 && y > 0 && x < w - 1 && y < h - 1;
  const api = {
    rect(x, y, rw, rh, ch = '.') { for (let j = y; j < y + rh; j++) for (let i = x; i < x + rw; i++) if (ok(i, j)) g[j][i] = ch; return api; },
    put(x, y, ch) { if (x >= 0 && y >= 0 && x < w && y < h) g[y][x] = ch; return api; },
    puts(list, ch) { for (const [x, y] of list) api.put(x, y, ch); return api; },
    // (x, y) から dx, dy の 向きへ n マス
    line(x, y, dx, dy, n, ch) { for (let i = 0; i < n; i++) api.put(x + dx * i, y + dy * i, ch); return api; },
    rows() { return g.map((r) => r.join('')); },
  };
  return api;
}
const W = 26, H = 18;

// 1階「5さい 星祭りの夜」: はじめての 影の 道。ランプ台1 → 柱の 影が 北へ のびて 下りかいだんの へやへ。
// ランプ台2 → 東へ のびて 思い出の かけらの へやへ（かけらを 取ると、その 影の 道は 消えなくなる）
