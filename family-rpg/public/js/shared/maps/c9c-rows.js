export const RIVER_W = 90, RIVER_H = 36;
// 文字: # 岩かべ / , 川岸 / = さんばし（いかだ乗り場）/ ^ > v < 川の 流れ / ~ ゆるい 所 / r 川の 中の 岩
function riverGrid() {
  const g = Array.from({ length: RIVER_H }, () => Array(RIVER_W).fill('#'));
  const rect = (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch; };
  // 川の はじめ（ヒカリゴケの里から 来た いかだが 着く）: さんばしと ゆるい 所
  rect(1, 16, 3, 20, ','); rect(2, 18, 4, 18, '=');
  rect(5, 16, 7, 20, '~');
  // 本流 1（東へ）→ ゆるい 所 1
  rect(8, 17, 19, 19, '>');
  rect(20, 15, 23, 21, '~');
  // わき道 1（南へ → 東へ → 小さな 岸 → 東へ → 北へ もどる）
  rect(21, 22, 22, 26, 'v'); rect(21, 27, 25, 28, '>');
  rect(26, 26, 29, 29, ',');
  rect(30, 27, 31, 28, '>'); rect(32, 20, 33, 28, '^');
  // 本流 2（東へ。まん中に 岩）
  rect(24, 17, 37, 19, '>');
  g[18][30] = 'r';
  // 南へ まがる → ゆるい 所 2
  rect(38, 17, 40, 26, 'v');
  rect(37, 27, 42, 30, '~');
  // わき道 2（南へ → 東へ → 小さな 岸 → 北へ もどる）
  rect(39, 31, 40, 32, 'v'); rect(39, 33, 50, 34, '>');
  rect(51, 32, 54, 34, ',');
  rect(55, 31, 56, 34, '^');
  // 本流 3（東へ。大きな 空どう … 頭の 上に さかさの 町）
  rect(43, 28, 62, 30, '>');
  g[29][52] = 'r';
  // 大きな 空どう（川の 北は 遠い やみ。歩けない）
  // 北へ まがる → ゆるい 所 3
  rect(63, 12, 65, 30, '^');
  rect(62, 8, 66, 11, '~');
  // わき道 3（北へ → 東へ → 小さな 岸 → 南へ もどる）
  rect(63, 4, 64, 7, '^'); rect(63, 2, 70, 3, '>');
  rect(71, 2, 74, 5, ',');
  rect(75, 4, 76, 7, 'v');
  // 本流 4（東へ。岩）→ 川の 終わりの ゆるい 所 → ピラミッドの 岸
  rect(67, 8, 80, 10, '>');
  g[9][70] = 'r';
  rect(81, 7, 83, 11, '~');
  rect(84, 4, 88, 14, ',');
  rect(84, 8, 84, 10, '=');
  return g;
}
