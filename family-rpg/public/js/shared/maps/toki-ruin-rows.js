export const RUIN_W = 34, RUIN_H = 26;

function floor(draw) {
  const g = Array.from({ length: RUIN_H }, (_, y) => Array.from({ length: RUIN_W }, (_, x) => (x === 0 || y === 0 || x === RUIN_W - 1 || y === RUIN_H - 1 ? '#' : '.')));
  const put = (x, y, ch) => { if (x >= 0 && y >= 0 && x < RUIN_W && y < RUIN_H) g[y][x] = ch; };
  const h = (y, x0, x1, ch) => { for (let x = x0; x <= x1; x++) put(x, y, ch); };
  const v = (x, y0, y1, ch) => { for (let y = y0; y <= y1; y++) put(x, y, ch); };
  const fill = (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) h(y, x0, x1, ch); };
  draw({ put, h, v, fill });
  return g.map((r) => r.join(''));
}
