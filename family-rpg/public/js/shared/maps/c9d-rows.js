// ・星のはかば c9d_grave（31×25）… 広くて しずか。魔物は 出ない。ねむる 星の 小さな くぼみ・古い 石の 文字・まん中に 魔人・おくに 大きな くぼみ
// 文字: # 岩かべ / . ゆか / ~ 深い 谷 / b n d D 光の 橋（echo2〜echo5）/ E ひびきの石（場所は POS の stones）/ L ランプ（左の 道の）/ R ランプ（右の 道の）/
//   m 光る こけ / c 宝箱 / S 階段 / X 出口 / F 回復の いずみ /
//   はかば: g 地面 / o 小さな くぼみ（ねむる 星）/ H 大きな くぼみ / r まわりの 岩 / T 古い 石の 文字

const grid = (w, h, ch = '#') => Array.from({ length: h }, () => Array(w).fill(ch));
const rectOf = (g) => (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch; };

// ───── ふたごの道 1階（31×40）─────
export const G1_W = 31, G1_H = 40;
function g1Grid() {
  const g = grid(G1_W, G1_H);
  const rect = rectOf(g);
  // 入口の 広間（左右の 道が つながる）
  rect(2, 33, 28, 37, '.');
  // 深い 谷（2つの 道の 間）
  rect(8, 3, 22, 32, '~');
  // 左の 道・右の 道
  rect(2, 3, 6, 32, '.');
  rect(24, 3, 28, 32, '.');
  // 道の 中の 岩（まっすぐに しない）
  rect(2, 28, 3, 29, '#'); rect(5, 24, 6, 25, '#'); rect(2, 12, 3, 13, '#'); rect(5, 8, 6, 8, '#');
  rect(27, 28, 28, 29, '#'); rect(24, 24, 25, 25, '#'); rect(27, 17, 28, 18, '#');
  // 道の とぎれた 所（光の 橋。左 … echo2・右 … echo3）
  rect(2, 18, 6, 19, 'b');
  rect(24, 10, 28, 11, 'n');
  // 光る こけ
  for (const [x, y] of [[4, 31], [3, 30], [5, 27], [4, 22], [6, 15], [3, 10], [4, 5], [26, 31], [25, 27], [27, 22], [26, 15], [25, 13], [27, 6]]) g[y][x] = 'm';
  // ランプ（谷の ふちの 岩に うめこむ）
  for (const y of [30, 22, 14, 6]) { g[y][7] = 'L'; g[y][23] = 'R'; }
  // 宝箱
  g[4][6] = 'c'; g[30][28] = 'c'; g[15][2] = 'c';
  // 2階への 階段（右の 道の いちばん おく）・ピラミッドの 岸への 出口
  g[4][26] = 'S';
  g[38][15] = 'X'; rect(14, 38, 14, 38, '#'); rect(16, 38, 16, 38, '#');
  return g;
}
export const G1_ROWS = g1Grid().map((r) => r.join(''));

// ───── ふたごの道 2階（31×34）─────
export const G2_W = 31, G2_H = 34;
function g2Grid() {
  const g = grid(G2_W, G2_H);
  const rect = rectOf(g);
  rect(2, 27, 28, 31, '.');
  rect(8, 3, 22, 26, '~');
  rect(2, 3, 6, 26, '.');
  rect(24, 3, 28, 26, '.');
  rect(2, 22, 3, 23, '#'); rect(5, 11, 6, 12, '#'); rect(27, 22, 28, 23, '#'); rect(24, 15, 25, 16, '#');
  // 左の 道の とぎれた 所（echo4）
  rect(2, 16, 6, 17, 'd');
  // 北の 出口の 台（谷の 上）と、そこへの 光の 橋（echo5 … こだま）
  rect(13, 1, 17, 5, '.');
  rect(7, 4, 12, 4, 'D'); rect(18, 4, 23, 4, 'D');
  g[0][15] = '#';
  g[1][15] = 'X';
  // 回復の いずみ（入口の 広間）
  g[28][5] = 'F';
  // 光る こけ
  for (const [x, y] of [[4, 25], [3, 19], [5, 14], [4, 9], [2, 4], [26, 25], [25, 19], [27, 13], [26, 9]]) g[y][x] = 'm';
  for (const y of [24, 18, 12, 6]) { g[y][7] = 'L'; g[y][23] = 'R'; }
  g[24][2] = 'c'; g[17][28] = 'c'; g[3][6] = 'c';
  // 1階への 階段
  g[31][15] = 'S';
  return g;
}
export const G2_ROWS = g2Grid().map((r) => r.join(''));

// ───── 星のはかば（31×25）─────
export const GRAVE_W = 31, GRAVE_H = 25;
function graveGrid() {
  const g = grid(GRAVE_W, GRAVE_H, 'r');
  const rect = rectOf(g);
  rect(2, 2, 28, 22, 'g');
  // かどを まるく
  for (const [x, y] of [[2, 2], [3, 2], [2, 3], [28, 2], [27, 2], [28, 3], [2, 22], [2, 21], [28, 22], [28, 21]]) g[y][x] = 'r';
  // いちばん 大きな くぼみ（おく）
  rect(13, 3, 17, 5, 'H');
  // ねむる 星の 小さな くぼみ（まん中と 道は あける）
  for (const [x, y] of [[5, 6], [9, 4], [21, 4], [25, 6], [4, 10], [8, 9], [22, 9], [26, 10], [5, 14], [9, 16], [21, 16], [25, 14],
    [4, 19], [8, 20], [22, 20], [26, 19], [11, 7], [19, 7]]) g[y][x] = 'o';
  // おくの 岩（少年が 立つ 高い 岩）
  rect(26, 2, 28, 3, 'r');
  // 古い 石の 文字（入口の そば）
  g[20][13] = 'T';
  // 宝箱
  g[3][4] = 'c'; g[21][27] = 'c';
  // 入口（ふたごの道 2階へ）
  g[23][15] = 'X';
  return g;
}
export const GRAVE_ROWS = graveGrid().map((r) => r.join(''));

