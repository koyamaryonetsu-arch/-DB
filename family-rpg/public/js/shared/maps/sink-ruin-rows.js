// 1階が いちばん 上。下の 階へ 下りて いく（> … 下の 階へ / < … 上の 階へ）
// #=古い 石の かべ .=石の ゆか p=かたむいた 柱 i=たいまつ !=石の 文字ばん o=つぼ k=本だな G=かべ画 O=出口（外へ）
// かたむく ゆか: /=かたむく ゆか（かたむきの石で 西 ⇔ 東）L=かたむきの石 R=岩（西に かたむいている 時）r=岩が ころがって くる ところ（東に かたむいた 時）
//               ~=水たまり（西に かたむいている 時）w=水が 流れて くる ところ（東に かたむいた 時）
// 重さの てんびん: a・b=てんびんの 皿 q=岩が ころがって くる 皿（3階）Z=てんびんの 柱 |=てんびんの とびら
// c=入りこんだ 雲（強い 魔物・よい 宝）H=たて穴（2階。縄ばしごを かけると 5階へ）h=まるめた 縄ばしご（5階）
// F=休み所の 星の いずみ T=守り星の かけらの 台 g=島の 根
// 第38回 A: どの 階も 東や 南・北に わき道・行き止まりの 宝の へや・見晴らしの よい 広間を たして 広くした。
//   前からの へや・しかけ・かいだんの 場所（ざひょう）は そのまま（マップの 東と 南を のばした）。
//   4階の 休み所の 東に 小さな 重さの てんびんの 宝物庫（しなくても 先へ 行ける）

function sheet(w, h, fill = '#') {
  const g = Array.from({ length: h }, () => Array(w).fill(fill));
  const ok = (x, y) => x >= 0 && y >= 0 && x < w && y < h;
  const api = {
    w, h,
    rect(x, y, rw, rh, ch = '.') { for (let j = y; j < y + rh; j++) for (let i = x; i < x + rw; i++) if (ok(i, j)) g[j][i] = ch; return api; },
    put(x, y, ch) { if (ok(x, y)) g[y][x] = ch; return api; },
    puts(list, ch) { for (const [x, y] of list) api.put(x, y, ch); return api; },
    rows() { return g.map((r) => r.join('')); },
  };
  return api;
}

