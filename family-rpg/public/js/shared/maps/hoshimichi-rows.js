export const HM_W = 40, HM_H = 30;

function floor(draw) {
  const g = Array.from({ length: HM_H }, (_, y) => Array.from({ length: HM_W }, (_, x) => (x === 0 || y === 0 || x === HM_W - 1 || y === HM_H - 1 ? '#' : '.')));
  const put = (x, y, ch) => { if (x >= 0 && y >= 0 && x < HM_W && y < HM_H) g[y][x] = ch; };
  const h = (y, x0, x1, ch) => { for (let x = x0; x <= x1; x++) put(x, y, ch); };
  const v = (x, y0, y1, ch) => { for (let y = y0; y <= y1; y++) put(x, y, ch); };
  const fill = (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) h(y, x0, x1, ch); };
  // 道（[x, y] の 点を たてと よこの 線で つなぐ）
  const path = (pts, ch) => {
    for (let i = 0; i < pts.length - 1; i++) {
      const [ax, ay] = pts[i], [bx, by] = pts[i + 1];
      if (ax === bx) v(ax, Math.min(ay, by), Math.max(ay, by), ch);
      else h(ay, Math.min(ax, bx), Math.max(ax, bx), ch);
    }
  };
  draw({ put, h, v, fill, path });
  return g.map((r) => r.join(''));
}
// どの 階にも ある かざり（柱・たいまつ）
const deco = (d, rows, xs = [5, 34]) => {
  for (const y of rows) for (const x of xs) d.put(x, y, 'O');
};

