// ウツボ: 水門の 石の すき間から ぬっと 出た 大きな ウツボ。黄色い 目・大きな 口。うしろの 水に もう 1ぴきの しっぽ。
//   コマ0 … 口を 少し 開けて じっと 見る / コマ1 … 体を くねらせて 大きく 口を 開ける
function gateEel(g0, f) {
  const g = fit(g0, 100);
  const C = EL;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 水門の 石（うしろ）
  g.rect(0.02, 0.32, 0.22, 0.64, C.S);
  g.rect(0.04, 0.34, 0.18, 0.6, C.SL);
  for (let i = 0; i < 4; i++) g.rect(0.02, 0.44 + i * 0.13, 0.22, 0.012, C.S);
  // 水
  g.ell(0.55, 0.9, 0.46, 0.09, C.WD);
  g.ell(0.55, 0.88, 0.43, 0.07, C.W);
  for (let i = 0; i < 6; i++) g.ell(0.18 + i * 0.13, 0.86 + (i % 2) * 0.02, 0.05, 0.012, C.WL);
  // 体（S字に くねる。たてに ならべた まる）
  const sw = f ? 0.05 : 0;
  const pts = [];
  for (let i = 0; i <= 14; i++) {
    const u = i / 14;
    pts.push([0.62 + Math.sin(u * 3.2 + 0.4) * (0.14 + sw) * (1 - u * 0.3), 0.88 - u * 0.62, 0.11 - u * 0.02]);
  }
  for (const [x, y, r] of pts) R(x, y, r + 0.01, C.BK);
  for (const [x, y, r] of pts) R(x, y, r, C.B);
  for (const [x, y, r] of pts) g.ell(x - r * 0.35, y, r * 0.35, r * 0.6 * k, C.BL);
  // せびれ
  for (let i = 2; i < 13; i += 2) {
    const [x, y, r] = pts[i];
    g.poly([[x + r * 0.8, y - 0.02], [x + r * 1.5, y - 0.04], [x + r * 0.9, y + 0.03]], C.BD);
  }
  // 頭
  const [hx, hy] = pts[14];
  const op = f ? 0.08 : 0.03;
  g.ell(hx - 0.06, hy - 0.02, 0.17, 0.09, C.BK);
  g.ell(hx - 0.06, hy - 0.03, 0.16, 0.08, C.B);
  g.ell(hx - 0.12, hy + 0.04 + op / 2, 0.12, 0.04 + op / 2, C.BD);
  // 口の 中と キバ
  g.ell(hx - 0.13, hy + 0.035, 0.1, 0.012 + op * 0.6, C.M);
  for (let i = 0; i < 5; i++) {
    const x = hx - 0.21 + i * 0.035;
    g.poly([[x, hy + 0.02], [x + 0.018, hy + 0.02], [x + 0.009, hy + 0.045]], C.T);
  }
  // 黄色い 目
  R(hx - 0.04, hy - 0.06, 0.035, C.YD);
  R(hx - 0.04, hy - 0.06, 0.028, C.Y);
  g.ell(hx - 0.045, hy - 0.06, 0.006, 0.02, C.BK);
  // うしろの 水に もう 1ぴきの しっぽ
  g.poly([[0.84, 0.86], [0.92, 0.7 - sw], [0.96, 0.74 - sw], [0.9, 0.88]], C.BD);
}

