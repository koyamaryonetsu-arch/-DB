  g.ell(0.5, 0.56 + up, 0.2, 0.1, C.WD);
  g.rect(0.3, 0.3 + up, 0.4, 0.27, C.W);
  // 頭（三角）
  g.poly([[0.24, 0.36 + up], [0.5, 0.02 + up], [0.76, 0.36 + up]], C.WD);
  g.poly([[0.27, 0.34 + up], [0.5, 0.05 + up], [0.73, 0.34 + up]], C.W);
  g.poly([[0.38, 0.22 + up], [0.5, 0.08 + up], [0.46, 0.24 + up]], C.WL);
