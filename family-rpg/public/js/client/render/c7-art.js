  g.rect(0.46, 0.06, 0.08, 0.56, C.WD);
  g.rect(0.47, 0.06, 0.05, 0.56, C.W);
  g.rect(0.48, 0.06, 0.02, 0.56, C.WL);
  // うで（えだ）
