// render/monsters.js の さいごで addRareArt(MONSTER_ART) を よぶ。かきかたは monsters.js と おなじ
// （g … monsters.js の かく ための どうぐ。w・h の わりあいで かく。f … 0 か 1 の コマ）
// field … フィールドの シンボル（ちいさい え）の 大きさ。ふつうの 魔物は 20。とくべつな 魔物なので すこし 大きく
// ふつうの 魔物より 大きく、かざり（かぶと・たて・つばさ・ひかり）を ていねいに かく

// 線の 太さを え の 大きさに あわせる（g.line の 太さは ドットの 数なので、フィールドの ちいさい え では 細く する）
function fit(g, base) {
  const k = g.w / base;
  const w = Object.create(g);
  w.line = (pts, c, lw = 1) => g.line(pts, c, Math.max(0.5, lw * k));
  return w;
}

