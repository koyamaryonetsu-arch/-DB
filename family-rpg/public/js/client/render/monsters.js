// かく ための べんりな かんすう（w,h は 0〜1 の わりあいで しめす）
function G(ctx, w, h) {
  const X = (v) => v * w, Y = (v) => v * h;
  return {
    ctx, w, h,
    ell(cx, cy, rx, ry, c, rot = 0) { ctx.fillStyle = c; ctx.beginPath(); ctx.ellipse(X(cx), Y(cy), Math.max(0.5, rx * w), Math.max(0.5, ry * h), rot, 0, Math.PI * 2); ctx.fill(); },
    poly(pts, c) { ctx.fillStyle = c; ctx.beginPath(); pts.forEach(([x, y], i) => (i ? ctx.lineTo(X(x), Y(y)) : ctx.moveTo(X(x), Y(y)))); ctx.closePath(); ctx.fill(); },
    rect(x, y, rw, rh, c) { ctx.fillStyle = c; ctx.fillRect(X(x), Y(y), rw * w, rh * h); },
    line(pts, c, lw = 1) { ctx.strokeStyle = c; ctx.lineWidth = lw; ctx.lineCap = 'round'; ctx.beginPath(); pts.forEach(([x, y], i) => (i ? ctx.lineTo(X(x), Y(y)) : ctx.moveTo(X(x), Y(y)))); ctx.stroke(); },
    // め（しろめ＋くろめ＋ひかり）
    eye(cx, cy, r, look = 0, white = '#ffffff', pupil = '#1a1026') {
      this.ell(cx, cy, r, r * 1.25 * (w / h), white);
      this.ell(cx + look * r * 0.3, cy + r * 0.15 * (w / h), r * 0.55, r * 0.75 * (w / h), pupil);
      this.ell(cx - r * 0.25, cy - r * 0.35 * (w / h), r * 0.2, r * 0.25 * (w / h), '#ffffff');
    },
    dot(x, y, c) { ctx.fillStyle = c; ctx.fillRect(Math.round(X(x)), Math.round(Y(y)), 1, 1); },
  };
}

function jelly(g, f, c, cD, cL, extra) {
  const sq = f ? 0.04 : 0;
  g.ell(0.5, 0.64 + sq / 2, 0.44 + sq, 0.34 - sq, cD);
  g.ell(0.5, 0.6 + sq / 2, 0.42 + sq, 0.33 - sq, c);
  g.poly([[0.38, 0.35 + sq], [0.5, 0.1 + sq * 2], [0.62, 0.35 + sq]], c);
  g.ell(0.34, 0.47 + sq, 0.1, 0.06, cL);
  g.ell(0.27, 0.56 + sq, 0.04, 0.05, cL);
  g.eye(0.38, 0.6 + sq, 0.075, 0.3);
  g.eye(0.62, 0.6 + sq, 0.075, 0.3);
  g.poly([[0.43, 0.75 + sq], [0.57, 0.75 + sq], [0.5, 0.83 + sq]], '#6a1a2a');
  g.ell(0.5, 0.8 + sq, 0.035, 0.025, '#ff8aa0');
  if (extra) extra(sq);
}

