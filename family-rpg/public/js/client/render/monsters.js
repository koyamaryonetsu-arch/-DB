const cache = new Map();

// たたかい用の え（scale=ドットの おおきさ）
export function monsterCanvas(sp, frame = 0, small = false) {
  const key = `${sp}:${frame}:${small ? 1 : 0}`;
  let c = cache.get(key);
  if (c) return c;
  const def = MONSTER_ART[sp] || MONSTER_ART.pururin;
  let [w, h] = def.size;
  if (small) {
    // フィールド用の ちいさい え
    const k = Math.min(1, 20 / Math.max(w, h));
    w = Math.max(10, Math.round(w * k));
    h = Math.max(10, Math.round(h * k));
  }
  c = makeCanvas(w + 2, h + 2);
  const ctx = ctxOf(c);
  ctx.translate(1, 1);
  def.draw(G(ctx, w, h), frame);
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  pixelize(c, { palette: def.pal.concat(['#000000']), outline: '#130d24' });
  cache.set(key, c);
  return c;
}

export function monsterSize(sp) {
  const def = MONSTER_ART[sp] || MONSTER_ART.pururin;
  return def.size;
}

// フィールドの おおきな NPC（ボスの すがた など）
export function bigNpcCanvas(kind, frame = 0) {
  if (kind === 'treant') return monsterCanvas('dark_treant', frame);
  if (kind === 'treant_calm') {
    const key = `calm:${frame}`;
    if (cache.has(key)) return cache.get(key);
    const src = monsterCanvas('dark_treant', frame);
    const c = makeCanvas(src.width, src.height);
    const x = ctxOf(c);
    x.filter = 'hue-rotate(60deg) saturate(1.3) brightness(1.15)';
    x.drawImage(src, 0, 0);
    cache.set(key, c);
    return c;
  }
  if (kind === 'goldoon_sleep') {
    const key = `gsleep:${frame}`;
    if (cache.has(key)) return cache.get(key);
    const src = monsterCanvas('goldoon', 0);
    const c = makeCanvas(src.width, src.height);
    const x = ctxOf(c);
    x.filter = 'grayscale(0.7) brightness(0.8)';
    x.drawImage(src, 0, 0);
    cache.set(key, c);
    return c;
  }
  return null;
}
