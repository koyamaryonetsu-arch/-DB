function hoshimori(g0, f) {
  const g = fit(g0, 224);
  const C = HM;
  const k = g.w / g.h;
  const nod = f >= 2;
  const up = f % 2;
  const dy = nod ? 0.04 + up * 0.01 : 0;
  // 台座
  g.rect(0.18, 0.86, 0.64, 0.12, C.SD);
  g.rect(0.2, 0.86, 0.6, 0.04, C.SL);
  for (const x of [0.26, 0.5, 0.74]) g.ell(x, 0.93, 0.025, 0.02, C.M);
  // はね（体の 横）
  for (const d of [-1, 1]) {
    const lift = nod ? -0.02 : up ? 0.02 : 0;
    g.poly([[0.5 + d * 0.2, 0.42], [0.5 + d * 0.42, 0.5 - lift], [0.5 + d * 0.4, 0.8], [0.5 + d * 0.22, 0.84]], C.SD);
    g.poly([[0.5 + d * 0.22, 0.46], [0.5 + d * 0.38, 0.53 - lift], [0.5 + d * 0.36, 0.78], [0.5 + d * 0.23, 0.8]], C.S);
    for (let i = 0; i < 3; i++) g.line([[0.5 + d * 0.25, 0.58 + i * 0.07], [0.5 + d * 0.36, 0.6 + i * 0.07 - lift]], C.SD, 2);
  }
  // 体
  g.ell(0.5, 0.64, 0.24, 0.24, C.SD);
  g.ell(0.5, 0.62, 0.22, 0.23, C.S);
  g.ell(0.5, 0.68, 0.15, 0.16, C.SL);
  // むねの もよう（うろこの 形）
  for (let r = 0; r < 3; r++) for (let i = -1; i <= 1; i++) g.line(bez([[0.5 + i * 0.07 - 0.03, 0.62 + r * 0.06], [0.5 + i * 0.07, 0.65 + r * 0.06], [0.5 + i * 0.07 + 0.03, 0.62 + r * 0.06]], 4), C.S, 1.2);
  // むねの 星の しるし（光る）
  spark(g, 0.5, 0.56, 0.06, up ? C.TL : C.T, '#ffffff');
  // こけ
  g.ell(0.34, 0.76, 0.05, 0.025, C.M);
  g.ell(0.66, 0.48, 0.04, 0.02, C.ML);
  // 足
  for (const d of [-1, 1]) for (let i = -1; i <= 1; i++) g.ell(0.5 + d * 0.1 + i * 0.025, 0.86, 0.015, 0.02, C.B);
  // 頭（うなずく ときは 少し 下へ・前へ）
  const hy = 0.28 + dy;
  g.ell(0.5, hy, 0.24, 0.18, C.SD);
  g.ell(0.5, hy - 0.01, 0.22, 0.17, C.S);
  // 耳の はね
  g.poly([[0.28, hy - 0.08], [0.3, hy - 0.24], [0.4, hy - 0.12]], C.SD);
  g.poly([[0.72, hy - 0.08], [0.7, hy - 0.24], [0.6, hy - 0.12]], C.SD);
  g.poly([[0.3, hy - 0.09], [0.315, hy - 0.2], [0.38, hy - 0.12]], C.S);
  g.poly([[0.7, hy - 0.09], [0.685, hy - 0.2], [0.62, hy - 0.12]], C.S);
  // 顔の まる
  for (const d of [-1, 1]) g.ell(0.5 + d * 0.095, hy, 0.09, 0.09 * k, C.SX);
  // 目（ためし … 大きく ひらいた 金色 / うなずく … やさしく とじる）
  for (const d of [-1, 1]) {
    const x = 0.5 + d * 0.095;
    if (nod) {
      g.line(bez([[x - 0.05, hy], [x, hy + 0.025], [x + 0.05, hy]], 6), C.K, 3);
      continue;
    }
    g.ell(x, hy, 0.065, 0.065 * k, C.ED);
    g.ell(x, hy, 0.055, 0.055 * k, C.E);
    g.ell(x + 0.005, hy + 0.005, 0.025, 0.03 * k, C.K);
    g.ell(x - 0.02, hy - 0.02, 0.012, 0.012 * k, C.EL);
  }
  g.poly([[0.475, hy + 0.06], [0.525, hy + 0.06], [0.5, hy + 0.11]], C.B);
  // 夜明けの 光（うなずく ときの コマ1）
  if (nod && up) for (const [x, y] of [[0.14, 0.14], [0.86, 0.18], [0.1, 0.5], [0.9, 0.46]]) spark(g, x, y, 0.035, C.EL, '#ffffff');
  // 足もとの 小さな ともしび（ためしの しるし）
  if (!nod) {
    g.rect(0.47, 0.98 - 0.06, 0.06, 0.04, C.SD);
    g.ell(0.5, 0.9, 0.015, 0.03, C.L);
  }
}

