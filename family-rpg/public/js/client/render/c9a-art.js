function face(g, x, y, s, skin, smile = true) {
  const k = g.w / g.h;
  g.ell(x, y, s, s * k, skin);
  g.ell(x - s * 0.38, y - s * 0.1 * k, s * 0.14, s * 0.18 * k, ST.K);
  g.ell(x + s * 0.38, y - s * 0.1 * k, s * 0.14, s * 0.18 * k, ST.K);
  if (smile) g.line([[x - s * 0.35, y + s * 0.35 * k], [x, y + s * 0.55 * k], [x + s * 0.35, y + s * 0.35 * k]], ST.K, 1.6);
  else g.ell(x, y + s * 0.45 * k, s * 0.18, s * 0.14 * k, ST.R);
}
function suitoru(g0, f) {
  const g = fit(g0, 248);
  const C = ST;
  const up = f % 2 ? 1 : 0;
  const k = g.w / g.h;
  const b = up ? 0.008 : 0;
  // ホース（右へ のびて、となりの すいこみ口に つながる）
  g.line(bez([[0.72, 0.6], [0.88, 0.56 + b * 2], [0.94, 0.74], [1.0, 0.78]], 14), C.HD, 16);
  g.line(bez([[0.72, 0.6], [0.88, 0.56 + b * 2], [0.94, 0.74], [1.0, 0.78]], 14), C.H, 11);
  for (let i = 1; i < 6; i++) {
    const t = i / 6;
    const x = 0.72 + t * 0.28, y = 0.6 + Math.sin(t * Math.PI) * -0.04 + t * 0.18;
    g.ell(x, y, 0.012, 0.03, C.HL);
  }
  // 車（4つ）
  for (const x of [0.18, 0.38, 0.58]) {
    g.ell(x, 0.9, 0.08, 0.08 * k, C.W);
    g.ell(x, 0.9, 0.04, 0.04 * k, C.WL);
    g.ell(x, 0.9, 0.012, 0.012 * k, C.ML);
  }
  // 体（そうじきの まるい タンク）
  g.ell(0.4, 0.66 + b, 0.36, 0.22, C.PD);
  g.ell(0.4, 0.64 + b, 0.34, 0.2, C.P);
  g.ell(0.32, 0.56 + b, 0.18, 0.06, C.PL);
  // 黄色い すじ と 星の しるし
  g.rect(0.06, 0.7 + b, 0.68, 0.035, C.Y);
  g.ell(0.4, 0.66 + b, 0.08, 0.08 * k, C.YD);
  spark(g, 0.4, 0.66 + b, 0.07, C.Y, '#ffffff');
  // 前の すいこみ口の つけね
  g.ell(0.74, 0.62 + b, 0.05, 0.08, C.MD);
  g.ell(0.74, 0.62 + b, 0.035, 0.06, C.M);
  // うしろの けむり出し
  g.rect(0.04, 0.4 + b, 0.06, 0.18, C.MD);
  g.rect(0.05, 0.4 + b, 0.04, 0.18, C.M);
  g.ell(0.07, 0.4 + b, 0.04, 0.02, C.ML);
  if (up) for (const [x, y, r] of [[0.06, 0.32, 0.03], [0.1, 0.24, 0.04], [0.05, 0.15, 0.035]]) g.ell(x, y, r, r * k, '#d8d8e0');
  // 上の まど（3人組が 乗る ところ）
  g.ell(0.42, 0.44 + b, 0.26, 0.04, C.MD);
  g.poly([[0.18, 0.44 + b], [0.22, 0.22 + b], [0.62, 0.22 + b], [0.66, 0.44 + b]], C.G);
  // 3人組
  const r = up ? -0.01 : 0.01;
  // ズラッカ（左。大きい・はちまき・力こぶ）
  g.ell(0.27, 0.36 + b, 0.07, 0.08, C.ZB);
  face(g, 0.27, 0.26 + b + r, 0.055, C.ZS, true);
  g.rect(0.215, 0.2 + b + r, 0.11, 0.018, C.ZB);
  g.ell(0.27, 0.19 + b + r, 0.055, 0.025, C.ZH);
  g.ell(0.19, 0.32 + b, 0.035, 0.04, C.ZS);
  // キラジョ（まん中。ピンクの 長い かみ・ティアラ・リボン）
  g.ell(0.42, 0.25 + b - r, 0.075, 0.1, C.KH);
  g.ell(0.42, 0.37 + b, 0.06, 0.07, C.KR);
  face(g, 0.42, 0.24 + b - r, 0.05, C.KS, false);
  g.poly([[0.38, 0.15 + b - r], [0.4, 0.11 + b - r], [0.42, 0.14 + b - r], [0.44, 0.11 + b - r], [0.46, 0.15 + b - r]], C.KG);
  g.ell(0.49, 0.18 + b - r, 0.025, 0.018, C.KR);
  g.ell(0.52, 0.18 + b - r, 0.025, 0.018, C.KR);
  // ボヤッチ（右。ゴーグル・スパナ）
  g.ell(0.56, 0.36 + b, 0.05, 0.07, C.BH);
  face(g, 0.56, 0.26 + b + r, 0.048, C.BS, true);
  g.ell(0.545, 0.245 + b + r, 0.02, 0.02 * k, C.BG);
  g.ell(0.585, 0.245 + b + r, 0.02, 0.02 * k, C.BG);
  g.line([[0.53, 0.245 + b + r], [0.6, 0.245 + b + r]], C.BO, 1.2);
  g.line([[0.6, 0.34 + b], [0.66, 0.24 + b - r * 2]], C.ML, 3);
  g.ell(0.665, 0.23 + b - r * 2, 0.018, 0.018 * k, C.ML);
  // まどの 光
  g.line([[0.24, 0.26 + b], [0.28, 0.4 + b]], C.GL, 1.6);
  // 頭の 上の アンテナと 赤い ボタン（ポチッとね）
  g.line([[0.42, 0.22 + b], [0.42, 0.07]], C.MD, 2);
  g.ell(0.42, 0.06, 0.025, 0.025 * k, up ? '#ff3a4a' : C.R);
}

