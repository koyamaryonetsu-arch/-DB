  g.ell(0.5, 0.62 + b, 0.27, 0.25, D);
  g.ell(0.5, 0.61 + b, 0.26, 0.24, W);
  for (const [x, y] of [[0.42, 0.56], [0.58, 0.56], [0.5, 0.66], [0.4, 0.72], [0.6, 0.72]]) g.line([[x - 0.03, y + b], [x, y + 0.04 + b], [x + 0.03, y + b]], M, 0.9);
