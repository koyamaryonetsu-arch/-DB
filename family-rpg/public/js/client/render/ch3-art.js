  g.ell(0.5, 0.645 + sq / 2, 0.42 + sq, 0.3 - sq, B);
  g.poly([[0.36, 0.42 + sq], [0.5, 0.3 + sq * 1.4], [0.64, 0.42 + sq]], B);
  // ひかり
  g.ell(0.25, 0.5 + sq, 0.06, 0.045, L);
  g.ell(0.19, 0.58 + sq, 0.025, 0.035, L);
  // あたまの ゆき（こんもり）
