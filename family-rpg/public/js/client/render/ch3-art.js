  g.ell(0.5, y + 0.01, 0.21, 0.07, L);
  g.ell(0.4, y - 0.04, 0.1, 0.07, L);
  g.ell(0.58, y - 0.06, 0.11, 0.08, L);
  g.ell(0.49, y - 0.12, 0.075, 0.065, L);
  g.ell(0.53, y - 0.17, 0.03, 0.03, L);
  g.ell(0.63, y - 0.02, 0.07, 0.03, S);
  g.ell(0.36, y + 0.015, 0.06, 0.025, S);
  g.ell(0.5, y - 0.04, 0.05, 0.02, S);
  // め・ほっぺ・くち
