// かぶとの すき間から ゆうれいの 光。コマ1で 剣を もっと 上げて、目の 光が つよく なる
function castleArmor(g0, f) {
  const g = fit(g0, 44);
  const C = ARMOR;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const lift = f ? -0.035 : 0;
  // かげ
  g.ell(0.5, 0.965, 0.34, 0.028, C.ADD);
  // マント（うしろ。すそが ぎざぎざ）
  g.poly([[0.3, 0.3], [0.7, 0.3], [0.78, 0.86], [0.7, 0.82], [0.64, 0.9], [0.56, 0.84], [0.48, 0.92], [0.4, 0.84], [0.32, 0.9], [0.24, 0.84]], C.RD);
  g.poly([[0.33, 0.32], [0.67, 0.32], [0.72, 0.8], [0.62, 0.77], [0.52, 0.82], [0.42, 0.77], [0.3, 0.8]], C.R);
  // あし（すね当てと くつ）
  for (const x of [0.4, 0.6]) {
    g.poly([[x - 0.07, 0.66], [x + 0.07, 0.66], [x + 0.06, 0.9], [x - 0.06, 0.9]], C.AD);
    g.poly([[x - 0.055, 0.67], [x + 0.055, 0.67], [x + 0.045, 0.88], [x - 0.045, 0.88]], C.A);
    g.line([[x - 0.03, 0.7], [x - 0.03, 0.85]], C.AL, 1);
    g.ell(x, 0.925, 0.085, 0.032, C.ADD);
    g.ell(x - 0.01, 0.915, 0.07, 0.022, C.AD);
  }
  // こしの よろい
  g.poly([[0.3, 0.56], [0.7, 0.56], [0.72, 0.68], [0.28, 0.68]], C.AD);
  g.poly([[0.32, 0.57], [0.68, 0.57], [0.69, 0.66], [0.31, 0.66]], C.A);
  g.line([[0.32, 0.6], [0.68, 0.6]], C.G, 1.4);
  // どう（むね）
  g.poly([[0.28, 0.3], [0.72, 0.3], [0.7, 0.58], [0.3, 0.58]], C.ADD);
  g.poly([[0.3, 0.31], [0.7, 0.31], [0.68, 0.56], [0.32, 0.56]], C.A);
  g.poly([[0.33, 0.33], [0.49, 0.33], [0.49, 0.54], [0.35, 0.54]], C.AL);
  g.line([[0.5, 0.32], [0.5, 0.56]], C.AD, 1.4);
  g.line([[0.3, 0.315], [0.7, 0.315]], C.G, 1.6);
  g.line([[0.36, 0.36], [0.4, 0.5]], C.AH, 1);
  // こびりついた 砂
  R(0.6, 0.5, 0.03, C.S);
  R(0.38, 0.63, 0.02, C.SD);
  R(0.62, 0.62, 0.016, C.S);
  // かた
  for (const s of [-1, 1]) {
    const x = 0.5 + s * 0.24;
    R(x, 0.31, 0.09, C.AD);
    R(x - s * 0.005, 0.3, 0.075, C.A);
    g.line([[x - 0.05, 0.27], [x + 0.03, 0.26]], C.AH, 1);
  }
  // 剣（みぎ手で ふり上げる）
  const hx = 0.8, hy = 0.5 + lift;
  g.poly([[hx - 0.02, hy], [hx + 0.02, hy], [hx + 0.03, 0.09 + lift], [hx, 0.045 + lift], [hx - 0.03, 0.09 + lift]], C.SWD);
  g.poly([[hx - 0.011, hy - 0.02], [hx + 0.011, hy - 0.02], [hx + 0.017, 0.1 + lift], [hx, 0.07 + lift], [hx - 0.017, 0.1 + lift]], C.SW);
  g.rect(hx - 0.08, hy - 0.02, 0.16, 0.03, C.G);
  g.rect(hx - 0.07, hy - 0.016, 0.06, 0.012, C.GL);
  R(hx, hy + 0.035, 0.04, C.AD);
  R(hx - 0.006, hy + 0.03, 0.028, C.A);
  // たて（ひだり手。まるい 青銅の たて）
  R(0.2, 0.52, 0.15, C.ADD);
  R(0.2, 0.515, 0.135, C.G);
  R(0.2, 0.515, 0.1, C.AD);
  R(0.2, 0.515, 0.085, C.G);
  R(0.2, 0.515, 0.035, C.GL);
  g.line([[0.12, 0.44], [0.16, 0.41]], C.GL, 1.2);
  // かぶと（赤い とさか）
  g.poly([[0.45, 0.1], [0.47, 0.035], [0.55, 0.025], [0.58, 0.1]], C.RD);
  g.poly([[0.47, 0.1], [0.49, 0.05], [0.54, 0.045], [0.56, 0.1]], C.R);
  g.poly([[0.38, 0.08], [0.62, 0.08], [0.66, 0.2], [0.62, 0.3], [0.38, 0.3], [0.34, 0.2]], C.ADD);
  g.poly([[0.4, 0.09], [0.6, 0.09], [0.63, 0.2], [0.6, 0.28], [0.4, 0.28], [0.37, 0.2]], C.A);
  g.line([[0.41, 0.11], [0.43, 0.26]], C.AH, 1.2);
  g.line([[0.4, 0.09], [0.6, 0.09]], C.G, 1.2);
  // 目の すき間（ゆうれいの 光）
  g.rect(0.39, 0.17, 0.22, 0.045, C.V);
  for (const x of [0.45, 0.55]) {
    g.ell(x, 0.192, f ? 0.032 : 0.022, f ? 0.014 : 0.011, C.E);
    g.ell(x, 0.192, 0.01, 0.006, C.EL);
  }
  // ゆうれいの 光の つぶ
  const motes = f ? [[0.3, 0.12], [0.72, 0.22], [0.26, 0.7]] : [[0.32, 0.18], [0.7, 0.14], [0.74, 0.7]];
  for (const [x, y] of motes) R(x, y, 0.012, C.E);
}

