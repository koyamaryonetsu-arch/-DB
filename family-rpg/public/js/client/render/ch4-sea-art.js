  // ── 手前の 砂の 波と しぶき ──
  g.poly([[0, 0.86], [0.1, 0.82], [0.2, 0.85], [0.32, 0.81], [0.46, 0.86], [0.58, 0.82], [0.72, 0.86], [0.86, 0.83], [1, 0.86], [1, 1], [0, 1]], C.SD);
