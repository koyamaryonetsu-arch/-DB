// ───── 砂ザメ ─────
const SHARK = {
  B: '#8e8470', BL: '#b2a68a', BD: '#5c5444', BDD: '#3a3428', // せなか（砂に まぎれる 色と しま）
  W: '#ece0c4', WD: '#c8b894', // おなか
  M: '#4a1420', MR: '#b23a42', T: '#f8f4ea', // 口の 中・歯
  EY: '#f2d860', P: '#1a1026', H: '#ffffff', // 目
  S: '#d8b070', SL: '#f2d49a', SD: '#a07a44', // 砂
};
// 砂ザメ: 砂の 中から 弓なりに とび出した サメ（右むき）。せびれ・左の 砂から つき出る おびれ・大きく 開けた 口と 歯。
// コマ1で 高く とび上がって、口を もっと 開ける
function sandShark(g0, f) {
  const g = fit(g0, 50);
  const C = SHARK;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? -0.05 : 0;
  // 砂の 山（からだの 下）
  g.ell(0.46, 0.93, 0.44, 0.055, C.SD);
  g.ell(0.45, 0.915, 0.38, 0.04, C.S);
  g.ell(0.36, 0.905, 0.15, 0.016, C.SL);
  // おびれ（左の 砂から つき出る）
  g.poly([[0.17, 0.86], [0.05, 0.62 + up * 0.5], [0.12, 0.65 + up * 0.5], [0.21, 0.74], [0.11, 0.9]], C.BDD);
  g.poly([[0.17, 0.83], [0.07, 0.65 + up * 0.5], [0.12, 0.68 + up * 0.5], [0.19, 0.75]], C.BD);
  // からだ（せぼねの 線に そって、頭の ほうが ふとい）
  const sp = bez([[0.16, 0.8], [0.27, 0.54 + up], [0.55, 0.38 + up], [0.8, 0.47 + up]], 16);
  taper(g, sp, 0.14, 0.3, C.BDD);
  taper(g, sp, 0.11, 0.27, C.B);
  // おなか（下がわ）
  taper(g, sp.slice(4).map(([x, y]) => [x + 0.01, y + 0.06]), 0.06, 0.15, C.WD);
  taper(g, sp.slice(5).map(([x, y]) => [x + 0.012, y + 0.07]), 0.04, 0.11, C.W);
  // せなかの しま と 明るい ふち
  for (const i of [6, 9, 12]) {
    const [x, y] = sp[i];
    g.line([[x - 0.02, y - 0.06], [x + 0.012, y - 0.015]], C.BD, 1.6);
  }
  g.line(sp.slice(3, 13).map(([x, y]) => [x, y - 0.065]), C.BL, 1.2);
  // せびれ（三角）
  const [dx, dy] = sp[8];
  g.poly([[dx - 0.08, dy - 0.06], [dx - 0.02, dy - 0.31], [dx + 0.06, dy - 0.07]], C.BDD);
  g.poly([[dx - 0.06, dy - 0.065], [dx - 0.02, dy - 0.27], [dx + 0.04, dy - 0.075]], C.BD);
  g.line([[dx - 0.045, dy - 0.08], [dx - 0.022, dy - 0.23]], C.BL, 1);
  // むなびれ
  const [qx, qy] = sp[11];
  g.poly([[qx - 0.04, qy + 0.07], [qx - 0.13, qy + 0.2], [qx + 0.03, qy + 0.11]], C.BD);
  // 頭（口を 大きく 開ける）
  const [hx, hy] = sp[16];
  const open = f ? 0.05 : 0.03;
  g.poly([[hx - 0.16, hy - 0.12], [hx + 0.1, hy - 0.08], [hx + 0.16, hy - 0.02], [hx - 0.04, hy + 0.0], [hx - 0.16, hy + 0.04]], C.BDD);
  g.poly([[hx - 0.15, hy - 0.11], [hx + 0.09, hy - 0.07], [hx + 0.14, hy - 0.025], [hx - 0.04, hy - 0.008], [hx - 0.15, hy + 0.03]], C.B);
  g.line([[hx - 0.12, hy - 0.1], [hx + 0.06, hy - 0.07]], C.BL, 1);
  g.poly([[hx - 0.06, hy - 0.01], [hx + 0.14, hy - 0.02], [hx + 0.12, hy + open + 0.06], [hx - 0.04, hy + open + 0.04]], C.M);
  g.ell(hx + 0.02, hy + open * 0.5 + 0.025, 0.05, 0.025, C.MR);
  g.poly([[hx - 0.12, hy + open + 0.035], [hx + 0.13, hy + open + 0.055], [hx + 0.06, hy + open + 0.11], [hx - 0.12, hy + open + 0.1]], C.WD);
  for (let i = 0; i < 5; i++) {
    const x = hx - 0.04 + i * 0.034;
    g.poly([[x, hy - 0.012], [x + 0.02, hy - 0.014], [x + 0.009, hy + 0.03]], C.T);
  }
  for (let i = 0; i < 4; i++) {
    const x = hx - 0.02 + i * 0.034;
    g.poly([[x, hy + open + 0.05], [x + 0.02, hy + open + 0.052], [x + 0.01, hy + open + 0.018]], C.T);
  }
  // 目（黄色く 光る）
  g.eye(hx - 0.07, hy - 0.06, 0.03, 0.4, C.EY, C.P);
  // とびちる 砂
  const dust = f ? [[0.3, 0.73], [0.62, 0.78], [0.84, 0.76], [0.22, 0.68], [0.5, 0.7]] : [[0.28, 0.8], [0.6, 0.84], [0.84, 0.84], [0.24, 0.76], [0.48, 0.78]];
  dust.forEach(([x, y], i) => R(x, y, i % 2 ? 0.012 : 0.018, i % 2 ? C.SL : C.S));
}

