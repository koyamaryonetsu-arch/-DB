// 第2部 第6章 Step 5（B）「止まった時計塔」の 魔物と、カリヨンの え（shared/data/monsters-tokei.js）
// render/monsters.js が addTokeiArt を よぶ。かきかたは ch6-road-art.js と おなじ（g … w・h の わりあいで かく。f … 0 か 1 の コマ）
// 新しい 絵は 3しゅ ＋ カリヨン（のこりは 時のいせきの 魔物の 色ちがい。variants.js の 'clock'）
// カリヨンは 台本の showMon でも 大きく 見える 大きさ（104×116）
import { fit } from './ch3-draw.js';

// ───── ころがり歯車 ─────
const COG = {
  B: '#c8963a', BL: '#f0d080', BD: '#7a5a2a', // 真ちゅう
  I: '#5a5e6a', // 鉄の ボルト
  W: '#ffffff', E: '#1a1010', M: '#8a2a2a', // 目・口
  D: '#d8c8a8', // 土けむり
};
// ころがり歯車: 顔の ある 大きな 歯車（正面）。コマ1で 歯が 回り、目を つりあげ、土けむり
function cogRoller(g0, f) {
  const g = fit(g0, 52);
  const C = COG;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 歯（10まい。コマで 半分 回る）
  for (let i = 0; i < 10; i++) {
    const a = (i / 10) * Math.PI * 2 + (f ? Math.PI / 10 : 0);
    const p = (r, d) => [0.5 + Math.cos(a + d) * r, 0.5 + Math.sin(a + d) * r * k];
    g.poly([p(0.34, -0.17), p(0.46, -0.11), p(0.46, 0.11), p(0.34, 0.17)], i % 2 ? C.BD : C.B);
  }
  // 体
  R(0.5, 0.5, 0.37, C.BD);
  R(0.5, 0.5, 0.34, C.B);
  R(0.5, 0.5, 0.25, C.BL);
  R(0.5, 0.5, 0.22, C.B);
  // ボルト（4つ）
  for (let i = 0; i < 4; i++) {
    const a = (i / 4) * Math.PI * 2 + Math.PI / 4 + (f ? 0.3 : 0);
    R(0.5 + Math.cos(a) * 0.29, 0.5 + Math.sin(a) * 0.29 * k, 0.025, C.I);
  }
  // 目（コマ1で つりあがる）
  for (const s of [-1, 1]) {
    R(0.5 + s * 0.09, 0.45, 0.06, C.W);
    R(0.5 + s * 0.08 - (f ? 0.02 : 0), 0.46, 0.03, C.E);
    g.line([[0.5 + s * 0.15, f ? 0.34 : 0.37], [0.5 + s * 0.04, f ? 0.39 : 0.37]], C.E, 1.4);
  }
  // 口（ぎざぎざ）
  g.poly([[0.4, 0.58], [0.6, 0.58], [0.56, f ? 0.66 : 0.63], [0.44, f ? 0.66 : 0.63]], C.M);
  for (let i = 0; i < 4; i++) g.rect(0.42 + i * 0.045, 0.58, 0.03, 0.025, C.W);
  // 土けむり（コマ1）
  if (f) for (const [x, y, r] of [[0.1, 0.9, 0.06], [0.2, 0.94, 0.05], [0.86, 0.92, 0.05]]) R(x, y, r, C.D);
  else R(0.5, 0.95, 0.03, C.D);
}

// ───── びっくりばねばこ ─────
const BOX = {
  R: '#d83a3a', RD: '#8a1e1e', Y: '#f8d040', // 箱
  S: '#b8bcc8', // ばね
  K: '#fbe0c8', W: '#ffffff', E: '#1a1010', // 顔
  H: '#3a6ad8', // ぼうし
};
// びっくりばねばこ: 赤と きいろの 箱から、ばねの 先の ピエロが とび出す（正面）。コマ1で ばねが のびて、うでを 広げる
function springBox(g0, f) {
  const g = fit(g0, 48);
  const C = BOX;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 箱（しまもよう）
  g.rect(0.14, 0.62, 0.72, 0.34, C.RD);
  for (let i = 0; i < 4; i++) g.rect(0.16 + i * 0.175, 0.64, 0.085, 0.3, C.R);
  for (let i = 0; i < 4; i++) g.rect(0.245 + i * 0.175, 0.64, 0.09, 0.3, C.Y);
  // ふた（ひらいている）
  g.poly([[0.14, 0.62], [0.04, f ? 0.4 : 0.46], [0.1, f ? 0.38 : 0.44], [0.24, 0.6]], C.R);
  // ばね（ぎざぎざ。コマ1で のびる）
  const top = f ? 0.4 : 0.5;
  const pts = [];
  for (let i = 0; i <= 6; i++) pts.push([0.5 + (i % 2 ? 0.07 : -0.07), 0.62 - ((0.62 - top) * i) / 6]);
  g.line(pts, C.S, 1.8);
  // うで（コマ1で 広げる）
  const hy = top + 0.04;
  g.line([[0.44, hy], [f ? 0.2 : 0.32, f ? hy - 0.12 : hy + 0.06]], C.H, 2);
  g.line([[0.56, hy], [f ? 0.8 : 0.68, f ? hy - 0.12 : hy + 0.06]], C.H, 2);
  R(f ? 0.19 : 0.31, f ? hy - 0.13 : hy + 0.07, 0.04, C.W);
  R(f ? 0.81 : 0.69, f ? hy - 0.13 : hy + 0.07, 0.04, C.W);
  // えり
  g.poly([[0.38, top + 0.02], [0.62, top + 0.02], [0.5, top + 0.09]], C.Y);
  // 顔
  const fy = top - 0.1;
  R(0.5, fy, 0.14, C.K);
  for (const s of [-1, 1]) {
    R(0.5 + s * 0.055, fy - 0.02, 0.022, f ? C.E : C.W);
    if (!f) R(0.5 + s * 0.055, fy - 0.02, 0.012, C.E);
  }
  R(0.5, fy + 0.02, 0.025, C.R);
  g.poly([[0.43, fy + 0.05], [0.57, fy + 0.05], [0.5, fy + (f ? 0.11 : 0.08)]], C.RD);
  // ぼうし（とんがり）
  g.poly([[0.38, fy - 0.08], [0.62, fy - 0.08], [0.56, fy - 0.24], [0.5, fy - 0.27]], C.H);
  R(0.5, fy - 0.27, 0.03, C.Y);
}

// ───── キラー ─────
const KILLER = {
  B: '#2a2a32', BL: '#5a5a6a', BD: '#121218', // 黒い 体
  W: '#ffffff', E: '#3a1010', // 目
  G: '#e8e8ec', // 手ぶくろ
  S: '#c8c8d0', SL: '#f0f0f4', // けむり
};
// キラー: 大砲から とんでくる 黒い 弾（左むき）。白い 目と 手。うしろに けむり。コマ1で 少し 前へ・けむりが 大きく
function killer(g0, f) {
  const g = fit(g0, 60);
  const C = KILLER;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const dx = f ? -0.04 : 0;
  // けむり（うしろ）
  for (const [x, y, r] of (f ? [[0.86, 0.46, 0.08], [0.93, 0.58, 0.06], [0.95, 0.36, 0.04]] : [[0.88, 0.5, 0.06], [0.94, 0.42, 0.04]])) {
    R(x, y, r, C.S);
    R(x - 0.01, y - 0.02, r * 0.5, C.SL);
  }
  // 体（まるい 頭と つつ）
  g.rect(0.36 + dx, 0.16, 0.42, 0.68, C.B);
  g.ell(0.38 + dx, 0.5, 0.3, 0.34, C.B);
  g.ell(0.34 + dx, 0.36, 0.14, 0.1, C.BL);
  // うしろの ふた
  g.rect(0.76 + dx, 0.12, 0.08, 0.76, C.BD);
  g.rect(0.78 + dx, 0.12, 0.02, 0.76, C.BL);
  // 目（おこった 目）
  g.ell(0.28 + dx, 0.42, 0.07, 0.12, C.W);
  g.ell(0.25 + dx, 0.44, 0.03, 0.06, C.E);
  g.line([[0.2 + dx, 0.28], [0.36 + dx, 0.34]], C.BD, 2);
  // 手（白い 手ぶくろ）
  g.ell(0.56 + dx, f ? 0.88 : 0.86, 0.06, 0.07, C.G);
  g.ell(0.6 + dx, f ? 0.1 : 0.14, 0.06, 0.07, C.G);
}

// ───── カリヨン ─────
const BELLMAN = {
  B: '#b8863a', BL: '#e8c070', BD: '#5a3e1a', // 真ちゅうの 体
  I: '#4a4e5a', IL: '#9aa0b0', // 鉄
  G: '#f0c040', GL: '#fff0a0', // 金の かね
  W: '#f4f0e0', K: '#1a1010', // 文字ばん・はり
  E: '#7af0ff', // 目の 光
  R: '#c83a3a', // ハンマーの おび
};
// カリヨン: かねつきの からくり。頭は かねの やぐら（中に 大きな かね）・むねに 時計の 文字ばん・右手に 大きな ハンマー・左手に 小さな かね
//   コマ0 … ハンマーを ふり上げる / コマ1 … ハンマーで かねを たたく（かねが かたむき、音の すじ・目が 光る）
function carillon(g0, f) {
  const g = fit(g0, 104);
  const C = BELLMAN;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 足もとの 歯車
  for (const [x, s] of [[0.32, 1], [0.68, -1]]) {
    for (let i = 0; i < 8; i++) {
      const a = (i / 8) * Math.PI * 2 + (f ? s * 0.3 : 0);
      g.rect(x + Math.cos(a) * 0.1 - 0.015, 0.9 + Math.sin(a) * 0.05 - 0.01, 0.03, 0.02, C.I);
    }
    g.ell(x, 0.9, 0.09, 0.045, C.I);
    g.ell(x, 0.9, 0.04, 0.02, C.IL);
  }
  // 体（台形）
  g.poly([[0.28, 0.42], [0.72, 0.42], [0.78, 0.88], [0.22, 0.88]], C.BD);
  g.poly([[0.3, 0.44], [0.7, 0.44], [0.75, 0.86], [0.25, 0.86]], C.B);
  g.poly([[0.32, 0.46], [0.4, 0.46], [0.36, 0.84], [0.28, 0.84]], C.BL);
  // むねの 文字ばん
  g.ell(0.5, 0.64, 0.14, 0.12, C.BD);
  g.ell(0.5, 0.64, 0.12, 0.105, C.W);
  for (let i = 0; i < 12; i++) {
    const a = (i / 12) * Math.PI * 2;
    g.rect(0.5 + Math.cos(a) * 0.1 - 0.006, 0.64 + Math.sin(a) * 0.088 - 0.005, 0.012, 0.01, i % 3 ? C.BD : C.K);
  }
  g.line([[0.5, 0.64], [0.5, 0.57]], C.K, 1.6);
  g.line([[0.5, 0.64], [f ? 0.56 : 0.44, 0.66]], C.K, 1.2);
  R(0.5, 0.64, 0.01, C.R);
  // かねの やぐら（頭）
  g.poly([[0.3, 0.44], [0.32, 0.16], [0.5, 0.05], [0.68, 0.16], [0.7, 0.44]], C.BD);
  g.poly([[0.33, 0.42], [0.35, 0.18], [0.5, 0.09], [0.65, 0.18], [0.67, 0.42]], C.B);
  g.poly([[0.38, 0.4], [0.39, 0.2], [0.5, 0.14], [0.61, 0.2], [0.62, 0.4]], C.K);
  // 大きな かね（コマ1で かたむく）
  const t = f ? 0.04 : 0;
  g.poly([[0.45 + t, 0.17], [0.55 + t, 0.17], [0.59 + t * 2, 0.33], [0.41 + t * 2, 0.33]], C.G);
  g.poly([[0.47 + t, 0.18], [0.5 + t, 0.18], [0.46 + t * 2, 0.32], [0.43 + t * 2, 0.32]], C.GL);
  g.rect(0.4 + t * 2, 0.32, 0.2, 0.025, C.BL);
  R(0.5 + t * 3, 0.37, 0.018, C.I);
  // 目（やぐらの 下に 2つ。コマ1で 光る）
  for (const s of [-1, 1]) R(0.5 + s * 0.09, 0.47, f ? 0.028 : 0.02, C.E);
  // 左手（小さな かね）
  g.line([[0.3, 0.5], [0.18, 0.58], [0.12, 0.66]], C.I, 3.4);
  g.line([[0.12, 0.66], [0.12, 0.7]], C.IL, 1);
  for (const [x, y] of [[0.1, 0.72], [0.15, 0.78]]) g.poly([[x - 0.02, y], [x + 0.02, y], [x + 0.035, y + 0.05], [x - 0.035, y + 0.05]], C.G);
  // 右手と ハンマー
  const [hx, hy] = f ? [0.62, 0.3] : [0.86, 0.12];
  g.line([[0.7, 0.5], [0.84, 0.44], [f ? 0.74 : 0.88, f ? 0.36 : 0.3]], C.I, 3.4);
  g.line([[f ? 0.74 : 0.88, f ? 0.36 : 0.3], [hx, hy]], C.BD, 2.4);
  const hw = 0.07, hh = 0.06;
  g.rect(hx - hw, hy - hh, hw * 2, hh * 2, C.IL);
  g.rect(hx - hw, hy - 0.012, hw * 2, 0.024, C.R);
  // 音の すじ（コマ1）
  if (f) {
    for (const s of [-1, 1]) {
      g.line([[0.5 + s * 0.2, 0.18], [0.5 + s * 0.26, 0.14]], C.GL, 1.6);
      g.line([[0.5 + s * 0.22, 0.26], [0.5 + s * 0.3, 0.26]], C.GL, 1.6);
    }
  } else g.line([[0.86, 0.04], [0.92, 0.06]], C.GL, 1);
}

export function addTokeiArt(ART) {
  // 時計塔 1〜5階
  ART.cog_roller = { size: [52, 52], pal: Object.values(COG), draw: cogRoller };
  ART.spring_box = { size: [48, 58], pal: Object.values(BOX), draw: springBox };
  ART.killer = { size: [60, 46], pal: Object.values(KILLER), draw: killer };
  // 5階の 中ボス（台本の showMon('carillon') でも 大きく）
  ART.carillon = { size: [104, 116], npc: 0.6, pal: Object.values(BELLMAN), draw: carillon };
}
