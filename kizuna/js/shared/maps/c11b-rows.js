// ・もとの 形の 文字（2まい 同じ）: # かべ / . 道 / D 月かげの 戸（乗って A で もう 片方へ）
//   ・おもてと うらで ちがう 文字（おもて ／ うら）:
//     f 水路（通れない）／ 道 … おもてで ふさがり、うらで 通れる
//     b 道 ／ がらくた（通れない） … うらで ふさがり、おもてで 通れる
//     G はかりの門 ／ かべ・R かべ ／ がらくた（トモシビに きまりを 聞くと どく）・T 名前の 塔の 入口 ／ かべ・P はとば ／ がらくた
//     H 家 ／ 小屋・L 名前の ランプの 台 ／ 木の 箱・E ランプの ない かぎ ／ 木の 箱・W 月の いずみ ／ ともしびの 井戸・n 花だん ／ ちょうちん
//   ・塔: L 光の ゆか ／ とじた とびら（ゆかを ふむと 開く）・P ランプ ／ かべ・K かべ ／ かげの 谷（ランプで 橋が かかる）・
//     U 階段 ／ かべ・u かべ ／ 階段・X 塔の 出口 ／ かべ・S ランプの たな ／ かべ・= テラス ／ がらくた・| 手すり（どちらも）
//   ・c 宝箱（ゆか。どちらの 宝箱かは 下の 表）
// ・区切り（C11B_SECTIONS）: 町の 3つ（きほん）と 塔の 3つ（光の ゆか・かげの 橋・2つを 合わせた 物）。
//   どの 区切りも「入口 → 出口」が とける ことと 行き止まりが ない ことを テストで たしかめる（world/c11b-steps.js の solve11b）

const grid = (w, h, ch) => Array.from({ length: h }, () => Array(w).fill(ch));
const toRows = (g) => g.map((r) => r.join(''));
const pen = (g) => ({
  put: (x, y, ch) => { if (g[y]?.[x] !== undefined) g[y][x] = ch; },
  h: (x0, x1, y, ch) => { for (let x = x0; x <= x1; x++) g[y][x] = ch; },
  v: (x, y0, y1, ch) => { for (let y = y0; y <= y1; y++) g[y][x] = ch; },
  rect: (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch; },
});
export const cells11b = (rows, ch) => {
  const out = [];
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === ch) out.push({ x, y }); }));
  return out;
};

