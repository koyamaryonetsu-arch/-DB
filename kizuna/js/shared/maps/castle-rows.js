//   1〜4階 風の階・5〜8階 炎の階・9〜12階 水の階。3つの ふういんの とびら（1階・4階・8階）。4階と 8階に 休み所
// #=かべ .=ゆか i=たいまつ p=柱 o=つぼ k=本だな X=城の 門（1階。影の城の 前の 小島へ）
