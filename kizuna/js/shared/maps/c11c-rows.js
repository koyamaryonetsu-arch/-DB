// ・かげの 台の 輪（はんい）は C11C_RANGE マス（台の まん中から さくの マスの まん中まで）。同じ 色の さくの かたまりに 1マスでも とどけば、かたまりごと 食べる
// ・つながった 同じ 文字の かたまりが 1つの さく・橋・通り道（カード 1まい）
// ・1マス はばの 道の 曲がりかどは 作らない（かどは 2マス いじょう。スマホの スティックが ひっかからない ように。テストで 見る）
// ・どの 階も「入口 → 出口」が とける ことと、行き止まりが ない ことを テストで たしかめる（world/c11c-steps.js の solve11c）

const grid = (w, h, ch) => Array.from({ length: h }, () => Array(w).fill(ch));
const toRows = (g) => g.map((r) => r.join(''));
const pen = (g) => ({
  put: (x, y, ch) => { if (g[y]?.[x] !== undefined) g[y][x] = ch; },
  rect: (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch; },
});

// かげの 台の 輪（マス）
export const C11C_RANGE = 4;

// ───── 1階（24×20）… きほん。台 4つ・さく 4つ ─────
