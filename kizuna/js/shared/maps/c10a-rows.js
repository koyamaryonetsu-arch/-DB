  const rect = rectOf(g);
  // 下の 原（入口）
  rect(3, 25, 44, 37, '.');
  g[38][24] = 'S';
  // 谷（大きな 葉が のびると 橋。まん中の 3れつ）
  rect(1, 22, 46, 24, '~');
  rect(20, 22, 22, 24, 'l');
