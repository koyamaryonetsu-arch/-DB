const grid = (w, h, ch = '#') => Array.from({ length: h }, () => Array(w).fill(ch));
const rectOf = (g) => (x0, y0, x1, y1, ch) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = ch; };

// ───── 古い 道 1階（29×40）─────
function r1Grid() {
  const g = grid(29, 40);
  const rect = rectOf(g);
  // 上の 広間（火口への 上り 階段）
  rect(9, 1, 19, 4, '.');
  g[1][14] = 'U';
  // まん中の 道（上）
  rect(13, 5, 15, 17, '.');
  rect(11, 7, 12, 8, '.'); rect(16, 11, 17, 12, '.');
  // 溶岩の 川（まん中は レバーで 黒い 石）・まわりは 遠くで 光る 溶岩
  rect(4, 18, 26, 20, 'V');
  rect(13, 18, 15, 20, 'B');
  g[16][16] = 'L';
  // まん中の 道（下）・下の 広間
  rect(13, 21, 15, 33, '.');
  rect(9, 34, 19, 37, '.');
  g[38][14] = 'D';
  // 遠回りの わき道（西）: 上の 道の 10行め → 西の はし → 30行め → まん中の 道
  rect(4, 9, 12, 10, '.');
  rect(2, 9, 3, 31, '.');
  rect(4, 30, 12, 31, '.');
  // わき道の 小部屋・宝箱
  g[24][1] = 'c';
  g[2][18] = 'c';
  // 遠くで 光る 溶岩（かざり）
  rect(20, 24, 26, 30, 'V'); rect(17, 24, 19, 26, '#');
  rect(18, 6, 25, 14, 'V');
  return g;
}
export const R1_ROWS = r1Grid().map((r) => r.join(''));

