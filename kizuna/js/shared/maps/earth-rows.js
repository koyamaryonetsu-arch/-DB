// 1階「根のげんかん」: 根の道の 初めて。入口の 広間の 水がめで、谷を わたる 根が のびる（北の 広間にも 同じ 水がめ）。
// 入口の 広間に こわれた 上り下りの ゆか（5階で 直すと 近道）。北の 広間の かべに 大地の 守り星の かべ画
function f1() {
  const s = sheet(W, H, '#');
  s.rect(9, 13, 10, 5); // 入口の 広間
  s.puts([[13, 18], [14, 18]], 'X');
  s.rect(3, 8, 22, 5, '~'); // 根の すきまの 谷
  s.rect(5, 3, 18, 5); // 北の 広間（下りかいだん）
  s.line(14, 8, 0, 1, 5, 'a');
  s.put(10, 14, '1').put(17, 7, '1');
  s.put(20, 4, '>');
  s.put(16, 15, 'L');
  s.puts([[9, 2], [10, 2], [11, 2], [12, 2]], 'M');
  s.puts([[6, 2], [21, 2], [8, 15], [19, 15]], 'i');
  // ── 第38回で ひろげた ところ（座標は もとの 階の 座標。マイナスや はばの 外も 使う）──
  // 西の 根の 小べや（入口の 広間から）。水がめ2で 根（b）が 谷の 上に のびて、北西の 根の 物見へ（かべ画・宝箱）
  s.rect(4, 16, 5, 1);
  s.rect(-2, 13, 6, 6);
  s.put(-2, 14, '2');
  s.rect(-3, 8, 6, 5, '~');
  s.line(0, 8, 0, 1, 5, 'b');
  s.rect(-3, 3, 6, 5);
  s.puts([[-1, 2], [0, 2]], 'M').puts([[-3, 2], [2, 2]], 'i').put(2, 4, 'O');
  // 東の 見晴らしの 間（北の 広間から。根の 谷を 見おろす）
  s.rect(23, 5, 2, 1);
  s.rect(25, 1, 7, 8);
  s.rect(25, 9, 3, 3, '~');
  s.puts([[27, 2], [30, 2], [30, 7]], 'O').puts([[26, 0], [30, 0]], 'i');
  // 南東の 根の 物置（入口の 広間から）
  s.rect(19, 16, 2, 1);
  s.rect(21, 14, 6, 5);
  s.puts([[21, 14], [26, 18]], 'R').put(24, 13, 'i');
  return s.rows();
}

// 2階「根の道を2本つなぐ」: 水がめ1で 西の 根（A）が ちぢみ、東の 根（a）が のびる（てんびんと おなじ「片方が 上がると 片方が 下がる」）。
