// 第5章 Step 6・7「大地の神殿」の レイアウト（1文字 = 1マス。文字の いみは maps/earth.js の EARTH_LEGEND）
// 8階。1階が いちばん 上で、下へ 下へ（> … 下の 階へ / < … 上の 階へ）。島々を ささえる 大きな 木の 根が、神殿を つつんでいる
// #=かべ .=ゆか ~=根の すきまの ふかい 谷（歩けない）X=神殿の 入口（1階。根の島へ）i=たいまつ O=柱 M=かべ画 R=大きな 根（歩けない）
// 1〜4=根の 水がめ（しらべると その 水がめの 根が のびる・ちぢむ。同じ 数字は 同じ 水がめ）
// a〜d=ふだんは ちぢんでいる 根（水がめ 1〜4 で のびて 橋に なる）A〜D=ふだんは のびている 根（水がめ 1〜4 で ちぢんで 谷に なる）
// G=土の 守り手（石の ゴーレム。むきは maps/earth.js の EARTH_GOLEMS）S=守り手の 石板 U=もとに もどす 石板 o=ゆかの あな（ゴーレムで うまる）
// x・y=ふむ石（4階。西・東）==根の とびら（4階。2つの ふむ石が 同時に ふまれると 開く）
// L=こわれた 上り下りの ゆか（1階 ⇔ 5階の 近道）P=重りの ゆか（5階。ゴーレムを のせると 上り下りの ゆかが 直る）
// F=大地の いずみ（5階の 休み所）k=本だな r=ピピを はさんだ 根（5階。ピピを 助けると ほどける）
// g=ゴーレムの 足場（7階。6階で ゴーレムを 根の すきまから 落とすと 谷が 足場に なる）T=大地の 守り星の 祭だん（8階）

// 1つの 階の 紙（ぜんたいは EARTH_W × EARTH_H）。rect・put・line の 座標は、もとの 階（ひろげる 前）の 座標で 書く。
// 紙の 上では EARTH_OX・EARTH_OY だけ ずれる（ひろげた ところは、マイナスの 座標や もとの はばの 外で 書く）
function sheet(w, h, fill) {
  const g = Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => (x === 0 || y === 0 || x === w - 1 || y === h - 1 ? '#' : fill)));
  const ok = (x, y) => x > 0 && y > 0 && x < w - 1 && y < h - 1;
  const api = {
    rect(x, y, rw, rh, ch = '.') { for (let j = y; j < y + rh; j++) for (let i = x; i < x + rw; i++) if (ok(i + OX, j + OY)) g[j + OY][i + OX] = ch; return api; },
    put(x, y, ch) { const X = x + OX, Y = y + OY; if (X >= 0 && Y >= 0 && X < w && Y < h) g[Y][X] = ch; return api; },
    puts(list, ch) { for (const [x, y] of list) api.put(x, y, ch); return api; },
    // (x, y) から dx, dy の 向きへ n マス
    line(x, y, dx, dy, n, ch) { for (let i = 0; i < n; i++) api.put(x + dx * i, y + dy * i, ch); return api; },
    rows() { return g.map((r) => r.join('')); },
  };
  return api;
}
