// 第3章クリアの あとの 長老ハクゲン（story.js が c3_elder に かぶせる）
export function elderCh4(x) {
  if (!x.flag('c4_start')) return introCh4();
  if (!x.flag('c4_ami')) {
    return S('長老ハクゲン', '砂の国へは、風の笛でアステルさまを呼んで、\n風の海の南のはしをこえるのじゃ。', '{name}、気を付けて行っておいで。');
  }
  if (x.flag('c4_scorpion')) {
    return S('長老ハクゲン', '砂の国の村に、水がもどったそうじゃな。\nアステルさまも、よろこんでおられたぞ。',
      'じゃが、水の守り星の光は、まだ弱いままじゃそうな…。\n王都で、何が起きておるのか…。気を付けて行っておいで。');
  }
  return S('長老ハクゲン', '砂の国の子どもを、魔物から助けたそうじゃな。\nアステルさまから聞いたぞ。さすがじゃ。',
    'じゃが、水の守り星のことは、まだ何も分かっておらぬ。\nくれぐれも、無理をするでないぞ。');
}

// 水門の レバー（ゴゴゴ…と たまり水が となりの 区画へ うつる。第3章の 炎の山の レバーと おなじ しくみ）
function waterLever(x, flag, onText, offText) {
  const on = !x.flag(flag);
  return [
    ...N('レバーを動かした！'),
    ['sfx', 'rumble'], ['toggle', flag], ['sync'],
    ...N(on ? onText : offText),
  ];
}

