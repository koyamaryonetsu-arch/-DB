const BUTTON_ORDER = ['sun', 'sand', 'moon', 'star'];
function pressButton(x, key) {
  const b = PYR_BUTTONS.find((k) => k.key === key);
  if (x.flag(PYR_DOOR_FLAG)) return N(`${b.name}のしるしのボタンは、光ったままだ。`);
  if (x.flag(b.flag)) return N(`${b.name}のしるしのボタンは、もう光っている。`);
  const next = BUTTON_ORDER.find((k) => !x.flag(PYR_BUTTONS.find((o) => o.key === k).flag));
  const steps = [...N(`${b.name}のしるしのボタンをおした！`), ['sfx', 'click']];
  if (key === next) {
    steps.push(['flag', b.flag], ['sfx', 'sparkle']);
    if (key !== 'star') return [...steps, ...N(`${b.name}のしるしが、金色に光った！`), ['sync']];
    return [
      ...steps,
      ...N(`${b.name}のしるしが、金色に光った！`, '4つのボタンが、全部光った！'),
      ['sync'],
      ['sfx', 'rumble'], ['shake'],
      ['look', 15.5, 8],
      ...N('ゴゴゴゴ…！', '北の石のとびらが、開いていく！'),
      ['look'],
      ['objective', C4_OBJ.pb],
    ];
  }
  // まちがい: ボタンの 光は みんな 消えて、足もとの ゆかが ぬける（地下の ミイラのへやへ）
  return [
    ...steps,
    ...N('カチッ…。'),
    ...PYR_BUTTONS.map((o) => ['unflag', o.flag]),
    ['sync'],
    ['sfx', 'rumble'], ['shake'],
    ...N('ボタンの光が、全部消えた…！', '足もとのゆかが、ぬけた！'),
    ['sfx', 'fall'],
    ['fade', 'out'],
    ['teleport', PYR_FALL.map, PYR_FALL.x, PYR_FALL.y, 'down'],
    ['fade', 'in'],
    ['shake'],
    ...N('ドサッ！'),
    ...N('…ここは、ピラミッドの地下のようだ。\n東のかいだんから、1階へもどれそうだ。'),
    ...N(x.flag('c4_song') ? '（ボタンは、わらべ歌の順番におすのかもしれない…。\n♪お日さまのぼって、砂がまう…）' : '（ボタンをおす順番に、ひみつがありそうだ…）'),
  ];
}

