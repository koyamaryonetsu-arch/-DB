// トロッコ（maps/ch3.js の CART_RIDES）
function cartSteps(x, id) {
  const r = CART_RIDES[id];
  const leg = r.lever && x.flag(r.lever) ? r.on : r.off;
  const [tx, ty, dir] = leg.to;
  return [
    ['choice', 'トロッコに乗る？', ['乗る', 'やめる'], [
      [['ride', leg.path], ['teleport', r.map, tx, ty, dir]],
      [],
    ]],
  ];
}

// レバー（ゴトン！と 行き先・流れが かわる）
function leverSteps(x, flag, onText, offText, sfx = 'door') {
  const on = !x.flag(flag);
  return [
    ...N('レバーを動かした！'),
    ['sfx', sfx], ['toggle', flag], ['sync'],
    ...N(on ? onText : offText),
  ];
}

// 温泉・大浴場（ただで HP・MPが 回復）
