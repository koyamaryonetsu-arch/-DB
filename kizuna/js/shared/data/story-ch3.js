// ───── たのまれごと（quest-targets.js の subQuests に たす）─────
export function ch3SubQuests(c, f, has, count) {
  const out = [];
  if (f('q_fox_start') && !f('q_fox_done')) {
    if (f('q_fox_found')) out.push({ name: '子ギツネ探し', who: 'c3_v_girl', ready: true, text: '竜守りの村のコユキに知らせよう' });
    else out.push({ name: '子ギツネ探し', who: 'c3_v_girl', find: 'fox', ready: false, text: 'しずか雪の森でユキマルを探そう' });
  }
  if (f('q_snow_start') && !f('q_snow_done')) {
    const n = Math.min(3, count('white_snowball'));
    out.push({ name: '雪だるまコンテスト', who: 'c3_v_kid', ready: n >= 3, text: n >= 3 ? '竜守りの村のユタにわたそう' : `まっ白な雪玉 ${n}/3（ゆきだるまんが持っている）` });
  }
  if (f('c3_onsen') && !f('c3_heatguard')) {
    out.push(has('eternal_ice')
      ? { name: '氷のお守り', who: 'obaba', ready: true, text: '湯守りのおばばに万年氷をわたそう' }
      : { name: '氷のお守り', who: 'obaba', ready: false, text: '氷の洞窟のおくで万年氷を探そう' });
  }
  if (f('q_smith_talk') && !f('q_star_done')) {
    out.push(has('star_iron')
      ? { name: '伝説の星の鉄', who: 'tetsujii', ready: true, text: 'カナトコのテツジイに星の鉄を見せよう' }
      : { name: '伝説の星の鉄', who: 'tetsujii', find: 'star_iron', ready: false, text: '神殿の西のおくで星の鉄を探そう' });
  }
  return out;
}

