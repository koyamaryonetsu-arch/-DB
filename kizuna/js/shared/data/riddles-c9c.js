// 見せる 字（さかさ言葉は さかさの ひらがな）
export const riddleShow = (r) => reverseKana(r.a);
// やさしい（4文字 まで）・むずかしい（5文字 いじょう ＋ なぞなぞ）
export const EASY = REVERSE.filter((r) => [...r.a].length <= 4).map((r) => ({ ...r, id: `r${REVERSE.indexOf(r)}`, type: 'reverse' }));
export const HARD = [
  ...REVERSE.filter((r) => [...r.a].length >= 5).map((r) => ({ ...r, id: `r${REVERSE.indexOf(r)}`, type: 'reverse' })),
  ...PUZZLE.map((r, i) => ({ ...r, id: `p${i}`, type: 'puzzle' })),
];
export const ALL_RIDDLES = [...EASY, ...HARD];

// 画面に 出す 問いの 文
export function riddleText(r) {
  if (!r) return '';
  if (r.type === 'puzzle') return r.q;
  return `『${riddleShow(r)}』…さかさに読むと、なんだ？`;
}
// 答えの 字
export const answerText = (r) => r?.a || '';
