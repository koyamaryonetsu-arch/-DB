// 小さなメダルを もらう（たのまれごとの ごほうび）。メダルは 見つけた 場所の id で 数える（c.medalSpots。world/casino.js）ので、
// ごほうびごとに きまった id（lab_<key>_1〜n）。話しかけた 人が もらう。2回 もらっても 数は ふえない
export function grantMedals(c, key, n, now = Date.now()) {
  c.medalSpots = c.medalSpots && typeof c.medalSpots === 'object' ? c.medalSpots : {};
  for (let i = 1; i <= n; i++) if (!c.medalSpots[`lab_${key}_${i}`]) c.medalSpots[`lab_${key}_${i}`] = now;
}
export function medalSteps(key, n) {
  return [
    ['call', (run) => { grantMedals(run.init.char, key, n, run.world.now()); run.world.markDirty(); }],
    ['sfx', 'key'], ['say', null, `{name}は小さなメダルを${n}枚手に入れた！`],
  ];
}

