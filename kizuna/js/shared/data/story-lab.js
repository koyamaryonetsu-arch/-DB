// 地下2階の 石の スイッチ: 2つとも ふむと 南の とびらが 開く
function plate(x, side) {
  const mine = side === 'w' ? F.plateW : F.plateE;
  const other = side === 'w' ? F.plateE : F.plateW;
  if (x.flag(mine)) return [];
  const steps = [['sfx', 'door'], ['flag', mine], ['sync'], ...N('カチッ…。', '足もとの石のスイッチが、しずんだ！')];
  if (x.flag(other)) {
    steps.push(['sfx', 'rumble'], ['shake'], ['flag', F.door2], ['sync'], ...N('ゴゴゴゴ…！', '2つのスイッチがそろった！\n南の大きな石のとびらが開いた！'));
  } else {
    steps.push(...N(`（${side === 'w' ? '東' : '西'}にも、同じスイッチがあったはずだ）`));
  }
  return steps;
}

