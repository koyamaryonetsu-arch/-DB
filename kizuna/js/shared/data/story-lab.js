// ───── 転送の門（近道）─────
// n … いま いる 階（0 は 古代都市）。地下3・6・9階の 門は、はじめて ふむと 光って、古代都市の 門と つながる
const floorLabel = (k) => (k === 0 ? '砂の古代都市' : `地下${k}階`);
function ringDest(k) {
  const r = ringPos(k);
  return ['teleport', labMapId(k), r.x + 0.5, r.y + 1.6, 'down'];
}
export function ringSteps(x, n) {
  const out = [];
  const lit = n === 0 || x.flag(WARP_FLAGS[n]);
  if (!lit) {
    out.push(['sfx', 'sparkle'], ['flag', WARP_FLAGS[n]], ['sync'], ['flash'],
      ...N('足もとの、古い転送の門に、光がともった！', '（砂の古代都市の転送の門から、この階へ一気に来られるようになった！）'));
  }
  const dests = [0, ...REST_FLOORS].filter((k) => k !== n && (k === 0 || x.flag(WARP_FLAGS[k])));
  if (!dests.length) {
    out.push(...N('古い転送の門だ。', 'まだ、どこにもつながっていない…。\n（大迷宮の地下3階・6階・9階にも、同じ門があるらしい）'));
    return out;
  }
  out.push(...N('古い転送の門が、青白く光っている…。'));
  out.push(['choice', 'どこへ行く？', [...dests.map(floorLabel), 'やめる'], [
    ...dests.map((k) => [['sfx', 'spell'], ['fade', 'out'], ringDest(k), ['fade', 'in'], ...N(`${floorLabel(k)}の転送の門に着いた。`)]),
    [],
  ]]);
  return out;
}

