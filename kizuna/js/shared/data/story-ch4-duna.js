export async function castlePlates(run) {
  // run.partyNow(): いっしょに いる 人（people）と 仲間（helpers: サポート・ゲスト・馬車）。world/scripts.js
  const { people: all, helpers } = run.partyNow();
  const people = all.filter((m) => m.inWorld && m.map === 'sand_castle1');
  const onPlate = CASTLE_PLATES.map(([px, py]) => people.find((m) => Math.floor(m.x) === px && Math.floor(m.y) === py) || null);
  const players = onPlate.filter(Boolean).length;
  if (!players) return;
  if (players >= CASTLE_PLATES.length) {
    await run.runSteps(OPEN_GATE());
    return;
  }
  const [ox, oy] = CASTLE_PLATES[onPlate.findIndex((m) => !m)];
  // 家族: もう 1人が、反対がわの 板に 乗るのを 待つ
  if (people.length >= 2) {
    await run.runSteps(N('石の板が、ゴトン…としずんだ。', '（反対がわの石の板にも、だれかが乗らないと…！\n家族のもう1人に、ふんでもらおう）'));
    return;
  }
  // ひとり: サラ（ゲスト）が いれば サラ、いなければ 馬車・酒場の 仲間
  const sara = helpers.find((h) => h.id === CH4_GUESTS.sara.id);
  const helper = sara || helpers[0];
  if (!helper) {
    await run.runSteps(N('石の板が、ゴトン…としずんだ。', 'しかし、何も起こらない…。',
      '（1人では、2つの板を同時にふめない。\n仲間を連れてこよう。酒場や「仲間」のメニューで、仲間を集められるよ）'));
    return;
  }
  if (helper === sara) {
    await run.runSteps([
      ...N('石の板が、ゴトン…としずんだ。'),
      ...S('サラ', 'もう1つの板は、あたしにまかせて！'),
      ['actor', 'sara_c', { sprite: 'sara', x: ox + 0.5, y: oy + 0.5, dir: 'up' }],
      ['look', ox + 0.5, oy + 0.5],
      ['sfx', 'whip'],
      ...N('サラはムチを柱にまきつけて、ひらりと反対がわの板にとびうつった！'),
      ...OPEN_GATE(),
      ['remove', 'sara_c'],
      ['look'],
    ]);
    return;
  }
  await run.runSteps([...N('石の板が、ゴトン…としずんだ。', `${helper.name}が、反対がわの石の板に乗った！`), ...OPEN_GATE()]);
}

