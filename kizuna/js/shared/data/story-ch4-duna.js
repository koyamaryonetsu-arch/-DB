// ───────────── 砂の古城の 2つの 石の 板 ─────────────
// 2つの 板に 同時に 人が 乗ると、北の 鉄の こうしが 開く（第3章の きずなの間と おなじ 考え方）
// 家族で 2人 いじょう いる ときは、2人で ふむ。ひとりの ときは、サラ（ゲスト）か 馬車・酒場の 仲間が もう1つを ふんで くれる
