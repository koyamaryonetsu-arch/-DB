export async function scaleCheck(run, key, from) {
  const S0 = SCALES[key];
  const f = run.owner.char.flags;
  if (f[S0.flag]) return;
  const { people: all, helpers } = run.partyNow();
  const people = all.filter((m) => m.inWorld && m.map === S0.map);
  const on = (p) => people.filter((m) => Math.floor(m.x) === p.x && Math.floor(m.y) === p.y);
  const rock = !!(S0.rock && f[S0.rock]);
  const onA = on(S0.a), onB = on(S0.b);
  if ((rock || onA.length) && onB.length) {
    await run.runSteps(balanceSteps(S0, null));
    return;
  }
  if (from === 'lever' || (!onA.length && !onB.length)) return;
  const half = N('皿が、ギイ…と少し下がった。', 'しかし、もう1つの皿が、上がったままだ…。');
  if (people.length >= 2) {
    await run.runSteps([...half, ...N('（もう1つの皿に、家族のだれかがのると…？）')]);
    return;
  }
  const rockHint = S0.rock && !onA.length ? '\n（かたむきの石で、岩を左の皿にころがすこともできそうだ）' : '';
  const helper = helpers[0];
  if (!helper) {
    await run.runSteps([...half, ...N(`（もう1つの皿に、重さがのらないと…。\n仲間を連れてこよう。酒場や「仲間」のメニューで、仲間を集められるよ）${rockHint}`)]);
    return;
  }
  await run.runSteps([
    ...half,
    ['choice', `${helper.name}に、もう1つの皿にのってもらう？`, ['のってもらう', 'やめる'], [balanceSteps(S0, helper.name), rockHint ? N(rockHint.slice(1)) : []]],
  ]);
}
