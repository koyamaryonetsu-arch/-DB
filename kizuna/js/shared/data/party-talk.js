// 話す 内容（目標が 表に ない ときは 目標の 文を そのまま）
export function talkFor(objective, style) {
  const t = OBJECTIVE_TALK[objective || ''];
  if (t) return t[style] || t.kind;
  const plain = String(objective || '').replace(/\n/g, '');
  if (!plain) return style === 'kid' ? 'どこへ行こうかなあ。ぼく、どこでもいいよ！' : '次にどこへ行くか、町の人に話を聞いてみるのもいいかもしれない。';
  return style === 'bold' ? `次は「${plain}」だったな。` : style === 'kid' ? `次は「${plain}」だよ！` : `次は「${plain}」ですね。`;
}

// 仲間 1人の 一言。モンスターは しぐさで 話す
export function memberTalk(m, objective) {
  if (m.species) {
    const name = MONSTERS[m.species]?.name || '';
    return { name: m.name, text: `${m.name}は、行き先のほうをじっと見つめている。`, mon: true, kind: name };
  }
  const style = TALK_STYLE[m.key] || TALK_STYLE[m.id] || 'kind';
  return { name: m.name, text: talkFor(objective, style) };
}
