// 星くずモグラ: まるい モグラ（正面）。大きな ツメと ピンクの はな。足もとに 星くずの 山。コマ1で ツメを 上げて 星くずを ほり上げる
function dustMole(g0, f) {
  const g = fit(g0, 50);
  const C = MOLE;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 星くずの 山
  g.ell(0.5, 0.92, 0.42, 0.06, C.D);
  for (const [x, y] of [[0.2, 0.9], [0.36, 0.94], [0.62, 0.93], [0.82, 0.9]]) R(x, y, 0.02, C.DL);
  // 体
  g.ell(0.5, 0.6, 0.32, 0.3, C.BD);
  g.ell(0.5, 0.58, 0.3, 0.28, C.B);
  g.ell(0.5, 0.68, 0.18, 0.16, C.BL);
  // 目（ほそい）・はな
  for (const s of [-1, 1]) g.line([[0.5 + s * 0.08, 0.44], [0.5 + s * 0.14, 0.43]], C.E, 1.4);
  R(0.5, 0.52, 0.07, C.N);
  R(0.48, 0.5, 0.02, C.DL);
  // うでと 大きな ツメ（コマ1で 上げる）
  for (const s of [-1, 1]) {
    const hy = f ? 0.3 : 0.7;
    g.line([[0.5 + s * 0.26, 0.6], [0.5 + s * 0.36, hy]], C.BD, 4);
    for (let i = -1; i <= 1; i++) g.line([[0.5 + s * 0.36, hy], [0.5 + s * (0.42 + i * 0.02), hy + (f ? -0.1 : 0.1) + i * 0.02]], C.C, 1.6);
  }
  // ほり上げた 星くず
  if (f) for (const [x, y, s] of [[0.2, 0.14, 0.05], [0.8, 0.1, 0.06], [0.5, 0.08, 0.04]]) star4(g, x, y, s, C.D, C.DL);
  else for (const [x, y] of [[0.14, 0.78], [0.86, 0.8]]) R(x, y, 0.025, C.D);
}

