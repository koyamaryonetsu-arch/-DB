// ───── ほしかげオオカミ ─────
const WOLF = {
  B: '#2a3060', BL: '#46508a', BD: '#161a3a', // 体
  S: '#fff6c0', L: '#9ad0ff', // 星座の 星と 線
  E: '#ffe070', M: '#c8304a', // 目・口
};
// ほしかげオオカミ: 体に 星座の 線が 光る 黒い オオカミ（左むき）。コマ1で 頭を 下げて 口を あけ、星が 強く 光る
function starWolf(g0, f) {
  const g = fit(g0, 60);
  const C = WOLF;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const dy = f ? 0.06 : 0;
  // しっぽ（ふさふさ）
  g.poly([[0.8, 0.46], [0.96, 0.3 - dy], [0.94, 0.44], [0.86, 0.56]], C.BD);
  g.poly([[0.82, 0.47], [0.93, 0.34 - dy], [0.9, 0.45]], C.BL);
  // 足
  for (const [x, c] of [[0.72, C.BD], [0.64, C.B], [0.36, C.BD], [0.28, C.B]]) {
    g.line([[x, 0.6], [x - 0.01, 0.78], [x - 0.02, 0.92]], c, 3);
    g.ell(x - 0.03, 0.93, 0.035, 0.025, C.BD);
  }
  // 体
  g.ell(0.54, 0.54, 0.29, 0.16, C.BD);
  g.ell(0.54, 0.52, 0.27, 0.14, C.B);
  g.ell(0.5, 0.46, 0.16, 0.06, C.BL);
  // くび・頭（コマ1で 下がる）
  g.poly([[0.34, 0.44], [0.2, 0.3 + dy], [0.3, 0.26 + dy], [0.42, 0.42]], C.B);
  g.ell(0.22, 0.34 + dy, 0.1, 0.09, C.B);
  // はな先（口）
  g.poly([[0.14, 0.32 + dy], [0.03, 0.38 + dy], [0.05, 0.42 + dy], [0.16, 0.42 + dy]], C.BL);
  if (f) g.poly([[0.05, 0.42 + dy], [0.15, 0.43 + dy], [0.12, 0.48 + dy], [0.06, 0.46 + dy]], C.M);
  R(0.04, 0.38 + dy, 0.016, C.BD);
  // 耳
  g.poly([[0.22, 0.27 + dy], [0.24, 0.14 + dy], [0.3, 0.26 + dy]], C.BD);
  g.poly([[0.26, 0.27 + dy], [0.3, 0.16 + dy], [0.33, 0.28 + dy]], C.B);
  // 目
  R(0.16, 0.32 + dy, f ? 0.022 : 0.016, C.E);
  // 星座の 線と 星（体の 上）
  const pts = [[0.36, 0.48], [0.46, 0.42], [0.58, 0.46], [0.68, 0.42], [0.76, 0.5]];
  g.line(pts, C.L, 0.8);
  g.line([[0.58, 0.46], [0.56, 0.58]], C.L, 0.8);
  for (const [x, y] of [...pts, [0.56, 0.58]]) R(x, y, f ? 0.022 : 0.015, C.S);
  if (f) star4(g, 0.46, 0.42, 0.05, C.S, C.L);
}

