// ───── ふたご星の精 ─────
const TWIN = {
  Y: '#ffe070', YL: '#fff8c0', YD: '#c89a2a', // 光の 星
  V: '#5a4aa0', VL: '#8a7ad0', VD: '#2a2058', // 闇の 星
  K: '#1a1026', R: '#ff9ab0', // 目・口・ほお
};
// 5つの とがりの 星（cx, cy … まん中・r … 大きさ・a … 回り）
function star5(g, cx, cy, r, a, c, k) {
  const pts = [];
  for (let i = 0; i < 10; i++) {
    const t = a + (i * Math.PI) / 5 - Math.PI / 2;
    const rr = i % 2 ? r * 0.46 : r;
    pts.push([cx + Math.cos(t) * rr, cy + Math.sin(t) * rr * k]);
  }
  g.poly(pts, c);
}
// ふたご星の精: 光の 星と 闇の 星が 手を つないだ 精（正面）。コマ1で くるりと 回って 入れかわる
function twinStar(g0, f) {
  const g = fit(g0, 52);
  const C = TWIN;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const lx = f ? 0.66 : 0.32, dx = f ? 0.34 : 0.68;
  const ly = f ? 0.56 : 0.44, dy = f ? 0.44 : 0.56;
  // 回る わ
  g.line([[0.12, 0.5], [0.3, 0.36], [0.5, 0.32], [0.7, 0.36], [0.88, 0.5], [0.7, 0.64], [0.5, 0.68], [0.3, 0.64], [0.12, 0.5]], C.VL, 0.8);
  // つないだ 手
  g.line([[lx, ly], [dx, dy]], C.YD, 1.6);
  // 闇の 星
  star5(g, dx, dy, 0.26, f ? 0.3 : 0.1, C.VD, k);
  star5(g, dx, dy, 0.22, f ? 0.3 : 0.1, C.V, k);
  R(dx - 0.05, dy - 0.02, 0.018, C.VL);
  g.line([[dx - 0.06, dy + 0.01], [dx - 0.03, dy + 0.01]], C.K, 1);
  g.line([[dx + 0.02, dy + 0.01], [dx + 0.05, dy + 0.01]], C.K, 1);
  // 光の 星
  star5(g, lx, ly, 0.26, f ? -0.3 : -0.1, C.YD, k);
  star5(g, lx, ly, 0.22, f ? -0.3 : -0.1, C.Y, k);
  R(lx - 0.06, ly - 0.05, 0.02, C.YL);
  R(lx - 0.04, ly, 0.018, C.K);
  R(lx + 0.04, ly, 0.018, C.K);
  g.ell(lx, ly + 0.06, 0.03, 0.015, C.K);
  R(lx - 0.07, ly + 0.04, 0.016, C.R);
  R(lx + 0.07, ly + 0.04, 0.016, C.R);
  // きらきら
  star4(g, f ? 0.16 : 0.84, f ? 0.16 : 0.84, 0.05, C.YL, C.Y);
}

