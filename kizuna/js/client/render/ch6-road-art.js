// ───── 星くいのよる鳥（中ボス）─────
const EATER = {
  B: '#1e2048', BL: '#3a3e7a', BD: '#0e0f26', F: '#5a5aa8', // 夜の 色の はね
  S: '#fff6c0', E: '#ffd040', EL: '#fff8d0', // 星・目
  K: '#e8a030', KD: '#a86a1a', M: '#c83a5a', // くちばし・口の 中
};
// 星くいのよる鳥: 夜の 色の 大きな 鳥（正面）。はねを 大きく ひろげ、はねに 星の つぶ。おなかの うずの 中で、食べた 星が 光る。
//   コマ0 … はねを 横に ひろげる・くちばしを とじる / コマ1 … はねを 高く 上げ、くちばしを ひらき、目が 強く 光る
function starEater(g0, f) {
  const g = fit(g0, 120);
  const C = EATER;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? -0.14 : 0;
  // はね（左右。3まいの かさなり）
  for (const s of [-1, 1]) {
    g.poly([[0.5 + s * 0.12, 0.36], [0.5 + s * 0.36, 0.14 + up], [0.5 + s * 0.48, 0.2 + up], [0.5 + s * 0.47, 0.42 + up * 0.5], [0.5 + s * 0.42, 0.58], [0.5 + s * 0.3, 0.66], [0.5 + s * 0.16, 0.6]], C.BD);
    g.poly([[0.5 + s * 0.14, 0.38], [0.5 + s * 0.35, 0.18 + up], [0.5 + s * 0.45, 0.23 + up], [0.5 + s * 0.44, 0.42 + up * 0.5], [0.5 + s * 0.38, 0.54], [0.5 + s * 0.18, 0.56]], C.B);
    // 風切りばね
    for (let i = 0; i < 4; i++) {
      const tx = 0.5 + s * (0.3 + i * 0.045), ty = 0.5 + i * 0.03;
      g.poly([[tx, ty - 0.08], [tx + s * 0.03, ty + 0.12], [tx - s * 0.02, ty + 0.06]], i % 2 ? C.BL : C.F);
    }
    // はねの 星の つぶ
    for (const [x, y] of [[0.26, 0.26], [0.36, 0.34], [0.42, 0.24], [0.3, 0.42]]) R(0.5 + s * x, y + up * (x > 0.3 ? 0.8 : 0.4), 0.008, C.S);
  }
  // 体
  g.ell(0.5, 0.56, 0.17, 0.3, C.BD);
  g.ell(0.5, 0.54, 0.15, 0.28, C.B);
  // おなかの うずと 食べた 星
  g.ell(0.5, 0.64, 0.09, 0.14, C.BL);
  g.line([[0.5, 0.64], [0.54, 0.6], [0.56, 0.66], [0.5, 0.72], [0.44, 0.66], [0.47, 0.58]], C.F, 1.4);
  star4(g, 0.5, 0.64, f ? 0.05 : 0.035, C.S, C.EL);
  // 頭と かんむりの はね
  for (const [x, h] of [[-0.06, 0.1], [0, 0.14], [0.06, 0.1]]) g.poly([[0.5 + x - 0.02, 0.22], [0.5 + x * 1.6, 0.22 - h], [0.5 + x + 0.02, 0.22]], C.F);
  R(0.5, 0.28, 0.1, C.B);
  // 目
  for (const s of [-1, 1]) {
    g.poly([[0.5 + s * 0.02, 0.25], [0.5 + s * 0.08, 0.23], [0.5 + s * 0.08, 0.28], [0.5 + s * 0.03, 0.29]], C.BD);
    R(0.5 + s * 0.055, 0.265, f ? 0.02 : 0.015, f ? C.EL : C.E);
  }
  // くちばし（コマ1で ひらく）
  if (f) {
    g.poly([[0.45, 0.31], [0.55, 0.31], [0.5, 0.36]], C.K);
    g.poly([[0.46, 0.36], [0.54, 0.36], [0.5, 0.44]], C.M);
    g.poly([[0.46, 0.38], [0.54, 0.38], [0.5, 0.46]], C.KD);
  } else {
    g.poly([[0.45, 0.31], [0.55, 0.31], [0.52, 0.38], [0.5, 0.42], [0.48, 0.38]], C.K);
    g.line([[0.47, 0.35], [0.53, 0.35]], C.KD, 1);
  }
  // 足（かぎづめ）
  for (const s of [-1, 1]) {
    g.line([[0.5 + s * 0.06, 0.82], [0.5 + s * 0.08, 0.92]], C.KD, 3);
    for (let i = -1; i <= 1; i++) g.line([[0.5 + s * 0.08, 0.92], [0.5 + s * 0.08 + i * 0.03, 0.97]], C.K, 1.6);
  }
  // まわりの 星（ねらう 星）
  star4(g, f ? 0.2 : 0.12, f ? 0.06 : 0.1, 0.03, C.S, C.EL);
  star4(g, f ? 0.84 : 0.9, f ? 0.08 : 0.12, 0.025, C.S, C.EL);
}

// ───── ペンデュラ（ボス）─────
const PEND = {
  D: '#3a2a5a', DL: '#5e4a8a', DD: '#1e1430', // ドレス・ぼうし
  S: '#f0d8c0', SD: '#c8a088', HR: '#c0c8e0', // はだ・かみ（銀）
  G: '#d8b040', GL: '#fff0a0', C: '#e8ecf4', K: '#1a1020', // 金の かざり・ふりこ・時計・針
  E: '#7af0ff', R: '#c83a5a', // 目の 光・リボン
};
// ペンデュラ: 大きな 時のふりこを 持つ 魔女（正面）。とんがりぼうしに 時計、銀の 長い かみ、すその ひろい ドレス。
//   右手の つえの 先から 大きな ふりこが さがる。コマ0 … ふりこが 左 / コマ1 … ふりこが 右・左手を 上げて 目が 光る
function pendula(g0, f) {
  const g = fit(g0, 104);
  const C = PEND;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // ドレスの すそ
  g.poly([[0.38, 0.5], [0.62, 0.5], [0.78, 0.94], [0.22, 0.94]], C.DD);
  g.poly([[0.4, 0.5], [0.6, 0.5], [0.75, 0.92], [0.25, 0.92]], C.D);
  g.poly([[0.42, 0.52], [0.5, 0.52], [0.4, 0.9], [0.3, 0.9]], C.DL);
  // すその 時計の もよう（金の 線）
  g.line([[0.24, 0.9], [0.76, 0.9]], C.G, 1.4);
  for (const x of [0.32, 0.44, 0.56, 0.68]) R(x, 0.86, 0.012, C.GL);
  // 銀の かみ（せなか）
  g.poly([[0.4, 0.2], [0.6, 0.2], [0.64, 0.5], [0.58, 0.56], [0.42, 0.56], [0.36, 0.5]], C.HR);
  // 体
  g.poly([[0.42, 0.32], [0.58, 0.32], [0.6, 0.52], [0.4, 0.52]], C.D);
  g.rect(0.41, 0.48, 0.18, 0.03, C.G);
  R(0.5, 0.36, 0.02, C.R);
  // 顔
  R(0.5, 0.25, 0.065, C.S);
  g.ell(0.5, 0.29, 0.04, 0.012, C.SD);
  for (const s of [-1, 1]) R(0.5 + s * 0.025, 0.245, f ? 0.012 : 0.009, f ? C.E : C.K);
  g.ell(0.5, 0.285, 0.012, 0.006, C.R);
  // ぼうし（とんがり・つばに 時計）
  g.ell(0.5, 0.19, 0.16, 0.03, C.DD);
  g.poly([[0.42, 0.19], [0.58, 0.19], [0.6, 0.02], [0.52, 0.06]], C.D);
  g.poly([[0.44, 0.18], [0.5, 0.18], [0.56, 0.04], [0.52, 0.07]], C.DL);
  R(0.5, 0.14, 0.035, C.G);
  R(0.5, 0.14, 0.026, C.C);
  g.line([[0.5, 0.14], [0.5, 0.125]], C.K, 0.8);
  g.line([[0.5, 0.14], [0.512, 0.145]], C.K, 0.8);
  // 左手（コマ1で 上げる。手の 上に 小さな 時計の 光）
  const [lx, ly] = f ? [0.24, 0.16] : [0.3, 0.5];
  g.line([[0.42, 0.34], [0.32, f ? 0.26 : 0.42], [lx, ly]], C.D, 3);
  R(lx, ly, 0.022, C.S);
  if (f) {
    R(lx, ly - 0.06, 0.03, C.GL);
    R(lx, ly - 0.06, 0.018, C.E);
  }
  // 右手と つえ
  g.line([[0.58, 0.34], [0.68, 0.4], [0.74, 0.36]], C.D, 3);
  R(0.74, 0.36, 0.022, C.S);
  g.line([[0.76, 0.96], [0.76, 0.1]], C.DD, 2.4);
  g.line([[0.762, 0.9], [0.762, 0.14]], C.G, 0.8);
  // つえの 先の かざり
  R(0.76, 0.08, 0.04, C.G);
  R(0.76, 0.08, 0.025, C.GL);
  // ふりこ（つえの 先から。コマで 左右に ゆれる）
  const a = f ? 0.42 : -0.42;
  const L = 0.5;
  const bx = 0.76 + Math.sin(a) * L * 0.42, by = 0.1 + Math.cos(a) * L;
  g.line([[0.76, 0.1], [bx, by]], C.G, 2);
  R(bx, by, 0.085, C.G);
  R(bx, by, 0.068, C.C);
  for (let i = 0; i < 12; i++) {
    const t = (i * Math.PI) / 6;
    R(bx + Math.cos(t) * 0.052, by + Math.sin(t) * 0.052 * k, i % 3 ? 0.004 : 0.008, C.K);
  }
  g.line([[bx, by], [bx + Math.cos(-1.2 + a) * 0.045, by + Math.sin(-1.2 + a) * 0.045 * k]], C.K, 1.2);
  g.line([[bx, by], [bx + Math.cos(0.4 - a) * 0.03, by + Math.sin(0.4 - a) * 0.03 * k]], C.R, 1);
  // ゆれの あと（光の すじ）
  g.line([[0.76 + Math.sin(-a * 0.6) * L * 0.42, 0.1 + Math.cos(a * 0.6) * L], [bx, by]], C.GL, 0.6);
}

