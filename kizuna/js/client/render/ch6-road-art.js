    const hx = 0.5 + s * 0.38, hy = f ? 0.2 : 0.44;
    g.line([[0.5 + s * 0.22, 0.56], [0.5 + s * 0.32, f ? 0.36 : 0.5], [hx, hy + 0.06]], C.SD, 4);
    g.ell(hx, hy, 0.09, 0.1, C.SD);
    g.ell(hx, hy - 0.01, 0.075, 0.085, C.S);
    // はさみの 2本の 先（コマ1で ひらく）
