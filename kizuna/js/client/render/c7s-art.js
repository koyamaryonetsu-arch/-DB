  const hx = up ? 0.8 : 0.76, hy = up ? 0.2 : 0.46;
  g.line([[0.62, 0.33], [0.7, up ? 0.28 : 0.4], [hx, hy]], C.TK, 7);
  g.line([[0.62, 0.33], [0.7, up ? 0.28 : 0.4], [hx, hy]], C.T, 5.6);
  g.line([[0.64, 0.34], [0.7, up ? 0.29 : 0.41]], C.TD, 1.6);
  for (let i = 0; i < 4; i++) R(hx + (i - 1.5) * 0.012, hy + (up ? -0.012 : 0.012), 0.012, i % 2 ? C.LD : C.L);
  // かぎ
  const cy = up ? hy - 0.03 : hy + 0.03;
  const dir = up ? -1 : 1;
  g.rect(hx - 0.012, Math.min(hy, cy), 0.024, Math.abs(cy - hy) + 0.01, C.GD);
  g.line([[hx, cy], [hx, cy + dir * 0.05], [hx + 0.03, cy + dir * 0.085], [hx + 0.065, cy + dir * 0.07], [hx + 0.07, cy + dir * 0.04]], C.GD, 3.4);
