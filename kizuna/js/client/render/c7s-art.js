  g.line([[0.5, 0.165], [0.49, 0.19], [0.5, 0.192]], C.SD, 1);
  // くるりと まいた ひげ
  for (const s of [-1, 1]) g.line([[0.5, 0.2], [0.5 + s * 0.03, 0.198], [0.5 + s * 0.055, 0.19], [0.5 + s * 0.06, 0.176], [0.5 + s * 0.05, 0.172]], C.H, 1.4);
  // 口（にやり）
