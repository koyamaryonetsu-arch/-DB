  const quill = [[0.57, 0.085], [0.64, 0.045 - fw], [0.72, 0.03 - fw], [0.8, 0.04 - fw], [0.86, 0.075 - fw / 2], [0.89, 0.13], [0.885, 0.18 + fw]];
