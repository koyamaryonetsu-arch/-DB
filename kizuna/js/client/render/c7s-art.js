  g.poly([[0.45, 0.32], [0.55, 0.32], [0.54, 0.6], [0.5, 0.63], [0.46, 0.6]], C.V);
  for (let i = 0; i < 5; i++) {
    R(0.5, 0.37 + i * 0.05, 0.008, C.GD);
    R(0.499, 0.369 + i * 0.05, 0.005, C.GL);
  }
  g.line([[0.45, 0.32], [0.46, 0.6]], C.G, 1);
  g.line([[0.55, 0.32], [0.54, 0.6]], C.G, 1);
  // ベルト
  g.rect(0.41, 0.53, 0.18, 0.022, C.B);
  g.rect(0.48, 0.525, 0.04, 0.032, C.G);
  g.rect(0.488, 0.532, 0.024, 0.018, C.B);
  // ── うで（左 … サーベル・右 … 金の かぎ）──
  // サーベルの うで（見る人の 左。コマ1 … 前へ つき出す）
  const sx = up ? 0.2 : 0.26, sy = up ? 0.4 : 0.5;
  g.line([[0.38, 0.33], [0.3, up ? 0.38 : 0.42], [sx, sy]], C.TK, 7);
  g.line([[0.38, 0.33], [0.3, up ? 0.38 : 0.42], [sx, sy]], C.T, 5.6);
  g.line([[0.37, 0.335], [0.3, up ? 0.385 : 0.425]], C.TL, 1.6);
  // そでの レース
  for (let i = 0; i < 4; i++) R(sx + 0.012 + (i - 1.5) * 0.012, sy + 0.012, 0.012, i % 2 ? C.LD : C.L);
  R(sx - 0.005, sy + 0.008, 0.014, C.S);
  // サーベル（金の つば・ほそい 刃）
  const tx = up ? 0.0 : 0.05, ty = up ? 0.26 : 0.22;
  g.line([[sx - 0.01, sy], [tx, ty]], C.KD, 2.2);
  g.line([[sx - 0.012, sy - 0.004], [tx + 0.004, ty]], C.K, 0.9);
  g.line([[sx - 0.02, sy - 0.03], [sx + 0.012, sy + 0.025]], C.G, 1.8);
  g.line([[sx - 0.005, sy + 0.015], [sx - 0.02, sy - 0.015], [sx - 0.008, sy - 0.035]], C.GD, 1);
