  if (up) for (const [x, y] of [[hx + 0.08, cy - 0.03], [hx + 0.02, cy - 0.1]]) R(x, y, 0.008, C.GL);
  // ── えり（白い レース）──
  for (let i = 0; i < 5; i++) {
    g.ell(0.5, 0.29 + i * 0.016, 0.06 - i * 0.008, 0.012, i % 2 ? C.LD : C.L);
  }
  g.poly([[0.38, 0.29], [0.44, 0.27], [0.46, 0.33], [0.39, 0.33]], C.L);
