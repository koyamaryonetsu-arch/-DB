  // あごひげ
  g.poly([[0.495, 0.228], [0.505, 0.228], [0.5, 0.245]], C.H);
  // ── 大きな ぼうしと 白い 羽 ──
  g.ell(0.5, 0.11, 0.17, 0.03, C.A);
  g.ell(0.5, 0.105, 0.165, 0.024, C.AL);
  g.poly([[0.39, 0.1], [0.42, 0.04], [0.5, 0.02], [0.58, 0.04], [0.61, 0.1]], C.A);
  g.poly([[0.42, 0.09], [0.44, 0.05], [0.5, 0.035], [0.52, 0.04], [0.46, 0.09]], C.AL);
  g.line([[0.4, 0.095], [0.6, 0.095]], C.G, 1.4);
  // 羽（大きく うしろへ そって たれる。コマ1 … ゆれる）。ななめの だ円を つないで、まん中に じく・ほそい すじ
