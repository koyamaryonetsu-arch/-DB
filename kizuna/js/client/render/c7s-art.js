  g.poly([[0.36, 0.3], [0.64, 0.3], [0.76 + flap, 0.8], [0.62, 0.78], [0.5, 0.62], [0.38, 0.78], [0.24 - flap, 0.8]], C.TK);
  g.poly([[0.365, 0.305], [0.635, 0.305], [0.745 + flap, 0.79], [0.625, 0.77], [0.5, 0.615], [0.375, 0.77], [0.255 - flap, 0.79]], C.T);
  // コートの かげと 光
  g.poly([[0.38, 0.34], [0.43, 0.34], [0.36, 0.76], [0.29 - flap, 0.78]], C.TL);
  g.poly([[0.6, 0.36], [0.64, 0.34], [0.72 + flap, 0.78], [0.66, 0.77]], C.TD);
  // 金の ふち（すそ・まえ）
  g.line([[0.255 - flap, 0.79], [0.375, 0.77], [0.5, 0.615], [0.625, 0.77], [0.745 + flap, 0.79]], C.G, 1.6);
  g.line([[0.26 - flap, 0.795], [0.375, 0.775]], C.GL, 0.6);
