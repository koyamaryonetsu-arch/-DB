  g.poly([[0.32, 0.36], [0.68, 0.36], [0.84, 0.92], [0.7, 0.86], [0.6, 0.95], [0.5, 0.88], [0.4, 0.95], [0.3, 0.86], [0.16, 0.92]], C.KD);
  g.poly([[0.34, 0.38], [0.66, 0.38], [0.8, 0.88], [0.68, 0.83], [0.58, 0.91], [0.5, 0.85], [0.42, 0.91], [0.32, 0.83], [0.2, 0.88]], C.K);
