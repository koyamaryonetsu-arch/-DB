// かねの精: 小さな 金の かねの 中から 顔を 出す 精。せなかに すきとおった はね。
//   コマ1 … かねが かたむいて、音の すじ・はねが ひらく
function bellSprite(g0, f) {
  const g = fit(g0, 34);
  const C = BS;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const tl = f ? 0.05 : 0;
  // はね
  for (const s of [-1, 1]) {
    const o = f ? 0.06 : 0;
    g.poly([[0.5 + s * 0.12, 0.42], [0.5 + s * (0.44 + o), 0.18], [0.5 + s * (0.42 + o), 0.42], [0.5 + s * 0.2, 0.52]], C.F);
    g.poly([[0.5 + s * 0.15, 0.44], [0.5 + s * (0.36 + o), 0.26], [0.5 + s * 0.24, 0.44]], C.FL);
  }
  // かね（上が まるく 下が ひろい）
  g.poly([[0.32 + tl, 0.28], [0.68 + tl, 0.28], [0.8 + tl * 2, 0.78], [0.2 + tl * 2, 0.78]], C.GD);
  g.poly([[0.34 + tl, 0.3], [0.66 + tl, 0.3], [0.76 + tl * 2, 0.74], [0.24 + tl * 2, 0.74]], C.G);
  R(0.5 + tl, 0.28, 0.17, C.G);
  g.poly([[0.36 + tl, 0.3], [0.44 + tl, 0.3], [0.36 + tl * 2, 0.72], [0.28 + tl * 2, 0.72]], C.GL);
  g.rect(0.16 + tl * 2, 0.76, 0.68, 0.06, C.GD);
  // つりひも
  g.rect(0.47 + tl, 0.06, 0.06, 0.08, C.GD);
  R(0.5 + tl, 0.06, 0.04, C.GL);
  // 顔（かねの 口から）
  R(0.5 + tl * 2, 0.6, 0.15, C.S);
  for (const s of [-1, 1]) {
    R(0.5 + tl * 2 + s * 0.06, 0.58, 0.028, C.E);
    R(0.5 + tl * 2 + s * 0.055, 0.57, 0.01, C.W);
    R(0.5 + tl * 2 + s * 0.11, 0.64, 0.025, C.P);
  }
  g.poly([[0.46 + tl * 2, 0.66], [0.54 + tl * 2, 0.66], [0.5 + tl * 2, 0.7]], C.E);
  // した（ゆれる 玉）
  R(0.5 + tl * 3, 0.88, 0.05, C.GD);
  R(0.49 + tl * 3, 0.87, 0.02, C.GL);
  // 音の すじ（コマ1）
  if (f) {
    for (const s of [-1, 1]) {
      g.line([[0.5 + s * 0.3, 0.12], [0.5 + s * 0.38, 0.06]], C.N, 1.4);
      g.line([[0.5 + s * 0.36, 0.22], [0.5 + s * 0.46, 0.2]], C.N, 1.4);
    }
  }
}

// ───── 大時計の番人 ─────
const CGM = {
  B: '#b8863a', BL: '#e8c070', BD: '#6a4a20', // 真ちゅうの 体
  I: '#5a5e6a', IL: '#9aa0b0', ID: '#2e3038', // 鉄
  W: '#f4ead0', K: '#1a1010', R: '#c83a3a', // 文字ばん
  E: '#7ad0ff', EL: '#e8fbff', // 目
};
// 大時計の番人: むねに 大きな 文字ばんの ある からくりの 大男。かたに 歯車・大きな 鉄の こぶし。
//   コマ0 … こぶしを ふり上げる / コマ1 … ふり下ろす（文字ばんの 針が すすみ、目が 光る）
function clockGolem(g0, f) {
  const g = fit(g0, 64);
  const C = CGM;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const gear = (x, y, r, rot, c, cl) => {
    for (let i = 0; i < 10; i++) {
      const a = rot + (i / 10) * Math.PI * 2;
      g.ell(x + Math.cos(a) * r, y + Math.sin(a) * r * k, r * 0.22, r * 0.22 * k, c);
    }
    R(x, y, r * 0.9, c);
    R(x, y, r * 0.45, cl);
    R(x, y, r * 0.18, C.ID);
  };
  // 足
  for (const x of [0.36, 0.64]) {
    g.rect(x - 0.08, 0.78, 0.16, 0.14, C.I);
    g.rect(x - 0.11, 0.9, 0.22, 0.06, C.ID);
    g.rect(x - 0.06, 0.8, 0.04, 0.1, C.IL);
  }
  // 体（四角い 箱の 時計）
  g.rect(0.2, 0.3, 0.6, 0.5, C.BD);
  g.rect(0.22, 0.32, 0.56, 0.46, C.B);
  g.rect(0.24, 0.34, 0.08, 0.42, C.BL);
  // かたの 歯車（回る）
  gear(0.2, 0.32, 0.1, f ? 0.3 : 0, C.I, C.IL);
  gear(0.8, 0.32, 0.1, f ? -0.3 : 0, C.I, C.IL);
  // むねの 文字ばん
  R(0.5, 0.52, 0.19, C.BD);
  R(0.5, 0.52, 0.16, C.W);
  for (let i = 0; i < 12; i++) {
    const a = (i / 12) * Math.PI * 2;
    g.rect(0.5 + Math.cos(a) * 0.13 - 0.008, 0.52 + Math.sin(a) * 0.13 * k - 0.006, 0.016, 0.012, i % 3 ? C.BD : C.K);
  }
  g.line([[0.5, 0.52], [0.5, 0.43]], C.K, 2);
  g.line([[0.5, 0.52], [f ? 0.6 : 0.42, f ? 0.55 : 0.47]], C.R, 1.6);
  R(0.5, 0.52, 0.015, C.R);
  // 頭（小さな 箱・目は 青い 光）
  g.rect(0.36, 0.1, 0.28, 0.2, C.BD);
  g.rect(0.38, 0.12, 0.24, 0.16, C.B);
  g.rect(0.44, 0.05, 0.12, 0.06, C.I);
  for (const s of [-1, 1]) {
    g.rect(0.5 + s * 0.06 - 0.035, 0.17, 0.07, 0.04, f ? C.EL : C.E);
  }
  g.rect(0.43, 0.24, 0.14, 0.02, C.ID);
  // うで（右は こぶしを ふり上げる / ふり下ろす）
  g.line([[0.22, 0.42], [0.1, 0.6], [0.12, 0.72]], C.I, 5);
  R(0.12, 0.76, 0.07, C.IL);
  R(0.12, 0.76, 0.045, C.I);
  const [fx, fy] = f ? [0.88, 0.78] : [0.9, 0.14];
  g.line([[0.78, 0.42], [0.92, f ? 0.6 : 0.3], [fx, fy]], C.I, 5);
  R(fx, fy, 0.09, C.IL);
  R(fx, fy, 0.06, C.I);
  if (f) for (const dx of [-0.08, 0, 0.08]) g.line([[fx + dx, 0.9], [fx + dx * 1.6, 0.96]], C.BL, 1.2);
}

// ───── ぜんまい草 ─────
const FERN = {
  L: '#6ab83a', LL: '#b8e880', LD: '#2e6a1e', // わか葉
  S: '#8a6a3a', SD: '#5a4020', // くき・はち
  W: '#ffffff', E: '#1a1a10', M: '#a82a2a', // 顔
  H: '#d8c098', // わた毛
};
// ぜんまい草: くるくる まいた わか葉（ぜんまい）が 3本。まん中の 太い くきに 顔。
//   コマ1 … まいた わか葉が びよーんと のびる
function zenmaiFern(g0, f) {
  const g = fit(g0, 44);
  const C = FERN;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // うずまき（cx・cy … まん中・r … 大きさ）
  const spiral = (cx, cy, r, dir, col, lw) => {
    const pts = [];
    for (let i = 0; i <= 28; i++) {
      const t = i / 28;
      const a = dir * t * Math.PI * 3.4;
      const rr = r * (1 - t * 0.85);
      pts.push([cx + Math.cos(a) * rr, cy + Math.sin(a) * rr * k]);
    }
    g.line(pts, col, lw);
  };
  // 足もとの 葉
  g.poly([[0.18, 0.96], [0.36, 0.78], [0.5, 0.96]], C.LD);
  g.poly([[0.5, 0.96], [0.66, 0.78], [0.84, 0.96]], C.LD);
  g.poly([[0.28, 0.96], [0.42, 0.84], [0.54, 0.96]], C.L);
  // わか葉（左右。コマ1で のびる）
  const up = f ? 0.1 : 0;
  g.line([[0.42, 0.7], [0.3, 0.52 - up], [0.2, 0.36 - up]], C.L, 3);
  spiral(0.2, 0.3 - up, 0.1, -1, C.L, 2.6);
  g.line([[0.58, 0.7], [0.7, 0.52 - up], [0.8, 0.36 - up]], C.L, 3);
  spiral(0.8, 0.3 - up, 0.1, 1, C.L, 2.6);
  // まん中の 大きな わか葉（あたま）
  g.line([[0.5, 0.8], [0.5, 0.36 - up * 0.6]], C.LD, 4);
  spiral(0.5, 0.22 - up * 0.6, 0.15, 1, C.LD, 3.6);
  spiral(0.5, 0.22 - up * 0.6, 0.15, 1, C.LL, 1.2);
  // わた毛（ぜんまいの 毛）
  for (const [x, y] of [[0.44, 0.44], [0.56, 0.5], [0.46, 0.6]]) R(x, y - up * 0.3, 0.02, C.H);
  // 顔（くきの ふくらみ）
  R(0.5, 0.66, 0.15, C.L);
  R(0.47, 0.63, 0.08, C.LL);
  for (const s of [-1, 1]) {
    R(0.5 + s * 0.06, 0.64, 0.028, C.W);
    R(0.5 + s * 0.06, 0.645, 0.016, C.E);
  }
  g.poly([[0.45, 0.71], [0.55, 0.71], [0.5, f ? 0.77 : 0.74]], C.M);
}

