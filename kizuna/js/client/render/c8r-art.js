// 小さな 顔（x・y … まんなか、s … 大きさ）
function fzFace(g, x, y, s, C, smug = true) {
  const k = g.w / g.h;
  // つり目（赤い ひとみ）
  for (const d of [-1, 1]) {
    g.poly([[x + d * s * 0.12, y - s * 0.02], [x + d * s * 0.42, y - s * 0.14], [x + d * s * 0.38, y + s * 0.06], [x + d * s * 0.14, y + s * 0.08]], '#ffffff');
    g.ell(x + d * s * 0.27, y - s * 0.02, s * 0.07, s * 0.08, C.R);
    g.ell(x + d * s * 0.27, y - s * 0.02, s * 0.03, s * 0.05, '#1a1026');
    g.line([[x + d * s * 0.1, y - s * 0.12], [x + d * s * 0.44, y - s * 0.26]], C.K, 1.6);
  }
  // 口（すまして わらう）
  g.line(smug ? [[x - s * 0.16, y + s * 0.3], [x, y + s * 0.34], [x + s * 0.18, y + s * 0.26]] : [[x - s * 0.14, y + s * 0.32], [x + s * 0.14, y + s * 0.32]], C.K, 1.6);
  g.ell(x, y + s * 0.42, s * 0.18, s * 0.04 * k, C.WD);
}
// 指を 立てた 手（x・y … 手、up … 指先が 光る）
function fzHand(g, x, y, s, C, glow) {
  const k = g.w / g.h;
  g.ell(x, y, s * 0.06, s * 0.06 * k, C.W);
  g.line([[x, y], [x, y - s * 0.12]], C.WD, 3.2);
  g.line([[x, y], [x, y - s * 0.12]], C.W, 2);
  if (glow) spark(g, x, y - s * 0.14, s * 0.06, C.Y, '#ffffff');
}
