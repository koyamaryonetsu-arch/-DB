const SL = {
  D: '#1a1030', DD: '#0a0618', DL: '#3a2a60', // 闇
  S: '#fff4c0', SL: '#ffffff', SD: '#e8c870', // 星の 光
  V: '#8a4ae0', VL: '#c8a0ff', // むらさきの 光
  T: '#9ae0ff', // なみだ
  G: '#6ad0a0', R: '#ff6a5a', O: '#ffb040', B: '#a0a0ff', // くらい心の 色（よくばり・いかり・ひとりじめ・見くだす）
  K: '#2a1a40', // 顔の 線
  E: '#ff3a5a', EL: '#ffd0d8', I: '#2a1a50', // 赤い 目・中の 闇
};
// 星の 形（x・y … まんなか、r … 大きさ、n … とげ、in … 内がわの わりあい）
function star(g, x, y, r, c, n = 5, inner = 0.45, rot = -Math.PI / 2) {
  const k = g.w / g.h;
  const pts = [];
  for (let i = 0; i < n * 2; i++) {
    const a = rot + (i * Math.PI) / n;
    const rr = i % 2 ? r * inner : r;
    pts.push([x + Math.cos(a) * rr, y + Math.sin(a) * rr * k]);
  }
  g.poly(pts, c);
}
// 星の 顔（目を とじる・ひらく）
function starFace(g, x, y, s, open, sad, tear) {
  const C = SL;
  for (const d of [-1, 1]) {
    if (open) {
      g.ell(x + d * s * 0.3, y, s * 0.11, s * 0.14, '#ffffff');
      g.ell(x + d * s * 0.3, y + s * 0.02, s * 0.06, s * 0.09, C.K);
    } else g.line([[x + d * s * 0.42, y + (sad ? -0.02 : 0.02) * s], [x + d * s * 0.18, y + (sad ? 0.04 : -0.02) * s]], C.K, 2);
    if (tear) {
      g.ell(x + d * s * 0.3, y + s * 0.3, s * 0.05, s * 0.09, C.T);
      g.ell(x + d * s * 0.32, y + s * 0.5, s * 0.04, s * 0.07, C.T);
    }
  }
  g.line(sad ? [[x - s * 0.14, y + s * 0.32], [x, y + s * 0.26], [x + s * 0.14, y + s * 0.32]] : [[x - s * 0.14, y + s * 0.26], [x, y + s * 0.32], [x + s * 0.14, y + s * 0.26]], C.K, 1.8);
}
function solitus(g0, f) {
  const g = fit(g0, 248);
  const C = SL;
  const k = g.w / g.h;
  const stage = f >= 4 ? 3 : f >= 2 ? 2 : 1;
  const up = f % 2;
  if (stage === 1) {
    // 1だんめ: 黒い 大きな 星（くらい心を まとう）。まわりに 4つの くらい心の 玉
    for (const [x, y, r] of [[0.16, 0.3, 0.12], [0.86, 0.26, 0.11], [0.12, 0.74, 0.1], [0.88, 0.76, 0.12]]) g.ell(x, y, r, r * k, C.DL);
    star(g, 0.5, 0.52, 0.47, C.DD, 5, 0.5, -Math.PI / 2 + (up ? 0.06 : 0));
    star(g, 0.5, 0.52, 0.43, C.D, 5, 0.5, -Math.PI / 2 + (up ? 0.06 : 0));
    star(g, 0.5, 0.52, 0.3, C.DL, 5, 0.5, -Math.PI / 2 + (up ? 0.06 : 0));
    // 中の 小さな 光（本当の 星が ちらりと 見える）
    star(g, 0.5, 0.5, 0.07, C.SD, 5, 0.45);
    g.ell(0.5, 0.5, 0.025, 0.025 * k, C.SL);
    // 赤い 目（闇の 顔）
    for (const d of [-1, 1]) {
      g.poly([[0.5 + d * 0.06, 0.4], [0.5 + d * 0.2, 0.34], [0.5 + d * 0.18, 0.42]], '#ff3a5a');
      g.poly([[0.5 + d * 0.08, 0.4], [0.5 + d * 0.17, 0.365], [0.5 + d * 0.16, 0.41]], '#ffd0d8');
    }
    // くらい心の 玉（よくばり・いかり・ひとりじめ・見くだす）
    const orbs = [[0.14, 0.18, C.G], [0.86, 0.16, C.R], [0.1, 0.86, C.O], [0.9, 0.86, C.B]];
    orbs.forEach(([x, y, c], i) => {
      const dy = up ? (i % 2 ? 0.02 : -0.02) : 0;
      g.ell(x, y + dy, 0.07, 0.07 * k, C.DD);
      g.ell(x, y + dy, 0.055, 0.055 * k, c);
      g.ell(x - 0.015, y + dy - 0.015, 0.018, 0.018 * k, '#ffffff');
    });
    return;
  }
  if (stage === 2) {
    // 2だんめ: ひとりぼっちの 星（ひびの ある 黒い からの 中で、ひざを かかえる 小さな 星）
    g.ell(0.5, 0.54, 0.44, 0.44, C.DD);
    g.ell(0.5, 0.54, 0.4, 0.4, C.D);
    // からの ひび（光が もれる）
    for (const pts of [[[0.22, 0.2], [0.3, 0.32], [0.26, 0.42]], [[0.8, 0.26], [0.72, 0.36], [0.78, 0.48]], [[0.4, 0.92], [0.46, 0.82], [0.42, 0.74]]]) g.line(pts, up ? C.S : C.SD, 2.2);
    // 中の 星（小さく まるまる）
    g.ell(0.5, 0.56, 0.24, 0.24 * k, '#2a1a50');
    star(g, 0.5, 0.55, 0.22, C.SD, 5, 0.55, -Math.PI / 2 - 0.15);
    star(g, 0.5, 0.55, 0.19, C.S, 5, 0.55, -Math.PI / 2 - 0.15);
    // ひざを かかえる 手
    g.ell(0.42, 0.66, 0.06, 0.04, C.SD);
    g.ell(0.58, 0.66, 0.06, 0.04, C.SD);
    starFace(g, 0.5, 0.52, 0.16, false, true, true);
    // なみだの つぶ（コマ1）
    if (up) for (const [x, y] of [[0.36, 0.78], [0.62, 0.82], [0.5, 0.9]]) g.ell(x, y, 0.015, 0.025, C.T);
    // まわりの 小さな 星（とおい）
    for (const [x, y] of [[0.08, 0.1], [0.92, 0.12], [0.06, 0.6], [0.94, 0.56]]) spark(g, x, y, 0.025, C.VL, '#ffffff');
    return;
  }
  // 3だんめ: 光が あふれる 星（からが くずれて、星が 手を のばす）
  for (let i = 0; i < 12; i++) {
    const a = (i / 12) * Math.PI * 2 + (up ? 0.13 : 0);
    g.line([[0.5 + Math.cos(a) * 0.2, 0.5 + Math.sin(a) * 0.2 * k], [0.5 + Math.cos(a) * 0.48, 0.5 + Math.sin(a) * 0.48 * k]], i % 2 ? C.VL : C.SD, 2);
  }
  // くずれる からの かけら
  for (const [x, y, r] of [[0.12, 0.2, 0.06], [0.88, 0.24, 0.05], [0.14, 0.8, 0.05], [0.86, 0.82, 0.06]]) {
    g.poly([[x - r, y], [x, y - r], [x + r, y + r * 0.4], [x - r * 0.3, y + r]], C.D);
  }
  star(g, 0.5, 0.5, 0.36, C.SD, 5, 0.5);
  star(g, 0.5, 0.5, 0.32, C.S, 5, 0.5);
  star(g, 0.5, 0.5, 0.18, C.SL, 5, 0.5);
  // 手を のばす
  g.line([[0.36, 0.56], [0.2, 0.52 - (up ? 0.06 : 0)]], C.SD, 6);
  g.line([[0.64, 0.56], [0.8, 0.52 - (up ? 0.06 : 0)]], C.SD, 6);
  for (const x of [0.2, 0.8]) g.ell(x, 0.52 - (up ? 0.06 : 0), 0.03, 0.03 * k, C.SL);
  starFace(g, 0.5, 0.47, 0.16, true, false, !up);
}

