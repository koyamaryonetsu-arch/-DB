// ───── 星見の目玉 ─────
const GAZER = {
  W: '#f4f0e8', WS: '#c8c0b0', V: '#d84a6a', // 白目・かげ・血の すじ
  I: '#8a4ad8', IL: '#c89aff', P: '#1a1026', // ひとみ
  B: '#4a2a6a', BL: '#7a4aa8', // こうもりの はね
  Y: '#ffe680', // 星
};
// 星見の目玉: 大きな 目玉に こうもりの はね。ひとみの 中に 星。下に 細い しょっ手。
// コマ1で はねが 上がり、ひとみが 動く
function gazerEye(g0, f) {
  const g = fit(g0, 38);
  const C = GAZER;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? -0.1 : 0;
  // はね
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.2), 0.4], [X(0.36), 0.12 + up], [X(0.48), 0.24 + up], [X(0.42), 0.4], [X(0.46), 0.52], [X(0.34), 0.48], [X(0.26), 0.56]], C.B);
    g.line([[X(0.22), 0.42], [X(0.36), 0.14 + up], [X(0.47), 0.25 + up]], C.BL, 1.1);
    g.line([[X(0.22), 0.42], [X(0.44), 0.5]], C.BL, 0.8);
  }
  // しょっ手
  for (let i = 0; i < 3; i++) {
    const x0 = 0.42 + i * 0.08;
    const leg = bez([[x0, 0.7], [x0 + (f ? 0.04 : -0.04), 0.82], [x0 - (f ? 0.03 : -0.03), 0.96]], 8);
    taper(g, leg, 0.04, 0.008, C.BL);
  }
  // 目玉
  R(0.5, 0.48, 0.25, C.WS);
  R(0.49, 0.47, 0.23, C.W);
  // 血の すじ
  for (const [a, b] of [[[0.3, 0.42], [0.36, 0.45]], [[0.68, 0.58], [0.62, 0.55]], [[0.34, 0.6], [0.39, 0.57]]]) g.line([a, b], C.V, 0.8);
  // ひとみ（星）
  const lx = f ? -0.04 : 0.02;
  R(0.5 + lx, 0.48, 0.12, C.I);
  R(0.48 + lx, 0.46, 0.06, C.IL);
  R(0.5 + lx, 0.48, 0.055, C.P);
  spark(g, 0.5 + lx, 0.48, 0.035, C.Y, C.W);
  // まぶたの ふち
  g.line([[0.3, 0.36], [0.5, 0.25], [0.7, 0.36]], C.BL, 1.4);
}

// ───── 星の番人アルゴス ─────
const ARG = {
  N: '#1e2450', NL: '#3a4a8a', NH: '#6a7ac8', ND: '#10142e', // 星空の 石の 体
  G: '#e8c060', GL: '#fff0a8', GD: '#a07a2a', // 金の ふち・星座の 線
  S: '#c8ccd8', SL: '#eef0f8', SD: '#8a8ea8', // 白い 石の かぶと・よろい
  E: '#7af0ff', EL: '#e8ffff', // 目の 光
  P: '#2a0e3a', // ひとみ
  H: '#b8a8ff', // 後光の わ
};
// 目の 場所（え の 大きさの わりあい。client/battle-ch5.js が 読まれて いる 間 光らせる）。左・右・ひたい
export const ARGOS_EYES = [[0.43, 0.25], [0.57, 0.25], [0.5, 0.17]];
// 星の番人アルゴス: 塔の てっぺんに うかぶ、星空の 石で できた 大きな 守り手（正面）。
// うしろに 星の ついた 後光の わと、星空の まくの つばさ。白い 石の かぶとに 目が 3つ（左右と ひたいの たての 目）。
// 体には 金の 星座の 線。大きな 2本の うでで、星の ついた つえと 光の 玉を 持つ。下は 雲に とける 長い 衣。
// コマ1で ひとみが 動き、うでが 少し 上がって、後光の 星が またたく
function argos(g0, f) {
  const g = fit(g0, 112);
  const C = ARG;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const lift = f ? -0.015 : 0;
  // ── 後光の わ ──
  g.ell(0.5, 0.28, 0.36, 0.27, C.H);
  g.ell(0.5, 0.28, 0.34, 0.255, C.ND);
  g.ell(0.5, 0.28, 0.3, 0.225, C.N);
  for (let i = 0; i < 12; i++) {
    const a = (i / 12) * Math.PI * 2 + (f ? 0.13 : 0);
    const x = 0.5 + Math.cos(a) * 0.35, y = 0.28 + Math.sin(a) * 0.25;
    if (i % 3 === 0) spark(g, x, y, f ? 0.03 : 0.022, C.GL, C.EL);
    else R(x, y, 0.008, C.G);
  }
  // ── 星空の まくの つばさ（左右）──
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.14), 0.36], [X(0.3), 0.14], [X(0.46), 0.1], [X(0.49), 0.3], [X(0.44), 0.52], [X(0.36), 0.46], [X(0.3), 0.6], [X(0.2), 0.52]], C.ND);
    g.poly([[X(0.16), 0.37], [X(0.31), 0.17], [X(0.45), 0.13], [X(0.47), 0.31], [X(0.425), 0.5], [X(0.355), 0.44], [X(0.3), 0.565], [X(0.21), 0.5]], C.NL);
    g.poly([[X(0.2), 0.38], [X(0.32), 0.22], [X(0.43), 0.18], [X(0.44), 0.32], [X(0.4), 0.45], [X(0.33), 0.4], [X(0.24), 0.46]], C.N);
    // つばさの ほねの ひかり
    g.line([[X(0.2), 0.38], [X(0.32), 0.22], [X(0.43), 0.18]], C.NH, 1);
    g.line([[X(0.33), 0.4], [X(0.4), 0.3]], C.NH, 0.8);
    // つばさの 星
    for (const [x, y, r] of [[0.3, 0.28, 0.008], [0.38, 0.22, 0.01], [0.42, 0.36, 0.007], [0.34, 0.4, 0.009], [0.26, 0.4, 0.006]]) R(X(x), y, r, C.EL);
    g.line([[X(0.3), 0.28], [X(0.38), 0.22], [X(0.42), 0.36], [X(0.34), 0.4]], C.H, 0.8);
    g.line([[X(0.16), 0.37], [X(0.31), 0.17], [X(0.45), 0.13]], C.G, 1.4);
  }
  // ── 長い 衣（下は 雲に とける）──
  g.poly([[0.32, 0.6], [0.68, 0.6], [0.76, 0.92], [0.24, 0.92]], C.ND);
  g.poly([[0.335, 0.61], [0.665, 0.61], [0.74, 0.9], [0.26, 0.9]], C.N);
  g.poly([[0.36, 0.62], [0.44, 0.62], [0.4, 0.9], [0.3, 0.9]], C.NL);
  g.line([[0.5, 0.62], [0.5, 0.9]], C.G, 1.4);
  for (const [x, y] of [[0.42, 0.72], [0.58, 0.68], [0.62, 0.8], [0.36, 0.84], [0.52, 0.82]]) R(x, y, 0.007, C.EL);
  g.line([[0.42, 0.72], [0.52, 0.82], [0.62, 0.8], [0.58, 0.68]], C.H, 0.7);
  // 雲
  for (const [x, y, r] of [[0.26, 0.93, 0.08], [0.4, 0.95, 0.09], [0.56, 0.95, 0.09], [0.72, 0.93, 0.08], [0.5, 0.91, 0.07]]) {
    g.ell(x, y, r, r * 0.45, C.SD);
    g.ell(x - r * 0.15, y - r * 0.1, r * 0.75, r * 0.32, C.SL);
  }
  // ── 体（よろい）──
  g.poly([[0.32, 0.36], [0.68, 0.36], [0.7, 0.5], [0.66, 0.63], [0.34, 0.63], [0.3, 0.5]], C.SD);
  g.poly([[0.335, 0.37], [0.665, 0.37], [0.685, 0.5], [0.65, 0.62], [0.35, 0.62], [0.315, 0.5]], C.S);
  g.poly([[0.35, 0.38], [0.45, 0.38], [0.42, 0.6], [0.35, 0.6], [0.33, 0.5]], C.SL);
  // むねの 星空の まど と 星座
  g.poly([[0.42, 0.42], [0.58, 0.42], [0.6, 0.52], [0.5, 0.58], [0.4, 0.52]], C.ND);
  g.poly([[0.43, 0.43], [0.57, 0.43], [0.585, 0.515], [0.5, 0.565], [0.415, 0.515]], C.N);
  const cons = [[0.45, 0.46], [0.5, 0.45], [0.55, 0.48], [0.52, 0.53], [0.47, 0.51]];
  g.line(cons, C.G, 0.9);
  cons.forEach(([x, y], i) => R(x, y, i === 1 ? 0.01 : 0.007, i === 1 ? C.GL : C.EL));
  // 金の ふち・こし帯
  g.line([[0.335, 0.37], [0.665, 0.37]], C.G, 1.6);
  g.rect(0.33, 0.6, 0.34, 0.03, C.GD);
  g.rect(0.33, 0.6, 0.34, 0.015, C.G);
  R(0.5, 0.615, 0.022, C.GL);
  // ── かた あて ──
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.ell(X(0.2), 0.38, 0.09, 0.06, C.SD);
    g.ell(X(0.2), 0.375, 0.08, 0.05, C.S);
    g.ell(X(0.19), 0.36, 0.04, 0.02, C.SL);
    g.line([[X(0.12), 0.39], [X(0.2), 0.33], [X(0.28), 0.39]], C.G, 1.2);
  }
  // ── 左うで（星の つえ）──
  const ly = lift;
  g.poly([[0.24, 0.4], [0.18, 0.46 + ly], [0.16, 0.58 + ly], [0.22, 0.6 + ly], [0.27, 0.48]], C.SD);
  g.poly([[0.245, 0.41], [0.19, 0.465 + ly], [0.175, 0.57 + ly], [0.215, 0.585 + ly], [0.26, 0.48]], C.S);
  // つえ
  g.line([[0.15, 0.2 + ly], [0.17, 0.86 + ly]], C.GD, 3);
  g.line([[0.15, 0.2 + ly], [0.17, 0.86 + ly]], C.G, 1.6);
  spark(g, 0.15, 0.17 + ly, f ? 0.06 : 0.05, C.GL, C.EL);
  R(0.15, 0.17 + ly, 0.014, C.E);
  // 手
  R(0.19, 0.6 + ly, 0.03, C.SD);
  R(0.188, 0.595 + ly, 0.024, C.S);
  // ── 右うで（光の 玉）──
  const ry = -lift * 2;
  g.poly([[0.76, 0.4], [0.82, 0.46 + ry], [0.84, 0.56 + ry], [0.78, 0.58 + ry], [0.73, 0.48]], C.SD);
  g.poly([[0.755, 0.41], [0.81, 0.465 + ry], [0.825, 0.55 + ry], [0.785, 0.565 + ry], [0.74, 0.48]], C.S);
  R(0.82, 0.62 + ry, 0.06, C.H);
  R(0.82, 0.62 + ry, 0.048, C.E);
  R(0.81, 0.61 + ry, 0.022, C.EL);
  R(0.81, 0.585 + ry, 0.028, C.SD);
  R(0.81, 0.58 + ry, 0.022, C.S);
  // ── 頭（白い 石の かぶと。目が 3つ）──
  g.poly([[0.38, 0.14], [0.5, 0.08], [0.62, 0.14], [0.64, 0.3], [0.58, 0.36], [0.42, 0.36], [0.36, 0.3]], C.SD);
  g.poly([[0.39, 0.15], [0.5, 0.095], [0.61, 0.15], [0.625, 0.295], [0.575, 0.345], [0.425, 0.345], [0.375, 0.295]], C.S);
  g.poly([[0.4, 0.16], [0.47, 0.12], [0.45, 0.3], [0.4, 0.28]], C.SL);
  // かぶとの かざり（金の つの 3本）
  g.poly([[0.48, 0.1], [0.5, 0.0], [0.52, 0.1]], C.G);
  g.poly([[0.385, 0.16], [0.33, 0.05], [0.41, 0.135]], C.G);
  g.poly([[0.615, 0.16], [0.67, 0.05], [0.59, 0.135]], C.G);
  g.line([[0.5, 0.01], [0.5, 0.09]], C.GL, 0.8);
  // 顔の かげ（目の まわり）
  g.poly([[0.39, 0.21], [0.61, 0.21], [0.6, 0.3], [0.4, 0.3]], C.ND);
  // 3つの 目（左右は よこ長、ひたいは たて長）
  const lx = f ? 0.01 : -0.006;
  for (const [i, [ex, ey]] of ARGOS_EYES.entries()) {
    const tall = i === 2;
    const rx = tall ? 0.018 : 0.035, ry = tall ? 0.04 : 0.02;
    if (tall) {
      g.ell(ex, ey, rx + 0.008, ry + 0.008, C.ND);
    }
    g.ell(ex, ey, rx, ry, C.E);
    g.ell(ex + lx * (tall ? 0.4 : 1), ey, tall ? 0.009 : 0.013, tall ? 0.022 : 0.014, C.P);
    R(ex - rx * 0.4, ey - ry * 0.4, 0.005, C.EL);
  }
  // 口もとの 金の もよう
  g.line([[0.45, 0.32], [0.5, 0.335], [0.55, 0.32]], C.G, 1);
}

