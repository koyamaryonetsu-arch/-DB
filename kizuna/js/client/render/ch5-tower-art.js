const CLOCK = {
  B: '#c89a4a', BL: '#e8c87a', BH: '#fff0c0', BD: '#8a6a2a', // 真ちゅう
  I: '#5a6070', IL: '#8a92a4', ID: '#2e323e', // 鉄
  L: '#7ae8ff', LL: '#e0fbff', // レンズの 目
  R: '#c8402a', // ランプ
};
// 歯車（x, y … まんなか、r … 大きさ、n … 歯の 数、rot … 回り）
function gear(g, x, y, r, n, rot, c, cL, cD) {
  const k = g.w / g.h;
  for (let i = 0; i < n; i++) {
    const a = rot + (i / n) * Math.PI * 2;
    const w = 0.35 / n * Math.PI;
    const p = (rr, da) => [x + Math.cos(a + da) * rr, y + Math.sin(a + da) * rr * k];
    g.poly([p(r * 0.8, -w), p(r * 1.18, -w * 0.6), p(r * 1.18, w * 0.6), p(r * 0.8, w)], cD);
  }
  g.ell(x, y, r, r * k, cD);
  g.ell(x, y, r * 0.86, r * 0.86 * k, c);
  g.ell(x - r * 0.15, y - r * 0.15 * k, r * 0.4, r * 0.3 * k, cL);
  g.ell(x, y, r * 0.3, r * 0.3 * k, cD);
}
// からくりの守り手: 真ちゅうと 鉄の からくり兵（正面）。むねに 大きな 歯車、頭は まるい かぶとに レンズの 目が 1つ、
// 右うでは 歯車の カッター、左うでは たて。せなかに ぜんまいの カギ。コマ1で 歯車が 回り、カッターを ふり上げる
function clockworkGuard(g0, f) {
  const g = fit(g0, 46);
  const C = CLOCK;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const rot = f ? 0.4 : 0;
  // せなかの ぜんまいの カギ
  g.rect(0.47, 0.1, 0.06, 0.12, C.ID);
  g.ell(0.42, 0.08, 0.06, 0.04, C.BD);
  g.ell(0.58, 0.08, 0.06, 0.04, C.BD);
  g.ell(0.42, 0.08, 0.035, 0.022, C.B);
  g.ell(0.58, 0.08, 0.035, 0.022, C.B);
  // 足
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.rect(X(0.1) - 0.05, 0.72, 0.1, 0.18, C.ID);
    g.rect(X(0.1) - 0.04, 0.72, 0.08, 0.17, C.I);
    g.rect(X(0.1) - 0.04, 0.73, 0.025, 0.15, C.IL);
    g.ell(X(0.1), 0.78, 0.055, 0.03, C.BD);
    g.poly([[X(0.1) - 0.08, 0.9], [X(0.1) + 0.08, 0.9], [X(0.1) + 0.09, 0.97], [X(0.1) - 0.09, 0.97]], C.BD);
    g.poly([[X(0.1) - 0.07, 0.9], [X(0.1) + 0.07, 0.9], [X(0.1) + 0.075, 0.94], [X(0.1) - 0.075, 0.94]], C.B);
  }
  // 体（たる の 形）
  g.poly([[0.3, 0.36], [0.7, 0.36], [0.74, 0.5], [0.7, 0.74], [0.3, 0.74], [0.26, 0.5]], C.BD);
  g.poly([[0.31, 0.375], [0.69, 0.375], [0.72, 0.5], [0.685, 0.725], [0.315, 0.725], [0.28, 0.5]], C.B);
  g.poly([[0.32, 0.39], [0.4, 0.39], [0.37, 0.7], [0.32, 0.7], [0.3, 0.5]], C.BL);
  // たがの おび・びょう
  for (const y of [0.42, 0.68]) {
    g.rect(0.28, y - 0.012, 0.44, 0.024, C.ID);
    for (let i = 0; i < 6; i++) R(0.31 + i * 0.076, y, 0.008, C.BH);
  }
  // むねの 大きな 歯車
  gear(g, 0.5, 0.55, 0.1, 10, rot, C.I, C.IL, C.ID);
  R(0.5, 0.55, 0.018, C.BL);
  // 左うで（たて）
  g.poly([[0.26, 0.4], [0.18, 0.44], [0.16, 0.6], [0.22, 0.62], [0.27, 0.5]], C.ID);
  g.ell(0.17, 0.6, 0.1, 0.12, C.BD);
  g.ell(0.17, 0.6, 0.085, 0.105, C.I);
  g.ell(0.16, 0.58, 0.04, 0.05, C.IL);
  R(0.17, 0.6, 0.02, C.B);
  // 右うで（歯車の カッター。コマ1で ふり上げる）
  const ay = f ? -0.12 : 0;
  g.poly([[0.74, 0.4], [0.82, 0.44 + ay * 0.5], [0.84, 0.56 + ay], [0.78, 0.58 + ay], [0.73, 0.5]], C.ID);
  g.poly([[0.745, 0.41], [0.81, 0.45 + ay * 0.5], [0.825, 0.55 + ay], [0.785, 0.565 + ay], [0.74, 0.5]], C.I);
  gear(g, 0.84, 0.6 + ay, 0.075, 8, -rot * 1.5, C.IL, C.BL, C.ID);
  R(0.84, 0.6 + ay, 0.015, C.R);
  // 頭（まるい かぶと）
  g.ell(0.5, 0.25, 0.14, 0.12, C.BD);
  g.ell(0.5, 0.245, 0.125, 0.105, C.B);
  g.ell(0.45, 0.2, 0.06, 0.035, C.BH);
  g.rect(0.36, 0.27, 0.28, 0.03, C.ID);
  // レンズの 目
  R(0.5, 0.25, 0.055, C.ID);
  R(0.5, 0.25, 0.042, C.L);
  R(0.49, 0.24, f ? 0.02 : 0.014, C.LL);
  // 頭の 上の ランプ
  g.rect(0.485, 0.11, 0.03, 0.04, C.ID);
  R(0.5, 0.11, 0.022, C.R);
  if (f) R(0.495, 0.105, 0.008, C.BH);
}

// ───── 塔のつむじ風 ─────
const WINDS = {
  A: '#3aa888', AL: '#7ad8b0', AH: '#bff0d8', AW: '#e8fff4', AD: '#1e6a5a', // 風
  E: '#0e3a32', // 目
};
// 塔のつむじ風: 下から 上へ ひろがる うずまきの 風（たつまき）。まん中に 目と 口の ある 小さな 顔。
// まわりに 葉っぱと 石の かけら。コマ1で うずが 回る
function towerWind(g0, f) {
  const g = fit(g0, 40);
  const C = WINDS;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const ph = f ? 0.5 : 0;
  // うずの わ（下ほど 小さい）
  const rings = [[0.92, 0.07], [0.8, 0.12], [0.66, 0.18], [0.5, 0.25], [0.34, 0.32], [0.2, 0.38]];
  rings.forEach(([y, r], i) => {
    const sh = Math.sin(i * 1.3 + ph * Math.PI) * 0.04;
    g.ell(0.5 + sh, y, r + 0.02, 0.05, C.AD);
    g.ell(0.5 + sh, y, r, 0.04, i % 2 ? C.A : C.AL);
    g.line([[0.5 + sh - r * 0.8, y - 0.01], [0.5 + sh, y - 0.035], [0.5 + sh + r * 0.6, y - 0.02]], C.AW, 1.2);
  });
  // うずの すじ
  for (let i = 0; i < 3; i++) {
    const s = bez([[0.5, 0.95], [0.3 + i * 0.1 + ph * 0.2, 0.7], [0.75 - i * 0.12 - ph * 0.2, 0.45], [0.2 + i * 0.28, 0.16]], 12);
    g.line(s, i === 1 ? C.AW : C.AH, 1);
  }
  // 顔
  R(0.5, 0.48, 0.1, C.AL);
  R(0.5, 0.48, 0.08, C.AH);
  g.ell(0.46, 0.46, 0.018, 0.03, C.E);
  g.ell(0.54, 0.46, 0.018, 0.03, C.E);
  R(0.455, 0.45, 0.006, C.AW);
  R(0.535, 0.45, 0.006, C.AW);
  g.ell(0.5, 0.53, 0.02, f ? 0.02 : 0.012, C.E);
  // 葉っぱと 石の かけら
  const bits = f ? [[0.1, 0.3], [0.88, 0.22], [0.16, 0.7], [0.86, 0.6]] : [[0.14, 0.22], [0.9, 0.34], [0.1, 0.6], [0.84, 0.72]];
  bits.forEach(([x, y], i) => {
    if (i % 2) g.poly([[x - 0.03, y], [x, y - 0.04], [x + 0.03, y], [x, y + 0.04]], C.A);
    else R(x, y, 0.02, C.AD);
  });
}

// ───── 星くらげ ─────
const JELLY = {
  J: '#8ac8ff', JL: '#c8e8ff', JH: '#f0faff', JD: '#4a7ad8', JDD: '#2a3a8a', // かさ
  Y: '#ffe680', YL: '#fffbe0', // 星の もよう
  E: '#1a2050', // 目
};
// 星くらげ: すきとおった かさに 星の もよう。下に 光る 足が ゆらゆら。かさの 下に 小さな 目。
// コマ1で かさが ちぢんで、足が ゆれる
function starJelly(g0, f) {
  const g = fit(g0, 48);
  const C = JELLY;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const sq = f ? 0.03 : 0;
  // 足（光る ひも）
  for (let i = 0; i < 6; i++) {
    const x0 = 0.3 + i * 0.08;
    const sw = (i % 2 ? 1 : -1) * (f ? 0.05 : -0.03);
    const leg = bez([[x0, 0.5], [x0 + sw, 0.66], [x0 - sw, 0.8], [x0 + sw * 0.5, 0.96]], 10);
    taper(g, leg, 0.035, 0.008, C.JD);
    taper(g, leg.slice(0, 7), 0.018, 0.006, C.JL);
    R(leg[10][0], leg[10][1], 0.012, C.Y);
  }
  // かさ
  g.ell(0.5, 0.36 + sq * 0.5, 0.36 + sq, 0.27 - sq, C.JDD);
  g.ell(0.5, 0.355 + sq * 0.5, 0.34 + sq, 0.255 - sq, C.J);
  g.ell(0.44, 0.27, 0.18, 0.12, C.JL);
  g.ell(0.38, 0.22, 0.06, 0.04, C.JH);
  // かさの ふち（なみなみ）
  for (let i = 0; i < 7; i++) {
    const x = 0.22 + i * 0.094;
    g.ell(x, 0.56 - sq * 0.5, 0.05, 0.035, C.JD);
    g.ell(x, 0.55 - sq * 0.5, 0.04, 0.025, C.J);
  }
  // 星の もよう（中に 光る 星）
  for (const [x, y, s] of [[0.36, 0.38, 0.05], [0.6, 0.3, 0.06], [0.68, 0.44, 0.04], [0.5, 0.18, 0.035]]) spark(g, x, y, s, C.Y, C.YL);
  // 目
  g.ell(0.44, 0.48, 0.022, 0.03, C.E);
  g.ell(0.56, 0.48, 0.022, 0.03, C.E);
  R(0.435, 0.47, 0.008, C.JH);
  R(0.555, 0.47, 0.008, C.JH);
}

