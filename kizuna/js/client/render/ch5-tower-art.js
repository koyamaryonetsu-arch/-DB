// ───── 石のガーゴイル ─────
const GARG = {
  S: '#7a7a8a', SL: '#a6a6b4', SH: '#d0d0dc', SD: '#50505e', SDD: '#2a2a38', // 石
  W: '#5e5e70', WL: '#8a8aa0', // つばさの まく
  E: '#ffb03a', EL: '#fff0b0', // 目
  K: '#5a8a5a', // こけ
};
// 石のガーゴイル: つばさを 広げて うかぶ 石像（正面）。2本の つの・とがった 耳・ひらいた 口と キバ・つめの ある 足。
// 体には ひびと こけ。コマ1で つばさが 上がり、目が 光る
function stoneGargoyle(g0, f) {
  const g = fit(g0, 50);
  const C = GARG;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? -0.08 : 0;
  // つばさ（左右。こうもりの ような 石の まく）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    const tip = [X(0.48), 0.1 + up];
    g.poly([[X(0.12), 0.36], [X(0.3), 0.14 + up * 0.6], tip, [X(0.44), 0.36 + up * 0.3], [X(0.4), 0.5], [X(0.32), 0.44], [X(0.26), 0.56], [X(0.18), 0.5]], C.SDD);
    g.poly([[X(0.14), 0.37], [X(0.3), 0.17 + up * 0.6], [X(0.46), 0.13 + up], [X(0.42), 0.36 + up * 0.3], [X(0.39), 0.47], [X(0.32), 0.42], [X(0.26), 0.53], [X(0.19), 0.48]], C.W);
    // ほね
    for (const [x, y] of [[0.46, 0.13 + up], [0.4, 0.46], [0.27, 0.52]]) g.line([[X(0.14), 0.37], [X(x), y]], C.WL, 1.2);
    g.line([[X(0.14), 0.37], [X(0.3), 0.17 + up * 0.6], [X(0.46), 0.13 + up]], C.SL, 1.4);
  }
  // 足（しゃがんだ ひざと つめ）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.ell(X(0.12), 0.74, 0.08, 0.1, C.SD);
    g.ell(X(0.12), 0.72, 0.065, 0.08, C.S);
    g.poly([[X(0.06), 0.82], [X(0.18), 0.82], [X(0.2), 0.92], [X(0.04), 0.92]], C.SD);
    for (const dx of [0.05, 0.11, 0.17]) g.poly([[X(dx - 0.02), 0.91], [X(dx + 0.02), 0.91], [X(dx), 0.97]], C.SDD);
  }
  // しっぽ
  const tail = bez([[0.56, 0.78], [0.7, 0.9], [0.84, 0.86], [0.88, 0.74]], 10);
  taper(g, tail, 0.05, 0.015, C.SD);
  g.poly([[0.88, 0.7], [0.92, 0.76], [0.85, 0.77]], C.SDD);
  // 体
  g.ell(0.5, 0.6, 0.17, 0.2, C.SDD);
  g.ell(0.5, 0.59, 0.155, 0.185, C.S);
  g.ell(0.46, 0.54, 0.07, 0.09, C.SL);
  // むねの もよう（あばら）と ひび
  for (const y of [0.56, 0.62, 0.68]) g.line([[0.42, y], [0.5, y + 0.02], [0.58, y]], C.SD, 1);
  g.line([[0.56, 0.48], [0.6, 0.55], [0.57, 0.6]], C.SDD, 0.9);
  // こけ
  R(0.38, 0.7, 0.025, C.K);
  R(0.62, 0.52, 0.018, C.K);
  // うで（左右に たらす）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.13), 0.48], [X(0.2), 0.52], [X(0.21), 0.68], [X(0.16), 0.7]], C.SD);
    g.poly([[X(0.14), 0.5], [X(0.185), 0.53], [X(0.195), 0.66], [X(0.165), 0.68]], C.S);
    for (const dx of [0.15, 0.18, 0.21]) g.poly([[X(dx - 0.012), 0.69], [X(dx + 0.012), 0.69], [X(dx), 0.74]], C.SDD);
  }
  // 頭
  g.ell(0.5, 0.33, 0.12, 0.11, C.SDD);
  g.ell(0.5, 0.33, 0.105, 0.095, C.S);
  g.ell(0.47, 0.3, 0.05, 0.035, C.SL);
  // つの・耳
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.05), 0.25], [X(0.11), 0.08], [X(0.09), 0.26]], C.SD);
    g.line([[X(0.065), 0.24], [X(0.105), 0.1]], C.SH, 0.9);
    g.poly([[X(0.09), 0.3], [X(0.18), 0.24], [X(0.11), 0.35]], C.SD);
  }
  // 目（光る）
  for (const s of [-1, 1]) {
    R(0.5 + s * 0.045, 0.32, 0.022, C.SDD);
    R(0.5 + s * 0.045, 0.32, f ? 0.017 : 0.013, C.E);
    R(0.5 + s * 0.045 - 0.004, 0.316, 0.006, C.EL);
  }
  // 口と キバ
  g.poly([[0.44, 0.37], [0.56, 0.37], [0.53, 0.41], [0.47, 0.41]], C.SDD);
  g.poly([[0.455, 0.37], [0.47, 0.37], [0.462, 0.395]], C.SH);
  g.poly([[0.53, 0.37], [0.545, 0.37], [0.538, 0.395]], C.SH);
  // 石の くず（コマ1）
  if (f) for (const [x, y] of [[0.3, 0.86], [0.7, 0.9], [0.5, 0.97]]) R(x, y, 0.012, C.SL);
}

