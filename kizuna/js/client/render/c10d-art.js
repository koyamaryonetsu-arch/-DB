const SILVER = ['#c8d0e0', '#7a8498', '#f4f8ff'];

// ───── かがみの番兵（鏡の かけらの よろいの 兵。48×56）─────
// trim … かざりの 色（番兵 … 金・門番 … 青銀・まどいの門番 … むらさき銀）
const TRIM = { c10d_shard: ['#e8c050', '#a8822a'], c10d_shard_w: ['#9ad0e8', '#4a7a98'], c10d_shard_m: ['#c8a0e8', '#7a5a98'] };
function shardBody(g0, f, body, trim) {
  const g = fit(g0, 48);
  const [B, BD, BL] = body;
  const [T, TD] = trim;
  const k = g.w / g.h;
  const up = f ? 0.015 : 0;
  // 足（とがった かけら）
  g.poly([[0.36, 0.72], [0.46, 0.72], [0.44, 0.95], [0.34, 0.95]], BD);
  g.poly([[0.54, 0.72], [0.64, 0.72], [0.66, 0.95], [0.56, 0.95]], BD);
  g.poly([[0.37, 0.73], [0.44, 0.73], [0.42, 0.9]], B);
  g.poly([[0.56, 0.73], [0.63, 0.73], [0.62, 0.9]], B);
  // 体（かけらを かさねた むね）
  g.poly([[0.3, 0.36 - up], [0.7, 0.36 - up], [0.66, 0.74], [0.34, 0.74]], BD);
  g.poly([[0.32, 0.38 - up], [0.5, 0.36 - up], [0.46, 0.6], [0.34, 0.7]], B);
  g.poly([[0.5, 0.36 - up], [0.68, 0.38 - up], [0.66, 0.7], [0.54, 0.6]], B);
  g.poly([[0.36, 0.62], [0.5, 0.56], [0.64, 0.62], [0.62, 0.72], [0.38, 0.72]], B);
  g.poly([[0.35, 0.4 - up], [0.42, 0.39 - up], [0.36, 0.56]], BL);
  g.poly([[0.55, 0.4 - up], [0.6, 0.4 - up], [0.57, 0.52]], BL);
  // むねの まん中の かざり（金の ひし形）
  g.poly([[0.5, 0.44 - up], [0.545, 0.5 - up], [0.5, 0.56 - up], [0.455, 0.5 - up]], TD);
  g.poly([[0.5, 0.455 - up], [0.53, 0.5 - up], [0.5, 0.545 - up], [0.47, 0.5 - up]], T);
  // かた（とがった かけら）
  g.poly([[0.22, 0.38 - up], [0.34, 0.33 - up], [0.36, 0.44 - up], [0.26, 0.46 - up]], BD);
  g.poly([[0.78, 0.38 - up], [0.66, 0.33 - up], [0.64, 0.44 - up], [0.74, 0.46 - up]], BD);
  g.poly([[0.24, 0.38 - up], [0.33, 0.35 - up], [0.34, 0.42 - up]], BL);
  // うで・鏡の つるぎ（右）・小さな たて（左）
  g.line([[0.27, 0.45 - up], [0.24, 0.6]], BD, 3);
  g.line([[0.73, 0.45 - up], [0.78, 0.58]], BD, 3);
  g.poly([[0.77, 0.6], [0.81, 0.58], [0.9, 0.18 - up * 2], [0.88, 0.16 - up * 2]], SILVER[1]);
  g.poly([[0.78, 0.59], [0.8, 0.585], [0.885, 0.2 - up * 2]], SILVER[2]);
  g.rect(0.74, 0.58, 0.1, 0.025, T);
  g.poly([[0.14, 0.52], [0.26, 0.5], [0.27, 0.66], [0.2, 0.72], [0.13, 0.66]], TD);
  g.poly([[0.155, 0.53], [0.25, 0.515], [0.255, 0.65], [0.2, 0.7], [0.145, 0.65]], B);
  g.poly([[0.17, 0.54], [0.2, 0.535], [0.17, 0.62]], BL);
  // かぶと（かけらの とさか・目の すき間）
  g.poly([[0.38, 0.36 - up], [0.36, 0.2 - up], [0.42, 0.12 - up], [0.58, 0.12 - up], [0.64, 0.2 - up], [0.62, 0.36 - up]], BD);
  g.poly([[0.39, 0.34 - up], [0.38, 0.21 - up], [0.43, 0.14 - up], [0.57, 0.14 - up], [0.62, 0.21 - up], [0.61, 0.34 - up]], B);
  g.poly([[0.41, 0.2 - up], [0.45, 0.15 - up], [0.46, 0.28 - up]], BL);
  g.poly([[0.46, 0.13 - up], [0.5, 0.02 - up], [0.54, 0.13 - up]], T);
  g.poly([[0.48, 0.12 - up], [0.5, 0.05 - up], [0.52, 0.12 - up]], TD);
  g.rect(0.41, 0.23 - up, 0.18, 0.04, '#1a1026');
  for (const ex of [0.46, 0.54]) g.ell(ex, 0.25 - up, 0.018, 0.014 * k, f ? '#ffffff' : T);
  // きらり
  spark(g, 0.36, 0.46 - up + (f ? 0.02 : 0), 0.03, '#ffffff', '#ffffff');
  spark(g, 0.66, 0.66, 0.022, BL, '#ffffff');
}
// ───── かがみのかけら（小さな うかぶ 鏡の かけら。36×36）─────
function smallShard(g0, f, body) {
  const g = fit(g0, 36);
  const [B, BD, BL] = body;
  const k = g.w / g.h;
  const up = f ? 0.04 : 0;
  // かげ
  g.ell(0.5, 0.94, 0.2, 0.04, 'rgba(0,0,0,0.25)');
  // ひし形の かけら（ふちは 金）
  g.poly([[0.5, 0.04 - up], [0.86, 0.46 - up], [0.5, 0.86 - up], [0.14, 0.46 - up]], '#a8822a');
  g.poly([[0.5, 0.08 - up], [0.81, 0.46 - up], [0.5, 0.81 - up], [0.19, 0.46 - up]], BD);
  g.poly([[0.5, 0.12 - up], [0.77, 0.46 - up], [0.5, 0.77 - up], [0.23, 0.46 - up]], B);
  g.poly([[0.5, 0.12 - up], [0.6, 0.24 - up], [0.34, 0.5 - up], [0.26, 0.44 - up]], BL);
  // 目（1つ・まばたき）
  g.ell(0.5, 0.46 - up, 0.1, 0.1 * k, '#ffffff');
  if (f) g.rect(0.42, 0.455 - up, 0.16, 0.02, '#1a1026');
  else g.ell(0.51, 0.47 - up, 0.05, 0.05 * k, '#1a1026');
  // きらきら
  spark(g, 0.82, 0.18 - up, 0.06, '#ffffff', '#ffffff');
  spark(g, 0.16, 0.74 - up, 0.045, BL, '#ffffff');
}

// ───── 幕の ボス: ミラーレ（224×240）─────
const MR = {
  G: '#e8c050', GD: '#a8822a', GL: '#fff0a8', GG: '#7a5a18', // 金の ふち
  M: '#c8dcf4', MD: '#8aa4c8', ML: '#f0f8ff', MS: '#a8bedc', // 鏡の ガラス（うすい 青銀）
  F: '#e8d8f0', FD: '#b8a0c8', // 顔（ガラスに うすく うつる。うす むらさきの 銀）
  E: '#4a3a6a', // 目
  K: '#1a1026', W: '#ffffff', P: '#e8a8c0', // ほっぺ
  R: '#d04a6a', // 王かんの 石
  C: '#3a2a4a', // ひび
};
function mirror(g0, f) {
  const g = fit(g0, 224);
  const C = MR;
  const k = g.w / g.h;
  const crack = f >= 2;
  const fr = f % 2;
  const up = fr ? 0.008 : 0;
  // 下の 足（金の 台）
  g.poly([[0.38, 0.86], [0.62, 0.86], [0.68, 0.96], [0.32, 0.96]], C.GD);
  g.poly([[0.4, 0.87], [0.6, 0.87], [0.64, 0.94], [0.36, 0.94]], C.G);
  // 金の ふち（大きな たまご形）
  g.ell(0.5, 0.48 - up, 0.38, 0.4, C.GG);
  g.ell(0.5, 0.48 - up, 0.365, 0.385, C.GD);
  g.ell(0.5, 0.475 - up, 0.35, 0.37, C.G);
  // ふちの もよう（小さな 玉）
  for (let i = 0; i < 16; i++) {
    const a = (i / 16) * Math.PI * 2;
    g.ell(0.5 + Math.cos(a) * 0.335, 0.475 - up + Math.sin(a) * 0.355, 0.012, 0.012 * k, i % 2 ? C.GL : C.GD);
  }
  // 鏡の ガラス
  g.ell(0.5, 0.48 - up, 0.3, 0.32, C.MD);
  g.ell(0.5, 0.48 - up, 0.29, 0.31, C.M);
  // ガラスの ひかり（ななめの すじ）
  g.poly([[0.3, 0.3 - up], [0.36, 0.24 - up], [0.28, 0.5 - up], [0.24, 0.48 - up]], C.ML);
  g.poly([[0.68, 0.62 - up], [0.73, 0.56 - up], [0.7, 0.7 - up]], C.ML);
  // 顔（ガラスに うすく うつる）
  g.ell(0.5, 0.5 - up, 0.2, 0.21, C.FD);
  g.ell(0.5, 0.495 - up, 0.19, 0.2, C.F);
  // ほっぺ
  g.ell(0.38, 0.56 - up, 0.035, 0.02, C.P);
  g.ell(0.62, 0.56 - up, 0.035, 0.02, C.P);
  // 目（ねむそうな おもい まぶた ／ ひびの 時は まるく 見ひらく）
  for (const ex of [0.42, 0.58]) {
    if (crack) {
      g.ell(ex, 0.46 - up, 0.035, 0.035 * k, C.W);
      g.ell(ex, 0.465 - up, 0.016, 0.016 * k, C.E);
    } else {
      g.ell(ex, 0.47 - up, 0.036, 0.022, C.W);
      g.ell(ex, 0.478 - up, 0.016, 0.014, C.E);
      // おもい まぶた（上 はんぶんを おおう）
      g.poly([[ex - 0.042, 0.47 - up], [ex - 0.03, 0.44 - up], [ex + 0.03, 0.44 - up], [ex + 0.042, 0.47 - up]], C.FD);
      g.line([[ex - 0.042, 0.47 - up], [ex + 0.042, 0.47 - up]], C.E, 1.6);
    }
    // まゆ（いばった 形・ひびの 時は 上がる）
    g.line([[ex - 0.04, (crack ? 0.4 : 0.42) - up], [ex + 0.035, (crack ? 0.395 : 0.415) - up + (ex < 0.5 ? 0.008 : -0.008)]], C.E, 2);
  }
  // つんと 上を むいた 鼻
  g.poly([[0.5, 0.49 - up], [0.53, 0.54 - up], [0.49, 0.545 - up]], C.FD);
  // くるんと した ひげ
  g.line(bez([[0.5, 0.57 - up], [0.44, 0.565 - up], [0.41, 0.58 - up], [0.42, 0.59 - up]], 8), C.E, 2.2);
  g.line(bez([[0.5, 0.57 - up], [0.56, 0.565 - up], [0.59, 0.58 - up], [0.58, 0.59 - up]], 8), C.E, 2.2);
  // 口（いばった 小さな 口 ／ ひびの 時は「お」の 口）
  if (crack) g.ell(0.5, 0.62 - up, 0.02, 0.02 * k, C.E);
  else g.line(bez([[0.47, 0.615 - up], [0.5, 0.605 - up], [0.53, 0.615 - up]], 6), C.E, 1.6);
  // あくびの「ふわぁ」の 泡（コマ 1）
  if (fr && !crack) for (const [x, y, r] of [[0.62, 0.66, 0.012], [0.65, 0.7, 0.009]]) g.ell(x, y - up, r, r * k, C.ML);
  // ふちの 上の 小さな 王かんの かざり
  g.poly([[0.4, 0.12 - up], [0.42, 0.04 - up], [0.46, 0.09 - up], [0.5, 0.02 - up], [0.54, 0.09 - up], [0.58, 0.04 - up], [0.6, 0.12 - up]], C.GD);
  g.poly([[0.41, 0.115 - up], [0.425, 0.06 - up], [0.46, 0.1 - up], [0.5, 0.04 - up], [0.54, 0.1 - up], [0.575, 0.06 - up], [0.59, 0.115 - up]], C.G);
  g.ell(0.5, 0.09 - up, 0.014, 0.014 * k, C.R);
  // まわりに うかぶ 小さな 手鏡（3つ）
  const hands = [[0.08, 0.3], [0.9, 0.36], [0.12, 0.72], [0.88, 0.76]];
  hands.forEach(([x, y], i) => {
    const bob = (fr ? 1 : -1) * (i % 2 ? 0.012 : -0.012);
    const cy = y + bob;
    g.line([[x, cy + 0.05], [x + (x < 0.5 ? 0.02 : -0.02), cy + 0.11]], C.GD, 3);
    g.ell(x, cy, 0.055, 0.055 * k, C.GD);
    g.ell(x, cy, 0.045, 0.045 * k, crack && i === 1 ? C.MS : C.M);
    g.ell(x - 0.014, cy - 0.014, 0.014, 0.014 * k, C.ML);
  });
  if (!crack) {
    for (const [x, y] of [[0.22, 0.14], [0.8, 0.16], [0.86, 0.56]]) spark(g, x, y + (fr ? 0.01 : 0), 0.022, C.GL, C.W);
  } else {
    // ひび（ガラスに ジグザグの 線）
    g.line([[0.58, 0.2], [0.54, 0.3], [0.6, 0.36], [0.52, 0.46], [0.58, 0.56], [0.5, 0.7], [0.54, 0.78]], C.C, 2.4);
    g.line([[0.6, 0.36], [0.7, 0.4], [0.74, 0.5]], C.C, 1.8);
    g.line([[0.52, 0.46], [0.36, 0.42], [0.28, 0.5]], C.C, 1.8);
    g.line([[0.5, 0.7], [0.4, 0.74]], C.C, 1.6);
    // あせ
    for (const [x, y] of [[0.3, 0.36], [0.7, 0.32]]) g.ell(x, y - up + (fr ? 0.01 : 0), 0.01, 0.018, C.ML);
  }
}

// ───── うつし身（予備の え: 人の 形の 鏡の かげ。40×48）─────
const CP = { M: '#a8c8f0', MD: '#6a8ab8', ML: '#e8f4ff' };
function copy(g0, f) {
  const g = fit(g0, 40);
  const C = CP;
  const k = g.w / g.h;
  const up = f ? 0.02 : 0;
  g.ell(0.5, 0.22 - up, 0.12, 0.12 * k, C.MD);
  g.ell(0.5, 0.215 - up, 0.105, 0.105 * k, C.M);
  g.poly([[0.32, 0.36 - up], [0.68, 0.36 - up], [0.7, 0.8], [0.3, 0.8]], C.MD);
  g.poly([[0.34, 0.38 - up], [0.66, 0.38 - up], [0.67, 0.78], [0.33, 0.78]], C.M);
  g.poly([[0.36, 0.4 - up], [0.44, 0.4 - up], [0.36, 0.7]], C.ML);
  g.rect(0.36, 0.8, 0.1, 0.14, C.MD);
  g.rect(0.54, 0.8, 0.1, 0.14, C.MD);
  spark(g, 0.62, 0.2 - up, 0.05, C.ML, '#ffffff');
}

export function addC10dArt(ART) {
  // 門の 番人（新しい 絵 2つ ＋ 色ちがい 2つ）・体の 色 ＝ まくの 色
  const allBody = [SILVER, ...Object.values(C10D_VEIL_ART)].flat();
  for (const sp of ['c10d_shard', 'c10d_shard_w', 'c10d_shard_m']) {
    const trim = TRIM[sp];
    const p = [...new Set([...allBody, ...trim, ...SILVER, '#1a1026', '#ffffff', '#a8822a'])];
    ART[sp] = { size: [48, 56], pal: p, draw: (g, f) => shardBody(g, f, SILVER, trim) };
    for (const [id, body] of Object.entries(C10D_VEIL_ART)) ART[`${sp}~${id}`] = { size: [48, 56], pal: p, draw: (g, f) => shardBody(g, f, body, trim) };
  }
  const ps = [...new Set([...allBody, '#a8822a', '#1a1026', '#ffffff', 'rgba(0,0,0,0.25)'])];
  ART.c10d_shard_s = { size: [36, 36], pal: ps, draw: (g, f) => smallShard(g, f, SILVER) };
  for (const [id, body] of Object.entries(C10D_VEIL_ART)) ART[`c10d_shard_s~${id}`] = { size: [36, 36], pal: ps, draw: (g, f) => smallShard(g, f, body) };
  // ボス（2倍の こまかさ。monsters-c10d.js の artScale 0.5。台本の showMon でも 大きく）
  ART.c10d_mirare = { size: [224, 240], npc: 0.6, pal: pal(MR), draw: mirror };
  ART.c10d_copy = { size: [40, 48], pal: pal(CP), draw: copy };
}
