// 第5章 Step 9（B9）「星のない広間」の ノクト（本気）と 魔王ソリトゥスの え（shared/data/monsters-final.js）
// render/monsters.js が addFinalArt を よぶ。かきかたは ch5-earth-mon-art.js と おなじ（g … w・h の わりあいで かく。f … 0 か 1 の コマ）
// ・nocto_2 … フードを 下ろした 黒い かみの 少年。黒むらさきの 闇の ほのおを まとい、右手の 紋章が 大きく 光る（コマ1で 手を かかげる）
// ・solitus … 星のない 夜の マントを 大きく 広げた、とても 大きな 魔王（176×124。がめんの はばの 7わり）。
//   黒い いばらの かんむりに 消えかけた 星・白い お面の ような 顔に つめたい 青白い 目・むねに 大きな 闇の 口（きずなを 食べる）・
//   長い うでの 先の 闇の つめ・こわれた くさりの かけら（ちぎれた つながり）・足もとは もやに とけて 消える。コマ1で 目と 口が 光る
import { fit, spark } from './ch3-draw.js?v=345c127ce483';

// ───── ノクト（本気） ─────
const N2 = {
  C: '#1c1e34', CL: '#2c3052', CH: '#444c78', CD: '#0e0f1c', // マント
  S: '#f0d0b0', SD: '#c8a080', // はだ
  H: '#141418', HL: '#2c2c3e', // 黒い かみ
  E: '#4a3a7a', EL: '#c8b8ff', // 目
  M: '#8a5ae0', ML: '#e6d8ff', MD: '#4a2a8a', // 紋章の 光・闇の ほのお
  R: '#6a2240', // マントの うら
};
function nocto2(g0, f) {
  const g = fit(g0, 76);
  const C = N2;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // 闇の ほのお（うしろ。体の まわりから 外へ のびる ほのおの した。コマで ゆれる）
  const sw = f ? 0.025 : -0.025;
  const tongues = [
    [0.22, 0.92, 0.06, 0.8 + sw, 0.12], [0.2, 0.64, 0.04, 0.5 - sw, 0.11], [0.26, 0.38, 0.1, 0.2 + sw, 0.1], [0.38, 0.22, 0.3 - sw, 0.02, 0.09],
    [0.62, 0.22, 0.7 + sw, 0.02, 0.09], [0.74, 0.38, 0.9, 0.2 - sw, 0.1], [0.8, 0.64, 0.96, 0.5 + sw, 0.11], [0.78, 0.92, 0.94, 0.8 - sw, 0.12],
  ];
  for (const [bx, by, tx, ty, w] of tongues) {
    g.poly([[bx - w / 2, by], [(bx + tx) / 2 - sw, (by + ty) / 2], [tx, ty], [bx + w / 2, by + w * 0.2]], C.MD);
    g.poly([[bx - w / 4, by], [(bx * 2 + tx) / 3 + sw, (by * 2 + ty) / 3], [bx + w / 4, by + w * 0.1]], C.M);
  }
  for (const [x, y] of [[0.1, 0.42], [0.92, 0.46], [0.18, 0.14], [0.84, 0.12]]) g.poly([[x, y - 0.04], [x + 0.015, y], [x, y + 0.015], [x - 0.015, y]], C.ML);
  // マント（ちぎれた すそ）
  g.poly([[0.5, 0.2], [0.78, 0.34], [0.86, 0.94], [0.76, 0.9], [0.68, 0.96], [0.58, 0.9], [0.5, 0.96], [0.42, 0.9], [0.32, 0.96], [0.24, 0.9], [0.14, 0.94], [0.22, 0.34]], C.R);
  g.poly([[0.5, 0.22], [0.74, 0.36], [0.8, 0.9], [0.2, 0.9], [0.26, 0.36]], C.C);
  g.poly([[0.3, 0.38], [0.4, 0.36], [0.36, 0.86], [0.26, 0.86]], C.CL);
  // 足
  for (const s of [-1, 1]) g.rect(0.5 + s * 0.05 - 0.03, 0.84, 0.06, 0.12, C.CD);
  // 体の まえ
  g.poly([[0.41, 0.36], [0.59, 0.36], [0.61, 0.62], [0.39, 0.62]], C.CH);
  g.line([[0.5, 0.38], [0.5, 0.6]], C.CD, 1);
  // 左うで
  g.poly([[0.32, 0.4], [0.22, 0.5], [0.22, 0.68], [0.28, 0.68], [0.32, 0.52]], C.CL);
  R(0.25, 0.7, 0.03, C.S);
  // 右うで（紋章。コマ1で 高く かかげる）
  if (f) {
    g.poly([[0.66, 0.4], [0.78, 0.3], [0.82, 0.16], [0.87, 0.18], [0.83, 0.34], [0.69, 0.47]], C.CL);
    R(0.85, 0.14, 0.04, C.S);
    spark(g, 0.85, 0.11, 0.11, C.M, C.ML);
    g.ell(0.85, 0.11, 0.05, 0.04, C.ML);
  } else {
    g.poly([[0.68, 0.4], [0.78, 0.5], [0.78, 0.66], [0.72, 0.66], [0.67, 0.52]], C.CL);
    R(0.75, 0.68, 0.035, C.S);
    spark(g, 0.75, 0.68, 0.07, C.M, C.ML);
  }
  // 顔（フードは 背中に 下ろしている）
  g.ell(0.5, 0.31, 0.15, 0.06, C.CD);
  g.ell(0.5, 0.21, 0.1, 0.1, C.SD);
  g.ell(0.5, 0.205, 0.093, 0.093, C.S);
  // 黒い かみ（長い 前がみ・うしろは はねる）
  g.poly([[0.39, 0.18], [0.42, 0.09], [0.5, 0.06], [0.6, 0.09], [0.62, 0.18], [0.6, 0.24], [0.56, 0.17], [0.52, 0.24], [0.47, 0.16], [0.42, 0.24]], C.H);
  g.poly([[0.39, 0.16], [0.33, 0.2], [0.38, 0.24]], C.H);
  g.poly([[0.61, 0.16], [0.67, 0.2], [0.62, 0.24]], C.H);
  g.line([[0.46, 0.09], [0.48, 0.16]], C.HL, 0.8);
  // 目（本気の 目。コマ1で 光る）
  for (const s of [-1, 1]) {
    g.ell(0.5 + s * 0.037, 0.23, 0.017, 0.013, f ? C.EL : C.E);
    g.line([[0.5 + s * 0.015, 0.212], [0.5 + s * 0.06, 0.205]], C.H, 0.8);
  }
  g.line([[0.48, 0.27], [0.52, 0.27]], C.SD, 0.8);
}

// ───── 魔王ソリトゥス ─────
const SL = {
  K: '#07060f', KD: '#030208', KL: '#141228', KM: '#221e40', KH: '#36305e', // 夜の マント・体
  W: '#e8e4f4', WD: '#a8a2c4', WS: '#6a6488', // お面の 顔
  E: '#7ad8ff', EL: '#e8fbff', // つめたい 目
  M: '#3a0a24', MD: '#18040e', MT: '#c8c0d8', // 闇の 口・きば
  T: '#2a2440', TL: '#4a4270', // いばらの かんむり
  S: '#f0e8a0', SD: '#8a8458', SW: '#ffffff', // 消えかけた 星
  CH: '#5a5470', CHL: '#8a84a0', // こわれた くさり
  V: '#4a2a7a', VL: '#7a5ac0', // もや・ふち の 光
};
function solitus(g0, f) {
  const g = fit(g0, 176);
  const C = SL;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const b = f ? 0.012 : 0; // コマ1で マントが ふくらむ
  // ── 夜の マント（つばさの ように 大きく 広がる。ふちは ぎざぎざ）──
  const wing = (s) => {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.06), 0.18], [X(0.2), 0.1 - b], [X(0.34), 0.08 - b], [X(0.46), 0.16], [X(0.49 + b / 2), 0.3], [X(0.47), 0.42], [X(0.5), 0.52 + b], [X(0.44), 0.6], [X(0.46), 0.72],
      [X(0.38), 0.74], [X(0.36), 0.86], [X(0.28), 0.82], [X(0.22), 0.94], [X(0.16), 0.86], [X(0.08), 0.96]], C.KD);
    g.poly([[X(0.08), 0.2], [X(0.2), 0.13 - b], [X(0.33), 0.12 - b], [X(0.43), 0.19], [X(0.45 + b / 2), 0.31], [X(0.43), 0.42], [X(0.45), 0.52 + b], [X(0.4), 0.59], [X(0.41), 0.7],
      [X(0.35), 0.71], [X(0.33), 0.82], [X(0.27), 0.79], [X(0.21), 0.9], [X(0.16), 0.83], [X(0.09), 0.9]], C.K);
    // マントの すじ（ほね）
    for (const [x0, y0, x1, y1] of [[0.12, 0.22, 0.3, 0.14], [0.13, 0.3, 0.42, 0.24], [0.14, 0.42, 0.42, 0.44], [0.15, 0.54, 0.38, 0.62], [0.16, 0.68, 0.3, 0.78]]) {
      g.line([[X(x0), y0], [X((x0 + x1) / 2), (y0 + y1) / 2 - 0.02], [X(x1), y1]], C.KM, 1.6);
    }
    // ふちの 光（むらさき）
    g.line([[X(0.2), 0.13 - b], [X(0.33), 0.12 - b], [X(0.43), 0.19], [X(0.45 + b / 2), 0.31]], C.V, 1.2);
    // 消えた 星の あと（マントの 中の 小さな あな）。1つだけ まだ かすかに 光る
    for (const [x, y, i] of [[0.3, 0.3, 0], [0.38, 0.36, 1], [0.24, 0.48, 2], [0.34, 0.54, 3], [0.28, 0.66, 4], [0.4, 0.26, 5]]) {
      R(X(x), y, 0.007, i === (s > 0 ? 2 : 4) && f ? C.SD : C.KH);
    }
  };
  wing(-1);
  wing(1);
  // ── 足もとの もや（体が 闇に とける）──
  for (let i = 0; i < 7; i++) {
    const x = 0.3 + i * 0.067 + (f ? 0.012 : 0);
    g.ell(x, 0.95, 0.06, 0.05, i % 2 ? C.KL : C.KM);
  }
  g.line([[0.28, 0.98], [0.4, 0.93 + (f ? 0.02 : 0)], [0.52, 0.98], [0.64, 0.93], [0.74, 0.97]], C.VL, 1.2);
  // ── 体（大きな よろいの ような むね）──
  g.poly([[0.38, 0.3], [0.62, 0.3], [0.67, 0.5], [0.62, 0.86], [0.38, 0.86], [0.33, 0.5]], C.KD);
  g.poly([[0.39, 0.31], [0.61, 0.31], [0.65, 0.5], [0.61, 0.84], [0.39, 0.84], [0.35, 0.5]], C.KL);
  g.poly([[0.4, 0.33], [0.47, 0.33], [0.44, 0.82], [0.4, 0.82], [0.37, 0.5]], C.KM);
  // むねの もよう（ひびの ような すじ）
  g.line([[0.5, 0.32], [0.5, 0.4]], C.KH, 1);
  g.line([[0.42, 0.72], [0.46, 0.78], [0.5, 0.75], [0.54, 0.79], [0.58, 0.72]], C.KH, 1);
  // ── むねの 闇の 口（きずなを 食べる。コマ1で 大きく ひらく）──
  const mo = f ? 0.035 : 0.02;
  g.ell(0.5, 0.56, 0.09, 0.075 + mo, C.KD);
  g.ell(0.5, 0.56, 0.08, 0.06 + mo, C.MD);
  g.ell(0.5, 0.57, 0.06, 0.035 + mo * 0.8, C.M);
  for (let i = 0; i < 5; i++) {
    const x = 0.44 + i * 0.03;
    g.poly([[x - 0.01, 0.5 - mo * 0.4], [x + 0.01, 0.5 - mo * 0.4], [x, 0.53]], C.MT);
    g.poly([[x - 0.008, 0.62 + mo * 0.4], [x + 0.008, 0.62 + mo * 0.4], [x, 0.59]], C.MT);
  }
  if (f) R(0.5, 0.57, 0.012, C.V);
  // ── 長い うでと 闇の つめ ──
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.poly([[X(0.12), 0.34], [X(0.2), 0.38], [X(0.27), 0.52], [X(0.32), 0.66 - b * 2], [X(0.28), 0.68 - b * 2], [X(0.22), 0.55], [X(0.13), 0.44]], C.KD);
    g.poly([[X(0.13), 0.36], [X(0.19), 0.39], [X(0.25), 0.52], [X(0.3), 0.65 - b * 2], [X(0.28), 0.66 - b * 2], [X(0.22), 0.54], [X(0.14), 0.43]], C.KM);
    // つめ（4本）
    for (let i = 0; i < 4; i++) {
      const bx = 0.3 + i * 0.012, by = 0.66 - b * 2;
      g.line([[X(bx), by], [X(bx + 0.02 + i * 0.006), by + 0.06], [X(bx + 0.012 + i * 0.008), by + 0.1]], C.WS, 1.3);
    }
  }
  // ── こわれた くさり（ちぎれた つながり。手首から たれる）──
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    for (let i = 0; i < 4; i++) {
      const y = 0.7 + i * 0.045 + (f ? 0.008 : 0);
      g.ell(X(0.27 - i * 0.01), y, 0.014, 0.018, C.CH);
      g.ell(X(0.27 - i * 0.01), y, 0.008, 0.01, C.KD);
    }
    g.line([[X(0.255), 0.88], [X(0.245), 0.9], [X(0.26), 0.91]], C.CHL, 1);
  }
  // ── 首と お面の 顔 ──
  g.ell(0.5, 0.31, 0.07, 0.03, C.KD);
  g.ell(0.5, 0.2, 0.075, 0.11, C.WS);
  g.ell(0.5, 0.195, 0.068, 0.1, C.WD);
  g.ell(0.49, 0.185, 0.058, 0.088, C.W);
  // 目の あな（つめたい 青白い 光。コマ1で 強く）
  for (const s of [-1, 1]) {
    g.poly([[0.5 + s * 0.012, 0.17], [0.5 + s * 0.05, 0.16], [0.5 + s * 0.048, 0.2], [0.5 + s * 0.016, 0.205]], C.KD);
    R(0.5 + s * 0.031, 0.183, f ? 0.012 : 0.009, C.E);
    R(0.5 + s * 0.031, 0.183, f ? 0.006 : 0.004, C.EL);
    // なみだの あと
    g.line([[0.5 + s * 0.03, 0.205], [0.5 + s * 0.028, 0.25]], C.WS, 0.9);
  }
  // 口（ほそい すじ）
  g.line([[0.475, 0.255], [0.5, 0.262], [0.525, 0.255]], C.WS, 0.9);
  // ── 黒い いばらの かんむり（まん中に 消えかけた 星）──
  const spikes = [[0.4, 0.13, 0.36, 0.04], [0.44, 0.1, 0.42, 0.02], [0.48, 0.09, 0.47, 0.006], [0.52, 0.09, 0.53, 0.006], [0.56, 0.1, 0.58, 0.02], [0.6, 0.13, 0.64, 0.04]];
  for (const [x0, y0, x1, y1] of spikes) g.poly([[x0 - 0.016, y0 + 0.02], [x0 + 0.016, y0 + 0.02], [x1, y1]], C.T);
  g.poly([[0.4, 0.12], [0.6, 0.12], [0.58, 0.15], [0.42, 0.15]], C.T);
  g.line([[0.41, 0.13], [0.59, 0.13]], C.TL, 0.9);
  spark(g, 0.5, 0.05, f ? 0.03 : 0.022, f ? C.S : C.SD, f ? C.SW : C.S);
  // ── まわりに うかぶ ひとりぼっちの 光（小さな 青い たま）──
  for (const [x, y] of [[0.08, 0.1], [0.92, 0.12], [0.04, 0.5], [0.96, 0.46]]) {
    R(x, y + (f ? -0.015 : 0), 0.012, C.V);
    R(x, y + (f ? -0.015 : 0), 0.006, C.E);
  }
}

export function addFinalArt(ART) {
  // ノクト（本気）・魔王ソリトゥス（図鑑・台本の showMon('nocto_2')・showMon('solitus')）
  ART.nocto_2 = { size: [76, 92], pal: Object.values(N2), draw: nocto2 };
  ART.solitus = { size: [176, 124], npc: 0.5, pal: Object.values(SL), draw: solitus };
}
