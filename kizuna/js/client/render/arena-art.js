const rnd = (i, s = 1) => {
  const v = Math.sin(i * 127.1 * s + 311.7) * 43758.5453;
  return v - Math.floor(v);
};

// かべと 観客席（hor … 地面の たかさ）
export function drawArenaBg(x, d, hor) {
  const top = 14;
  // 上の 観客席（だんだん）
  for (let row = 0; row < 4; row++) {
    const y = top + row * 9;
    x.fillStyle = row % 2 ? '#a87a46' : '#b8884e';
    x.fillRect(0, y, BW, 9);
    x.fillStyle = 'rgba(60,36,16,0.35)';
    x.fillRect(0, y + 8, BW, 1);
    // 観客の 頭（いろいろな 色の ぼうし・かみ）
    for (let k = 0; k < 34; k++) {
      const px = Math.round((k + rnd(k + row * 40, 1.7) * 0.8) * (BW / 34));
      const c = ['#3a2a1a', '#f2e6d0', '#c84a3a', '#2a6ab0', '#e8c24a', '#5a3a22', '#ffffff', '#3a8a4a'][Math.floor(rnd(k * 3 + row, 2.3) * 8)];
      x.fillStyle = '#d8a878';
      x.fillRect(px, y + 3, 3, 4);
      x.fillStyle = c;
      x.fillRect(px, y + 2, 3, 2);
      // 手を ふる 人
      if (rnd(k + row * 7, 5.1) < 0.18) {
        x.fillStyle = '#d8a878';
        x.fillRect(px + 3, y, 1, 3);
      }
    }
  }
  // かべ（石の アーチ）
  const wy = top + 36;
  x.fillStyle = '#c4945a';
  x.fillRect(0, wy, BW, hor - wy);
  x.fillStyle = '#9a6e3e';
  x.fillRect(0, wy, BW, 2);
  for (let k = 0; k < 9; k++) {
    const ax = 6 + k * 29;
    x.fillStyle = '#4a2e16';
    x.fillRect(ax + 4, wy + 8, 14, hor - wy - 8);
    x.beginPath();
    x.arc(ax + 11, wy + 8, 7, Math.PI, 0);
    x.fill();
    x.fillStyle = 'rgba(255,230,180,0.25)';
    x.fillRect(ax + 2, wy + 4, 1, hor - wy - 4);
    x.fillRect(ax + 20, wy + 4, 1, hor - wy - 4);
  }
  // 石の めじ
  x.fillStyle = 'rgba(80,50,20,0.25)';
  for (let y = wy + 6; y < hor; y += 6) x.fillRect(0, y, BW, 1);
  // 赤い 旗（観客席の 上）
  for (let k = 0; k < 6; k++) {
    const fx = 18 + k * 44;
    x.fillStyle = '#6a4a2a';
    x.fillRect(fx, 2, 1, top + 2);
    x.fillStyle = k % 2 ? '#d83a2a' : '#e8b030';
    x.beginPath();
    x.moveTo(fx + 1, 3);
    x.lineTo(fx + 12, 6);
    x.lineTo(fx + 1, 10);
    x.fill();
  }
  // 王者の 席（まん中の 金の 屋根）
  x.fillStyle = '#e8c24a';
  x.fillRect(BW / 2 - 18, top - 4, 36, 4);
  x.fillStyle = '#c83a2a';
  x.fillRect(BW / 2 - 16, top, 32, 6);
}

// ゆか: 砂と 白い 線の 輪・小石
export function drawArenaFloorBg(x, d, hor) {
  x.strokeStyle = 'rgba(255,250,235,0.55)';
  x.lineWidth = 1;
  x.beginPath();
  x.ellipse(BW / 2, hor + (BH - hor) * 0.55, BW * 0.42, (BH - hor) * 0.36, 0, 0, Math.PI * 2);
  x.stroke();
  for (let i = 0; i < 70; i++) {
    const px = Math.round(rnd(i, 3.1) * BW), py = hor + 3 + Math.round(rnd(i, 4.7) * (BH - hor - 4));
    x.fillStyle = i % 4 ? 'rgba(150,110,60,0.45)' : 'rgba(255,240,210,0.6)';
    x.fillRect(px, py, i % 5 ? 1 : 2, 1);
  }
  // かべの 下の かげ
  x.fillStyle = 'rgba(60,36,16,0.25)';
  x.fillRect(0, hor, BW, 3);
}

