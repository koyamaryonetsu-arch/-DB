import { fit, flame, taper, bez, spark } from './ch3-draw.js?v=7033f2971814';

const W = '#ffffff', K = '#1a1010';
const pal = (P) => [...new Set(Object.values(P).map((c) => c.toLowerCase()))];

// まるい ほうの だ円（たて・よこの ひりつを なおす）
const roundOf = (g) => {
  const k = g.w / g.h;
  return (x, y, r, c) => g.ell(x, y, r, r * k, c);
};
// とがった 耳（A・B … ねもと、T … さき。tip … さきの 色、p … さきの 色の ぶぶんの わりあい）
function ear(g, A, B, T, c, tip, p = 0.4) {
  g.poly([A, T, B], c);
  if (tip) g.poly([T, [T[0] + (A[0] - T[0]) * p, T[1] + (A[1] - T[1]) * p], [T[0] + (B[0] - T[0]) * p, T[1] + (B[1] - T[1]) * p]], tip);
}
// いなずまの 形（x0,y0 から x1,y1 へ ギザギザ。n … おれる 回数）
function zig(g, x0, y0, x1, y1, c, lw = 1, n = 3, amp = 0.05) {
  const pts = [[x0, y0]];
  for (let i = 1; i < n; i++) {
    const t = i / n;
    pts.push([x0 + (x1 - x0) * t + (i % 2 ? amp : -amp), y0 + (y1 - y0) * t]);
  }
  pts.push([x1, y1]);
  g.line(pts, c, lw);
}
// め（くろめ＋ひかり）。iris … 色の ある め の とき
function eyeDot(g, x, y, r, iris, hi = W) {
  const R = roundOf(g);
  R(x, y, r, K);
  if (iris) R(x, y + r * 0.15, r * 0.7, iris);
  if (iris) R(x, y + r * 0.2, r * 0.4, K);
  R(x - r * 0.3, y - r * 0.35, r * 0.38, hi);
}

