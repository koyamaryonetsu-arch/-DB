  // て（コマ0は 小さく むねの 前。コマ1で 左右に ひろげる）
  for (const s of [-1, 1]) {
    const arm = f ? [[cx + s * 0.14, 0.66], [cx + s * 0.3, 0.58]] : [[cx + s * 0.15, 0.64], [cx + s * 0.08, 0.7]];
    g.line(arm, C.YD, 2.6);
    g.line(arm, C.Y, 1.3);
  }
  // 耳（長く、先が 黒い）
  ear(g, [cx - 0.24, 0.38 + b], [cx - 0.08, 0.26 + b], [cx - 0.38, 0.0 + b], C.YD, C.K, 0.45);
  ear(g, [cx - 0.22, 0.36 + b], [cx - 0.1, 0.28 + b], [cx - 0.355, 0.04 + b], C.Y, C.K, 0.42);
  ear(g, [cx + 0.08, 0.26 + b], [cx + 0.24, 0.38 + b], [cx + 0.38, 0.0 + b], C.YD, C.K, 0.45);
  ear(g, [cx + 0.1, 0.28 + b], [cx + 0.22, 0.36 + b], [cx + 0.355, 0.04 + b], C.Y, C.K, 0.42);
  // あたま
  g.ell(cx, 0.44 + b, 0.26, 0.2, C.YD);
  g.ell(cx, 0.435 + b, 0.245, 0.185, C.Y);
  g.ell(cx - 0.08, 0.34 + b, 0.08, 0.035, C.YL);
  // め・はな・口
  eyeDot(g, cx - 0.1, 0.42 + b, 0.055);
  eyeDot(g, cx + 0.1, 0.42 + b, 0.055);
  R(cx, 0.475 + b, 0.012, C.K);
  if (f) g.ell(cx, 0.53 + b, 0.05, 0.045, C.M);
  else g.line([[cx - 0.05, 0.51 + b], [cx - 0.025, 0.53 + b], [cx, 0.51 + b], [cx + 0.025, 0.53 + b], [cx + 0.05, 0.51 + b]], C.K, 0.6);
