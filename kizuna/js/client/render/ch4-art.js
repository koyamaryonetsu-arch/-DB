// サソリ兵: 大きな サソリが 兵士の ように 立つ。こい 青銅いろの こうら・2本の はさみ・頭の 上に まがった 毒ばりの しっぽ・赤い こしぬの
function scorpionSoldier(g0, f) {
  const g = fit(g0, 48);
  const { C, CD, CDD, CL, CLL, GO, GOD, R, RD, RL, P, PL, PD, E, EL } = SCORP;
  const b = f ? 0.012 : 0;
  // ── しっぽ（こしの うしろから みぎを とおって 頭の 上へ。ふしが つながる）──
  const sw = f ? 0.02 : 0;
  const tail = bez([[0.6, 0.66], [1.0, 0.6], [0.95, 0.03 + sw], [0.43, 0.08 + sw]], 40);
  const SEG = [[8, 0.062, 0.05], [13, 0.064, 0.052], [18, 0.066, 0.054], [23, 0.068, 0.056], [28, 0.07, 0.058], [33, 0.07, 0.058], [37, 0.062, 0.052]];
  for (const [i, len, wid] of SEG) {
    const [x0, y0] = tail[i - 2], [x1, y1] = tail[Math.min(40, i + 2)];
    const a = Math.atan2(y1 - y0, x1 - x0);
    const [x, y] = tail[i];
    g.ell(x, y, len + 0.012, wid + 0.012, CDD, a);
    g.ell(x, y, len, wid, C, a);
    g.ell(x - 0.012, y - 0.014, len * 0.55, wid * 0.4, CL, a);
    g.ell(x - 0.02, y - 0.02, len * 0.2, wid * 0.18, CLL, a);
  }
  // どくばり（むらさきの ふくらみ と まがった はり。コマ1で どくの しずく）。かぶとの まえに かく
  const [ex, ey] = tail[tail.length - 1];
  const stinger = () => {
    g.ell(ex - 0.02, ey + 0.012, 0.085, 0.068, PD);
    g.ell(ex - 0.022, ey + 0.007, 0.074, 0.057, P);
    g.ell(ex - 0.04, ey - 0.009, 0.03, 0.02, PL);
    const sting = bez([[ex - 0.08, ey + 0.04], [ex - 0.15, ey + 0.06], [ex - 0.17, ey + 0.15 + sw]], 8);
    taper(g, sting, 0.055, 0.01, CDD);
    taper(g, sting.slice(0, -1), 0.03, 0.008, PL);
    if (f) g.ell(ex - 0.17, ey + 0.205 + sw, 0.014, 0.02, PL);
  };
  // ── あし（3本ずつ。かわりばんこに ふみかえる）──
  const LEGS = [[0.38, 0.68, 0.25, 0.66, 0.17, 0.88], [0.4, 0.73, 0.28, 0.76, 0.23, 0.96], [0.43, 0.78, 0.37, 0.85, 0.35, 0.98]];
  for (const s of [-1, 1]) {
    const X = (x) => (s < 0 ? x : 1 - x);
    LEGS.forEach(([x0, y0, x1, y1, x2, y2], i) => {
      const up = (i + (s < 0 ? 0 : 1) + f) % 2 ? -0.02 : 0;
      const pts = [[X(x0), y0 + b], [X(x1), y1 + up], [X(x2), y2 + up]];
      g.line(pts, CDD, 3.6);
      g.line(pts, CD, 2.2);
      g.line([[X(x0), y0 - 0.01 + b], [X(x1), y1 - 0.012 + up]], C, 0.9);
      g.ell(X(x1), y1 + up, 0.026, 0.026, C);
      g.ell(X(x1) - 0.006, y1 + up - 0.006, 0.01, 0.01, CL);
    });
  }
  // ── どう（たての よろいの ような ふし）──
  g.poly([[0.355, 0.37 + b], [0.645, 0.37 + b], [0.69, 0.5 + b], [0.665, 0.66 + b], [0.615, 0.8 + b], [0.385, 0.8 + b], [0.335, 0.66 + b], [0.31, 0.5 + b]], CDD);
  g.poly([[0.365, 0.38 + b], [0.635, 0.38 + b], [0.675, 0.5 + b], [0.65, 0.66 + b], [0.605, 0.79 + b], [0.395, 0.79 + b], [0.35, 0.66 + b], [0.325, 0.5 + b]], C);
  for (const [y, hw] of [[0.45, 0.165], [0.53, 0.17], [0.61, 0.16], [0.69, 0.14]]) {
    g.line([[0.5 - hw, y + b], [0.5, y + 0.015 + b], [0.5 + hw, y + b]], CDD, 1);
    g.line([[0.5 - hw + 0.02, y + 0.022 + b], [0.5, y + 0.035 + b], [0.5 + hw - 0.02, y + 0.022 + b]], CL, 0.7);
    // ふちの 金の びょう
    g.ell(0.5 - hw + 0.03, y + 0.035 + b, 0.014, 0.012, GO);
    g.ell(0.5 + hw - 0.03, y + 0.035 + b, 0.014, 0.012, GOD);
  }
  g.poly([[0.37, 0.39 + b], [0.45, 0.39 + b], [0.42, 0.46 + b], [0.35, 0.47 + b]], CLL);
  // こしの ベルト と 赤い こしぬの
  const flap = f ? 0.015 : -0.01;
  g.poly([[0.42, 0.79 + b], [0.58, 0.79 + b], [0.6 + flap, 0.95], [0.5, 0.92], [0.4 + flap, 0.95]], RD);
  g.poly([[0.43, 0.79 + b], [0.57, 0.79 + b], [0.585 + flap, 0.93], [0.5, 0.9], [0.415 + flap, 0.93]], R);
  g.line([[0.46, 0.81 + b], [0.45 + flap, 0.9]], RL, 0.8);
  g.rect(0.38, 0.765 + b, 0.24, 0.04, CDD);
  g.rect(0.385, 0.77 + b, 0.23, 0.028, GOD);
  g.rect(0.47, 0.76 + b, 0.06, 0.05, GO);
  // ── あたま（かぶとの ような こうら）──
  g.poly([[0.355, 0.41 + b], [0.335, 0.28 + b], [0.39, 0.2 + b], [0.5, 0.17 + b], [0.61, 0.2 + b], [0.665, 0.28 + b], [0.645, 0.41 + b]], CDD);
  g.poly([[0.365, 0.4 + b], [0.345, 0.28 + b], [0.395, 0.21 + b], [0.5, 0.185 + b], [0.605, 0.21 + b], [0.655, 0.28 + b], [0.635, 0.4 + b]], C);
  g.poly([[0.37, 0.28 + b], [0.41, 0.22 + b], [0.48, 0.2 + b], [0.45, 0.27 + b]], CL);
  g.poly([[0.39, 0.25 + b], [0.42, 0.22 + b], [0.45, 0.215 + b], [0.43, 0.245 + b]], CLL);
  g.poly([[0.49, 0.19 + b], [0.51, 0.19 + b], [0.51, 0.27 + b], [0.49, 0.27 + b]], CD);
  // ほおあて
  g.poly([[0.345, 0.33 + b], [0.4, 0.35 + b], [0.42, 0.42 + b], [0.36, 0.41 + b]], CD);
  g.poly([[0.655, 0.33 + b], [0.6, 0.35 + b], [0.58, 0.42 + b], [0.64, 0.41 + b]], CD);
  // かぶとの すきまの 光る 目
  g.poly([[0.36, 0.29 + b], [0.5, 0.325 + b], [0.64, 0.29 + b], [0.64, 0.33 + b], [0.5, 0.36 + b], [0.36, 0.33 + b]], CDD);
  for (const x of [0.44, 0.56]) {
    g.ell(x, 0.327 + b, 0.032, 0.021, E);
    g.ell(x + (x < 0.5 ? -0.006 : 0.006), 0.323 + b, 0.012, 0.01, EL);
  }
  // 口の 小さな はさみ
  g.poly([[0.44, 0.38 + b], [0.48, 0.38 + b], [0.475, 0.43 + b], [0.455, 0.42 + b]], CL);
  g.poly([[0.52, 0.38 + b], [0.56, 0.38 + b], [0.545, 0.42 + b], [0.525, 0.43 + b]], CL);
  stinger();
  // ── うで と 大きな はさみ（ひだりは 高く ふりあげ、みぎは まえに かまえる）──
  const open = f ? 0.05 : 0.32;
  arm(g, [0.37, 0.43 + b], [0.17, 0.5 + b], [0.14, 0.31 + b], -Math.PI / 2 - 0.2, open, -1, 1);
  arm(g, [0.63, 0.43 + b], [0.8, 0.52 + b], [0.75, 0.63 + b], 1.0, open * 0.8, 1, 0.9);
}

// サソリの うで（かた → ひじ → てくび）と はさみ。ang … ゆびの むき、open … はさみの ひらき、s … そとがわ（-1 ひだり・1 みぎ）、sc … はさみの 大きさ
function arm(g, sh, el, wr, ang, open, s, sc) {
  const { C, CD, CDD, CL, CLL } = SCORP;
  g.line([sh, el, wr], CDD, 5.2);
  g.line([sh, el, wr], C, 3.6);
  g.line([[sh[0], sh[1] - 0.014], [el[0], el[1] - 0.014]], CL, 1);
  g.ell(el[0], el[1], 0.036, 0.034, CDD);
  g.ell(el[0], el[1], 0.028, 0.026, CD);
  g.ell(el[0] - 0.006, el[1] - 0.008, 0.012, 0.011, CLL);
  const k = g.w / g.h;
  const P = (d, a) => [wr[0] + Math.cos(a) * d * sc, wr[1] + Math.sin(a) * d * k * sc];
  // てのひら（ふくらんだ はさみの ねもと）
  const [cx, cy] = P(0.04, ang);
  g.ell(cx, cy, 0.105 * sc, 0.082 * k * sc, CDD, ang);
  g.ell(cx, cy, 0.092 * sc, 0.07 * k * sc, C, ang);
  const [hx, hy] = P(0.035, ang - s * 0.5);
  g.ell(hx, hy, 0.05 * sc, 0.026 * k * sc, CL, ang);
  const [h2x, h2y] = P(0.05, ang - s * 0.55);
  g.ell(h2x, h2y, 0.018 * sc, 0.012 * k * sc, CLL, ang);
  // ゆび（そとがわは うごかない ゆび、うちがわが ひらく）。うちがわに ぎざぎざ
  const sa = ang - s * 0.42, sb = ang + s * 0.42;
  const fx = bez([P(0.1, sa), P(0.19, ang - s * 0.38), P(0.25, ang - s * 0.02)], 8);
  const fm = bez([P(0.1, sb), P(0.18, ang + s * (0.42 + open)), P(0.23, ang + s * (0.16 + open))], 8);
  taper(g, fx, 0.075 * sc, 0.014, CDD);
  taper(g, fx, 0.054 * sc, 0.008, C);
  g.line(fx.slice(1, 6).map(([x, y]) => [x - 0.008, y - 0.008]), CL, 0.8);
  taper(g, fm, 0.068 * sc, 0.014, CDD);
  taper(g, fm, 0.048 * sc, 0.008, CD);
  for (const i of [2, 4]) g.dot(fm[i][0], fm[i][1], CL);
}

