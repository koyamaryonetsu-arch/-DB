// だえんの ふちの てん（a0 → a1 の むき。0 は みぎ、PI/2 は した）
function ellArc(cx, cy, rx, ry, a0, a1, n = 10) {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    out.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return out;
}

// まわした だえん（花びら・はっぱ）。ang の むきに len、よこに wid（どちらも はばの わりあい。たてよこの ちがいも なおす）
function blade(g, cx, cy, ang, dist, len, wid, c) {
  const k = g.w / g.h;
  const x = cx + Math.cos(ang) * dist, y = cy + Math.sin(ang) * dist * k;
  g.ell(x, y, len, wid * k, c, ang);
}

