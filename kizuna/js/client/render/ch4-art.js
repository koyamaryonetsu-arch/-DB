const SAND = {
  B: '#f0bc54', D: '#b47a32', DD: '#865626', M: '#da9c44', L: '#fadc96', LL: '#fff6d6',
  W: '#ffffff', P: '#3a2412', K: '#f4a070', MO: '#6a1a2a', T: '#ff8aa0',
};
// 砂ぷるりん: 金色の 砂つぶで できた ぷるりん。した半分は 砂丘の もよう・あたまの さきは 風で くるんと まがる・すそから 砂が こぼれて ひろがる
function sandSlime(g0, f) {
  const g = fit(g0, 32);
  const { B, D, DD, M, L, LL, W, P, K, MO, T } = SAND;
  const sq = f ? 0.035 : 0;
  const cy = 0.645 + sq / 2, rx = 0.42 + sq, ry = 0.29 - sq;
  // すその 砂の やま（からだから こぼれて ひろがる。でこぼこ）
  const mound = [[0.03, 0.975], [0.07, 0.94], [0.11, 0.915], [0.16, 0.9], [0.22, 0.88], [0.5, 0.87], [0.78, 0.88], [0.85, 0.9], [0.9, 0.915], [0.94, 0.94], [0.97, 0.975]];
  g.poly(mound.map(([x, y]) => [x, y + 0.012]), D);
  g.poly(mound, M);
  // からだ
  g.ell(0.5, cy + 0.02, rx + 0.01, ry + 0.005, D);
  g.ell(0.5, cy, rx, ry, B);
  // あたまの さき（風で くるんと みぎへ まがる）
  const tx = 0.53 + (f ? 0.02 : 0), ty = 0.13 + sq * 1.6;
  g.poly([[0.35, 0.46 + sq], [0.42, 0.3 + sq], [tx, ty], [0.57, 0.3 + sq], [0.65, 0.46 + sq]], B);
  const curl = bez([[tx - 0.01, ty + 0.03], [tx + 0.04, ty - 0.07], [tx + 0.14, ty - 0.06], [tx + 0.13, ty + 0.03]], 10);
  taper(g, curl, 0.07, 0.02, B);
  g.poly([[0.46, 0.34 + sq], [tx, ty + 0.03], [0.5, 0.38 + sq]], L);
  g.line(curl.slice(1, 6).map(([x, y]) => [x - 0.005, y - 0.012]), L, 0.8);
  // した半分は こい 砂（なみの もよう で わける）
  const by = cy + 0.12;
  const a0 = Math.asin(Math.min(0.99, (by - cy) / (ry - 0.01)));
  const arc = ellArc(0.5, cy, rx - 0.01, ry - 0.01, a0, Math.PI - a0, 12);
  const xl = arc[arc.length - 1][0], xr = arc[0][0];
  const wave = [];
  for (let i = 0; i <= 10; i++) wave.push([xl + ((xr - xl) * i) / 10, by + Math.sin(i * 1.3 + (f ? 0.8 : 0)) * 0.02]);
  g.poly([...wave, ...arc], M);
  g.line(wave.slice(1, -1).map(([x, y]) => [x, y - 0.025]), L, 0.9);
  // からだを つたって こぼれる 砂の すじ
  for (const [x0, x1] of [[0.2, 0.17], [0.8, 0.83]]) g.line([[x0, 0.76 + sq], [x1, 0.88]], L, 0.8);
  // 砂つぶ
  for (const [x, y] of [[0.22, 0.52], [0.31, 0.44], [0.7, 0.44], [0.8, 0.55], [0.6, 0.36], [0.16, 0.63], [0.86, 0.66], [0.27, 0.68], [0.73, 0.68]]) g.dot(x, y + sq, D);
  for (const [x, y] of [[0.24, 0.85], [0.4, 0.88], [0.58, 0.9], [0.72, 0.84], [0.5, 0.84]]) g.dot(x, y + sq / 2, DD);
  for (const [x, y] of [[0.07, 0.93], [0.12, 0.95], [0.9, 0.92], [0.94, 0.95]]) g.dot(x, y, DD);
  for (const [x, y] of [[0.35, 0.5], [0.66, 0.52], [0.78, 0.62], [0.2, 0.7], [0.46, 0.4]]) g.dot(x, y + sq, LL);
  // ひかり
  g.ell(0.25, 0.5 + sq, 0.06, 0.04, LL);
  g.ell(0.19, 0.58 + sq, 0.022, 0.032, LL);
  // め・ほっぺ・くち
  g.eye(0.37, 0.6 + sq, 0.07, 0.25, W, P);
  g.eye(0.63, 0.6 + sq, 0.07, 0.25, W, P);
  g.ell(0.25, 0.7 + sq, 0.05, 0.03, K);
  g.ell(0.75, 0.7 + sq, 0.05, 0.03, K);
  g.poly([[0.43, 0.72 + sq], [0.57, 0.72 + sq], [0.5, 0.79 + sq]], MO);
  g.ell(0.5, 0.77 + sq, 0.03, 0.02, T);
  // 風に まう 砂つぶ
  for (const [x, y] of f ? [[0.8, 0.1], [0.88, 0.2]] : [[0.76, 0.18], [0.86, 0.1]]) g.dot(x, y, M);
}

