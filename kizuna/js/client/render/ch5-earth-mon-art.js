// ───── 根っこのこびと ─────
const SPRITE = {
  B: '#8a6a44', BL: '#b08a5a', BD: '#5a4228', BDD: '#3a2a18', // 木の はだ
  L: '#5aa83a', LL: '#9ad860', // 頭の 葉っぱ
  E: '#1a120a', C: '#e8a080', // 目の あな・ほっぺ
};
// 根っこのこびと: 木の 根から 生まれた 小さな せいれい（正面）。まるい 頭に 葉っぱ、根の 足。コマ1で 頭を かしげて からから 鳴らす
function rootSprite(g0, f) {
  const g = fit(g0, 40);
  const C = SPRITE;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const tilt = f ? 0.035 : 0;
  // 根の 足
  for (const [x0, x1] of [[0.38, 0.26], [0.46, 0.42], [0.54, 0.6], [0.62, 0.76]]) {
    g.line([[x0, 0.78], [(x0 + x1) / 2, 0.88], [x1, 0.96]], C.BDD, 2.4);
    g.line([[x0, 0.78], [(x0 + x1) / 2, 0.88], [x1, 0.95]], C.BD, 1.4);
  }
  // 体（小さな こけし の ような 形）
  g.ell(0.5, 0.68, 0.17, 0.16, C.BDD);
  g.ell(0.5, 0.67, 0.155, 0.15, C.B);
  g.ell(0.45, 0.64, 0.06, 0.08, C.BL);
  // うで（小さな 根）
  for (const s of [-1, 1]) g.line([[0.5 + s * 0.14, 0.64], [0.5 + s * 0.24, 0.6 - (f && s > 0 ? 0.06 : 0)], [0.5 + s * 0.27, 0.66]], C.BD, 1.6);
  // 頭
  const hx = 0.5 + tilt;
  g.ell(hx, 0.38, 0.22, 0.2, C.BDD);
  g.ell(hx, 0.375, 0.205, 0.185, C.B);
  g.ell(hx - 0.07, 0.32, 0.08, 0.07, C.BL);
  // 木の すじ
  g.line([[hx - 0.12, 0.25], [hx - 0.09, 0.32]], C.BD, 0.8);
  g.line([[hx + 0.14, 0.28], [hx + 0.11, 0.36]], C.BD, 0.8);
  // 目の あな・口（コマ1は まるい 口）
  for (const s of [-1, 1]) R(hx + s * 0.07, 0.39, 0.035, C.E);
  if (f) R(hx, 0.47, 0.02, C.E);
  else g.ell(hx, 0.47, 0.035, 0.012, C.E);
  for (const s of [-1, 1]) R(hx + s * 0.13, 0.45, 0.022, C.C);
  // 頭の 葉っぱ（2まい）
  g.poly([[hx, 0.2], [hx - 0.14, 0.08], [hx - 0.04, 0.06]], C.L);
  g.poly([[hx, 0.2], [hx + 0.12, 0.04], [hx + 0.16, 0.12]], C.L);
  g.line([[hx, 0.2], [hx - 0.08, 0.09]], C.LL, 0.8);
  g.line([[hx, 0.2], [hx + 0.11, 0.08]], C.LL, 0.8);
  g.rect(hx - 0.01, 0.17, 0.02, 0.04, C.BD);
}

