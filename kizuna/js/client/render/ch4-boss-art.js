  taper(g, pl, 0.036, 0.01, C.TD);
  taper(g, pl, 0.02, 0.005, C.TL);
  g.poly([[0.5, 0.07 + b], [0.532, 0.112 + b], [0.5, 0.155 + b], [0.468, 0.112 + b]], C.GD);
  g.poly([[0.5, 0.082 + b], [0.52, 0.112 + b], [0.5, 0.144 + b], [0.48, 0.112 + b]], C.E);
  R(0.493, 0.102 + b, 0.008, C.EL);
  // ── 手の 上の 砂の うず（まぼろしの 力。コマで まわる）──
  const cx = 0.84, cy = 0.255 + b;
  R(cx, cy + 0.01, 0.03, C.V);
  R(cx, cy + 0.012, 0.014, C.VL);
  for (let i = 0; i < 4; i++) {
    const y = cy + 0.06 - i * 0.032;
    const r = 0.022 + i * 0.016;
    const pts = [];
    for (let t = 0; t <= 8; t++) {
      const a = (f ? Math.PI * 0.9 : 0) + i * 1.3 + (t / 8) * Math.PI * 1.25;
      pts.push([cx + Math.cos(a) * r, y + Math.sin(a) * r * 0.32]);
    }
    g.line(pts, i % 2 ? C.NL : C.N, 1.1);
  }
  const dust = f ? [[0.77, 0.2], [0.91, 0.24], [0.8, 0.31], [0.88, 0.17]] : [[0.78, 0.24], [0.9, 0.2], [0.89, 0.3], [0.82, 0.17]];
