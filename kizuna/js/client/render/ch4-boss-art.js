// 砂の魔神ザイード: 夜の いろの 大きな 魔神。ひろい かた（とげ）・ふとい うでに 金の うでわ・白い 大きな ツメ。
// 頭には 外へ 上へ まがる 2本の つの と、大臣の ターバンと おなじ 赤い 宝石。光る 目・キバの 口・大臣の なごりの とがった ひげ。
// 下半身は まわる 砂の うず（コマで まわる）。まわりに 砂つぶと あやしい 光が まう
function zaidDemon(g0, f) {
  const g = fit(g0, 136);
  const C = ZD;
  const k = g.w / g.h;
  const b = f ? 0.012 : 0;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // ── 砂の うず（下半身。こしから 下へ ろうとの ように ほそく なり、ゆらゆら ゆれる。すじは ななめに まく）──
  const top = 0.56, bot = 0.99;
  const tAt = (y) => (y - top) / (bot - top);
  const cxAt = (y) => 0.5 + Math.sin(tAt(y) * 4 + (f ? 1.2 : 0)) * 0.035 * tAt(y);
  const hwAt = (y) => 0.018 + 0.215 * Math.pow(1 - tAt(y), 1.5);
  const side = (d) => {
    const out = [];
    for (let i = 0; i <= 16; i++) {
      const y = top + ((bot - top) * i) / 16;
      out.push([cxAt(y) + d * hwAt(y), y]);
    }
    return out;
  };
  g.poly([...side(-1), ...side(1).reverse()], C.SD);
  g.poly([...side(-0.92), ...side(0.35).reverse()], C.S);
  // ななめに まく すじ（コマで 下へ ながれる）
  for (let i = 0; i < 7; i++) {
    const y0 = top + 0.02 + i * 0.06 + (f ? 0.03 : 0);
    const y1 = y0 + 0.05;
    if (y1 > bot - 0.03) continue;
    const pts = [];
    for (let t = 0; t <= 10; t++) {
      const u = t / 10;
      const y = y0 + (y1 - y0) * u;
      const xu = -1 + 2 * u;
      pts.push([cxAt(y) + xu * hwAt(y) * 0.96, y + (1 - xu * xu) * 0.018]);
    }
    g.line(pts, i % 2 ? C.SL : C.SD, Math.max(1, 2.6 - i * 0.3));
  }
  // こしの まわりで まわる 砂の わ
  g.ell(0.5, top + 0.012, 0.25, 0.034, C.SD);
  g.ell(0.495, top + 0.006, 0.235, 0.024, C.S);
  g.line([[0.29, top + 0.012], [0.36, top + 0.03], [0.46, top + 0.036]], C.SL, 1.4);
  g.line([[0.56, top + 0.034], [0.66, top + 0.026], [0.72, top + 0.012]], C.SL, 1.2);
  // ふちから はなれる 砂の けむり・下の 先（くるりと まがる）
  for (const s of [-1, 1]) {
    const y = top + (f ? 0.14 : 0.1) + (s > 0 ? 0.06 : 0);
    const x = cxAt(y) + s * hwAt(y);
    taper(g, bez([[x - s * 0.01, y], [x + s * 0.05, y - 0.02], [x + s * 0.08, y + 0.03], [x + s * 0.05, y + 0.06]], 8), 0.03, 0.006, C.SL);
  }
  const ty0 = bot - 0.07;
  taper(g, bez([[cxAt(ty0), ty0], [cxAt(bot) + 0.01, bot - 0.012], [cxAt(bot) + (f ? 0.045 : -0.045), bot - 0.008]], 6), 0.03, 0.006, C.SD);
  // まう 砂つぶ
  const dust = f
    ? [[0.22, 0.7], [0.27, 0.86], [0.78, 0.74], [0.74, 0.9], [0.3, 0.95], [0.66, 0.97], [0.17, 0.82], [0.84, 0.8]]
    : [[0.24, 0.76], [0.29, 0.92], [0.77, 0.68], [0.71, 0.86], [0.34, 0.97], [0.62, 0.95], [0.18, 0.88], [0.83, 0.86]];
  dust.forEach(([x, y], i) => R(x, y, i % 3 ? 0.007 : 0.01, i % 2 ? C.SH : C.SL));
  // ── からだ（かたが ひろく、こしへ ほそく）──
  g.poly([[0.5, 0.235 + b], [0.66, 0.25 + b], [0.78, 0.29 + b], [0.79, 0.37 + b], [0.7, 0.45 + b], [0.635, 0.52 + b], [0.625, 0.6], [0.375, 0.6], [0.365, 0.52 + b], [0.3, 0.45 + b], [0.21, 0.37 + b], [0.22, 0.29 + b], [0.34, 0.25 + b]], C.BD);
  g.poly([[0.5, 0.245 + b], [0.655, 0.26 + b], [0.765, 0.298 + b], [0.775, 0.366 + b], [0.69, 0.442 + b], [0.625, 0.515 + b], [0.615, 0.59], [0.385, 0.59], [0.375, 0.515 + b], [0.31, 0.442 + b], [0.225, 0.366 + b], [0.235, 0.298 + b], [0.345, 0.26 + b]], C.B);
  // むね・おなかの すじ と 月明かり（ひだりが 明るい）
  g.ell(0.425, 0.31 + b, 0.06, 0.03, C.BL);
  g.ell(0.41, 0.3 + b, 0.03, 0.013, C.BH);
  g.line([[0.5, 0.29 + b], [0.43, 0.345 + b], [0.36, 0.335 + b]], C.BD, 1.8);
  g.line([[0.5, 0.29 + b], [0.57, 0.345 + b], [0.64, 0.335 + b]], C.BD, 1.8);
  g.line([[0.5, 0.29 + b], [0.5, 0.54 + b]], C.BD, 1.5);
  for (const y of [0.39, 0.44, 0.49]) {
    g.line([[0.44, y + b], [0.49, y + 0.006 + b]], C.BD, 1.3);
    g.line([[0.56, y + b], [0.51, y + 0.006 + b]], C.BD, 1.3);
    g.line([[0.445, y - 0.012 + b], [0.485, y - 0.007 + b]], C.BL, 0.9);
  }
  g.line([[0.235, 0.31 + b], [0.24, 0.36 + b], [0.31, 0.43 + b], [0.375, 0.5 + b]], C.BL, 1.2);
  // ── 金の おび（大臣の なごり）──
  g.poly([[0.365, 0.545], [0.635, 0.545], [0.655, 0.61], [0.345, 0.61]], C.GD);
  g.poly([[0.372, 0.552], [0.628, 0.552], [0.645, 0.6], [0.355, 0.6]], C.G);
  g.line([[0.375, 0.558], [0.625, 0.558]], C.GL, 1);
  R(0.5, 0.578, 0.026, C.GD);
  R(0.5, 0.576, 0.018, C.GEM);
  // ── うで（かたから 外へ、下へ。金の うでわ・白い 大きな ツメ。コマ1で 手を すこし 上げる）──
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    const up = f ? -0.035 : 0;
    const sh = [X(0.29), 0.32 + b], el = [X(0.4), 0.45 + b], wr = [X(0.39), 0.6 + up], ha = [X(0.385), 0.665 + up];
    taper(g, [sh, el], 0.13, 0.11, C.BD);
    taper(g, [el, wr], 0.12, 0.095, C.BD);
    taper(g, [sh, el], 0.105, 0.09, C.B);
    taper(g, [el, wr], 0.098, 0.075, C.B);
    if (s < 0) g.line([[X(0.33), 0.33 + b], [X(0.415), 0.45 + b], [X(0.41), 0.58 + up]], C.BL, 1.4);
    // て と ツメ（からだの がわへ まがる）
    R(ha[0], ha[1], 0.05, C.BD);
    R(ha[0] + s * 0.004, ha[1] - 0.006, 0.041, C.B);
    for (const [dx, len] of [[-0.036, 0.05], [-0.013, 0.066], [0.012, 0.066], [0.034, 0.05]]) {
      const x0 = ha[0] + dx, y0 = ha[1] + 0.035;
      const claw = bez([[x0, y0], [x0, y0 + len * 0.6], [x0 - s * 0.016, y0 + len]], 6);
      taper(g, claw, 0.024, 0.005, C.CD);
      taper(g, claw.slice(0, 5), 0.014, 0.004, C.CL);
    }
    // 金の うでわ
    g.ell(wr[0], wr[1], 0.062, 0.03, C.GD);
    g.ell(wr[0], wr[1] - 0.004, 0.056, 0.021, C.G);
    g.line([[wr[0] - 0.045, wr[1] - 0.011], [wr[0] + 0.015, wr[1] - 0.014]], C.GL, 1);
    // かたの まるみ と とげ
    R(sh[0], sh[1] - 0.004, 0.078, C.BD);
    R(sh[0] + s * 0.004, sh[1] - 0.01, 0.068, C.B);
    for (const [dx, dy, l] of [[0.23, 0.27, 0.05], [0.29, 0.255, 0.065], [0.345, 0.27, 0.048]]) {
      g.poly([[X(dx - 0.022), dy + 0.018 + b], [X(dx + 0.012), dy - l + b], [X(dx + 0.022), dy + 0.022 + b]], C.H);
      g.line([[X(dx - 0.006), dy + 0.01 + b], [X(dx + 0.01), dy - l * 0.7 + b]], C.HL, 0.9);
    }
    if (s < 0) g.ell(X(0.31), 0.29 + b, 0.035, 0.016, C.BL);
  }
  // ── 頭（つの・ひたいの 赤い 宝石・光る 目・キバの 口・とがった ひげ）──
  const hy = 0.16 + b;
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    const horn = bez([[X(0.065), hy - 0.03], [X(0.15), hy - 0.035], [X(0.215), hy - 0.09], [X(0.2), 0.012]], 12);
    taper(g, horn, 0.068, 0.012, C.BD);
    taper(g, horn, 0.05, 0.006, C.H);
    for (const i of [3, 5, 7, 9]) {
      const [x, y] = horn[i];
      g.line([[x - 0.018, y + 0.012], [x + 0.016, y - 0.01]], C.HL, 1);
    }
    const [tx, ty] = horn[11];
    R(tx, ty, 0.007, C.HH);
  }
  g.poly([[0.42, hy - 0.07], [0.58, hy - 0.07], [0.61, hy - 0.01], [0.59, hy + 0.05], [0.54, hy + 0.1], [0.5, hy + 0.112], [0.46, hy + 0.1], [0.41, hy + 0.05], [0.39, hy - 0.01]], C.BD);
  g.poly([[0.425, hy - 0.06], [0.575, hy - 0.06], [0.6, hy - 0.01], [0.58, hy + 0.045], [0.535, hy + 0.09], [0.5, hy + 0.1], [0.465, hy + 0.09], [0.42, hy + 0.045], [0.4, hy - 0.01]], C.B);
  g.line([[0.405, hy - 0.01], [0.425, hy + 0.045], [0.465, hy + 0.088]], C.BL, 1.4);
  g.line([[0.43, hy - 0.058], [0.49, hy - 0.06]], C.BH, 1.2);
  // とがった ひげ（大臣の あごひげの なごり）
  const sw = f ? 0.01 : -0.006;
  g.poly([[0.47, hy + 0.095], [0.53, hy + 0.095], [0.516 + sw, hy + 0.17], [0.5 + sw, hy + 0.205], [0.488, hy + 0.15]], C.BD);
  g.line([[0.496, hy + 0.11], [0.5 + sw, hy + 0.185]], C.H, 1);
  // ひたいの 宝石
  g.poly([[0.5, hy - 0.078], [0.527, hy - 0.042], [0.5, hy - 0.008], [0.473, hy - 0.042]], C.GD);
  g.poly([[0.5, hy - 0.068], [0.518, hy - 0.042], [0.5, hy - 0.018], [0.482, hy - 0.042]], C.GEM);
  R(0.494, hy - 0.05, 0.006, C.EL);
  // まゆの ほね と 光る 目（つり上がる）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.line([[X(0.02), hy - 0.006], [X(0.092), hy - 0.03]], C.BD, 2);
    g.poly([[X(0.025), hy + 0.004], [X(0.078), hy - 0.012], [X(0.082), hy + 0.008], [X(0.03), hy + 0.024]], C.E);
    g.poly([[X(0.037), hy + 0.008], [X(0.066), hy - 0.003], [X(0.069), hy + 0.007], [X(0.042), hy + 0.016]], C.EL);
  }
  // 口（中が 赤く 光る。上下の キバ）
  g.poly([[0.445, hy + 0.045], [0.555, hy + 0.045], [0.535, hy + 0.078], [0.465, hy + 0.078]], C.M);
  g.ell(0.5, hy + 0.066, f ? 0.03 : 0.022, 0.01, C.E);
  for (const x of [0.462, 0.487, 0.513, 0.538]) g.poly([[x - 0.009, hy + 0.045], [x + 0.009, hy + 0.045], [x, hy + 0.066]], C.CL);
  for (const x of [0.475, 0.5, 0.525]) g.poly([[x - 0.008, hy + 0.078], [x + 0.008, hy + 0.078], [x, hy + 0.06]], C.CD);
  // ── あやしい 光（手の まわりで ちらちら）──
  const sp = f ? [[0.06, 0.6], [0.95, 0.66], [0.2, 0.2]] : [[0.05, 0.7], [0.94, 0.57], [0.8, 0.18]];
  for (const [x, y] of sp) spark(g, x, y, 0.028, C.VL, C.V);
}

