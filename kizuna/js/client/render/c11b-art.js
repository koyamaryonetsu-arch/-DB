// ───── 月のむかえオボロ（2倍。224×224）─────
const OB = {
  R: '#f8f8ff', RD: '#c8c8e8', RL: '#ffffff', // 白い 衣
  V: '#d8d4ff', // うすい 衣
  CL: '#e8eaf8', CD: '#a8acd0', // 雲の 車
  F: '#f6e8e0', FD: '#d8c0b8', // 顔
  HR: '#2a2a48', // かみ
  G: '#ffe9a0', GD: '#d8b050', // 三日月の かんむり
  K: '#1a1026', W: '#ffffff', P: '#e8a0b0',
};
function oboro(g0, f) {
  const g = fit(g0, 224);
  const C = OB;
  const k = g.w / g.h;
  const away = f >= 2;
  const fr = f % 2;
  // 引いていく 時は 小さく 上へ（コマ 2・3）
  const s = away ? (fr ? 0.5 : 0.62) : 1;
  const ox = 0.5, oy = away ? (fr ? 0.3 : 0.38) : 0.5;
  const P = (x, y) => [ox + (x - 0.5) * s, oy + (y - 0.5) * s];
  const poly = (pts, c) => g.poly(pts.map(([x, y]) => P(x, y)), c);
  const ell = (x, y, rx, ry, c) => { const [px, py] = P(x, y); g.ell(px, py, rx * s, ry * s, c); };
  const line = (pts, c, lw) => g.line(pts.map(([x, y]) => P(x, y)), c, lw * s);
  // うしろの 月は かかない（戦いの 背景〈塔の 上の テラス〉に 大きな 月が ある）
  const sw = fr ? 0.012 : -0.012;
  // 雲の 車
  ell(0.5, 0.86, 0.36, 0.08, C.CD);
  for (const [x, y, r] of [[0.24, 0.84, 0.1], [0.38, 0.8, 0.12], [0.56, 0.79, 0.13], [0.74, 0.83, 0.1]]) ell(x, y, r, r * 0.7, C.CL);
  // うすい 衣（ひらひら。うしろ）
  poly([[0.36, 0.34], [0.12, 0.5 + sw], [0.2, 0.74], [0.4, 0.6]], C.V);
  poly([[0.64, 0.34], [0.88, 0.5 - sw], [0.8, 0.74], [0.6, 0.6]], C.V);
  // 白い 衣（体）
  poly([[0.4, 0.34], [0.6, 0.34], [0.68, 0.8], [0.32, 0.8]], C.RD);
  poly([[0.42, 0.34], [0.58, 0.34], [0.65, 0.78], [0.35, 0.78]], C.R);
  line([[0.5, 0.36], [0.5, 0.78]], C.RD, 2);
  // 長い そで（手を 前で 合わせる）
  poly([[0.42, 0.38], [0.3, 0.56], [0.4, 0.62], [0.5, 0.52]], C.RD);
  poly([[0.58, 0.38], [0.7, 0.56], [0.6, 0.62], [0.5, 0.52]], C.RD);
  poly([[0.43, 0.4], [0.33, 0.55], [0.41, 0.6], [0.5, 0.52]], C.RL);
  poly([[0.57, 0.4], [0.67, 0.55], [0.59, 0.6], [0.5, 0.52]], C.RL);
  // 顔・かみ
  const hx = 0.5, hy = 0.25;
  ell(hx, hy + 0.02, 0.085, 0.11, C.HR);
  ell(hx, hy, 0.065, 0.075, C.FD);
  ell(hx, hy - 0.004, 0.06, 0.07, C.F);
  // 目を ほそめた しずかな 顔
  line([[hx - 0.035, hy - 0.005], [hx - 0.012, hy - 0.002]], C.K, 1.6);
  line([[hx + 0.012, hy - 0.002], [hx + 0.035, hy - 0.005]], C.K, 1.6);
  line([[hx - 0.012, hy + 0.04], [hx + 0.012, hy + 0.04]], C.P, 1.4);
  // 長い かみ（りょうがわ）
  poly([[hx - 0.07, hy - 0.02], [hx - 0.09, hy + 0.14], [hx - 0.05, hy + 0.12]], C.HR);
  poly([[hx + 0.07, hy - 0.02], [hx + 0.09, hy + 0.14], [hx + 0.05, hy + 0.12]], C.HR);
  // 三日月の かんむり
  ell(hx, hy - 0.09, 0.04, 0.04, C.GD);
  ell(hx, hy - 0.092, 0.035, 0.035, C.G);
  ell(hx + 0.014, hy - 0.1, 0.03, 0.03, C.HR);
  if (!away) for (const [x, y] of [[0.16, 0.2], [0.3, 0.12], [0.9, 0.56]]) spark(g, x, y + sw, 0.02, C.G, C.W);
}

