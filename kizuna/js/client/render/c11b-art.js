  g.poly([[hx - 0.14, hy - 0.02], [hx - 0.13, hy - 0.2], [hx - 0.04, hy - 0.08]], C.BD);
  g.poly([[hx + 0.14, hy - 0.02], [hx + 0.13, hy - 0.2], [hx + 0.04, hy - 0.08]], C.BD);
  g.poly([[hx - 0.12, hy - 0.04], [hx - 0.11, hy - 0.16], [hx - 0.05, hy - 0.08]], C.P);
  g.ell(hx, hy, 0.15, 0.13, C.BD);
  g.ell(hx, hy - 0.01, 0.13, 0.11, C.B);
