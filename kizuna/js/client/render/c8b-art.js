  const C = PC;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const fr = f >= 2;
  const up = f % 2;
  const lean = up ? 0.03 : 0;
  // しっぽ（くるんと まく）
