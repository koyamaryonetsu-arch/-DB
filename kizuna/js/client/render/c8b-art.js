  g.poly([[tx - 0.04, ty], [tx, ty - 0.05], [tx + 0.04, ty], [tx, ty + 0.03]], C.K);
  // 足（細長い）
  for (const s of [-1, 1]) {
    const pts = [[0.5 + s * 0.06, 0.72], [0.5 + s * 0.1 + (fr ? s * 0.04 : 0), 0.84], [0.5 + s * 0.08, 0.95]];
    g.line(pts, C.BD, 7);
    g.line(pts, C.B, 4.5);
    g.ell(0.5 + s * 0.11, 0.96, 0.06, 0.02, C.BD);
  }
