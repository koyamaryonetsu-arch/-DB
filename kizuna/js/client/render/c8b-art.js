// ケロベロス: むらさきの 子犬。頭が 3つ（まん中が いちばん 大きい）・赤い とげの 首わ・しっぽの 先に 青い 火。コマ1 … 3つの 口で ほえる
function kerberos(g0, f) {
  const g = fit(g0, 48);
  const C = KB;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? 1 : 0;
  // しっぽと 青い 火
  g.line([[0.78, 0.66], [0.9, 0.56], [0.92, 0.42]], C.BD, 3);
  flame(g, 0.92, 0.44, 0.1, 0.16 + up * 0.04, up ? 0.02 : -0.02, [C.FD, C.F, C.FL]);
  // うしろ足
  for (const x of [0.62, 0.74]) {
    g.poly([[x - 0.05, 0.72], [x + 0.05, 0.72], [x + 0.05, 0.92], [x - 0.06, 0.92]], C.BD);
    g.ell(x, 0.93, 0.06, 0.03, C.BD);
  }
  // 体
  g.ell(0.58, 0.68, 0.24, 0.16, C.BD);
  g.ell(0.57, 0.66, 0.22, 0.14, C.B);
  g.ell(0.5, 0.62, 0.1, 0.06, C.BL);
  // 前足
  for (const x of [0.38, 0.5]) {
    g.poly([[x - 0.05, 0.72], [x + 0.05, 0.72], [x + 0.05, 0.93], [x - 0.05, 0.93]], C.B);
    g.ell(x, 0.94, 0.06, 0.03, C.BL);
  }
  // 首わ（赤・白い とげ）
  g.ell(0.4, 0.55, 0.2, 0.05, C.CD);
  g.ell(0.4, 0.54, 0.19, 0.04, C.C);
  for (const x of [0.25, 0.33, 0.41, 0.49, 0.56]) g.poly([[x - 0.015, 0.53], [x, 0.49], [x + 0.015, 0.53]], C.S);
  // 頭 3つ（左・右は 小さく うしろ、まん中は 大きく 前）
  const head = (cx, cy, r, look) => {
    R(cx, cy, r, C.BD);
    R(cx - 0.005, cy - 0.005, r * 0.92, C.B);
    // 耳
    g.poly([[cx - r * 0.8, cy - r * 0.3], [cx - r * 0.9, cy - r * 1.3], [cx - r * 0.2, cy - r * 0.8]], C.BD);
    g.poly([[cx + r * 0.8, cy - r * 0.3], [cx + r * 0.9, cy - r * 1.3], [cx + r * 0.2, cy - r * 0.8]], C.BD);
    // 口の まわり
    g.ell(cx, cy + r * 0.45 * k, r * 0.55, r * 0.38, C.M);
    R(cx, cy + r * 0.18, r * 0.16, C.N);
    // 口（コマ1 … 大きく 開いて ほえる）
    if (up) {
      g.ell(cx, cy + r * 0.72 * k, r * 0.32, r * 0.24, C.N);
      g.ell(cx, cy + r * 0.82 * k, r * 0.18, r * 0.1, C.T);
    } else g.line([[cx - r * 0.25, cy + r * 0.6 * k], [cx, cy + r * 0.7 * k], [cx + r * 0.25, cy + r * 0.6 * k]], C.N, 0.8);
    // 目（黄色い 目・まゆ）
    for (const s of [-1, 1]) {
      g.ell(cx + s * r * 0.4, cy - r * 0.2, r * 0.16, r * 0.2, C.Y);
      g.ell(cx + s * r * 0.4 + look * r * 0.05, cy - r * 0.18, r * 0.07, r * 0.12, C.N);
    }
  };
  head(0.18, 0.4 - up * 0.02, 0.11, -1);
  head(0.62, 0.38 - up * 0.02, 0.11, 1);
  head(0.4, 0.36, 0.15, 0);
  // ほえ声の 線（コマ1）
  if (up) for (const [x, y] of [[0.08, 0.26], [0.4, 0.12], [0.74, 0.24]]) {
    g.line([[x - 0.03, y], [x - 0.06, y - 0.06]], C.FL, 0.8);
    g.line([[x + 0.03, y], [x + 0.06, y - 0.06]], C.FL, 0.8);
  }
}

// ───── ホネギョ（ホネだけの 魚。マリオの 敵が もと）─────
