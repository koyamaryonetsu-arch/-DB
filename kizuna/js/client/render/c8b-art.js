    for (const s of [-1, 1]) g.poly([[0.5 + s * 0.2, hy - 0.12], [0.5 + s * 0.23, hy - 0.06], [0.5 + s * 0.2, hy - 0.04], [0.5 + s * 0.17, hy - 0.06]], C.S);
