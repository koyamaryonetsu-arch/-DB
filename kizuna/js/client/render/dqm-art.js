import { fit, spark, bez, taper, flame, snowflake } from './ch3-draw.js?v=3b236c4d2218';

const W = '#ffffff', K = '#1a1026';
const pal = (P) => [...new Set(Object.values(P).map((c) => c.toLowerCase()))];
// まるい だ円（たて・よこの ひりつを なおす）
const roundOf = (g) => {
  const k = g.w / g.h;
  return (x, y, r, c) => g.ell(x, y, r, r * k, c);
};
// だ円の 上の てん（cx,cy … まんなか、rx,ry … 大きさ、a … かくど）
const onEll = (cx, cy, rx, ry, a) => [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
// だ円の 弧（a0 → a1。n … こまかさ）
const arcPts = (cx, cy, rx, ry, a0, a1, n = 10) => Array.from({ length: n + 1 }, (_, i) => onEll(cx, cy, rx, ry, a0 + ((a1 - a0) * i) / n));

// ぷるりんの からだ（monsters.js の jelly と おなじ 形。cx,cy … まんなか、s … 大きさ〈1 で え いっぱい〉、sq … つぶれ）
function slime(g, cx, cy, s, sq, c, cD, cL, mouth = '#6a1a2a', tongue = '#ff8aa0') {
  const X = (v) => cx + (v - 0.5) * s, Y = (v) => cy + (v - 0.6) * s;
  g.ell(X(0.5), Y(0.64 + sq / 2), (0.44 + sq) * s, (0.34 - sq) * s, cD);
  g.ell(X(0.5), Y(0.6 + sq / 2), (0.42 + sq) * s, (0.33 - sq) * s, c);
  g.poly([[X(0.38), Y(0.35 + sq)], [X(0.5), Y(0.1 + sq * 2)], [X(0.62), Y(0.35 + sq)]], c);
  g.ell(X(0.34), Y(0.47 + sq), 0.1 * s, 0.06 * s, cL);
  g.ell(X(0.27), Y(0.56 + sq), 0.04 * s, 0.05 * s, cL);
  g.eye(X(0.38), Y(0.6 + sq), 0.075 * s, 0.3);
  g.eye(X(0.62), Y(0.6 + sq), 0.075 * s, 0.3);
  g.poly([[X(0.43), Y(0.75 + sq)], [X(0.57), Y(0.75 + sq)], [X(0.5), Y(0.83 + sq)]], mouth);
  g.ell(X(0.5), Y(0.8 + sq), 0.035 * s, 0.025 * s, tongue);
  return { X, Y };
}

