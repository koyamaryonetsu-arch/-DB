  const b = f ? 0.01 : 0;
  const F = '#7a5a48', FD = '#4a3228', FDD = '#2e1e18', FL = '#a8826a', FLL = '#c8a88a';
  const S = '#f4f8ff', SS = '#c8d8ec', I = '#bfeaff', ID = '#6ab8e0', IL = '#ffffff', N = '#e0d4c0';
