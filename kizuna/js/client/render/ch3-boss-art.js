    taper(g, pts, 0.062, 0.018, ID);
    taper(g, pts, 0.05, 0.01, I);
    taper(g, pts.slice(0, -1).map(([x, y]) => [x - 0.008, y - 0.01]), 0.012, 0.004, IL);
