  const FR = '#e84a2a', FO = '#ff9a3a', FY = '#ffe46a', FW = '#fff6d0';
  const F3 = [FR, FO, FY];
  // もえる マント（うしろ。くろっぽい 赤）
  g.poly([[0.3, 0.28 + b], [0.7, 0.28 + b], [0.84 + fl, 0.6], [0.92 + fl, 0.9], [0.08 - fl, 0.9], [0.16 - fl, 0.6]], CD);
