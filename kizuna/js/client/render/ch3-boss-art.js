// しろがねの たてがみ（ふわふわの ふさを うしろへ ながす。base … ふさの ねもとの 線、a … ながれる むき）
function maneLocks(g, base, n, len, a0, a1, sway) {
  const ry = g.w / g.h;
  const pts = bez(base, n - 1);
  const lock = (x, y, a, l, w, k) => {
    const tip = [x + Math.cos(a) * l, y + Math.sin(a) * l * ry];
    const mid = [x + Math.cos(a - 0.4) * l * 0.55, y + Math.sin(a - 0.4) * l * 0.55 * ry];
    const p = bez([[x, y], mid, tip], 8);
    taper(g, p.map(([px, py]) => [px + 0.003, py + 0.006]), w, 0.008, SD.MS);
    taper(g, p, w * 0.86, 0.006, SD.M);
    if (k) taper(g, p.slice(1, 6).map(([px, py]) => [px - 0.004, py - 0.008]), w * 0.3, 0.006, '#ffffff');
  };
  // うしろの みじかい ふさ
  pts.forEach(([x, y], i) => {
    const t = n > 1 ? i / (n - 1) : 0;
    lock(x + 0.01, y + 0.02, a0 + (a1 - a0) * t + 0.3, len * 0.6, 0.06, false);
  });
  pts.forEach(([x, y], i) => {
    const t = n > 1 ? i / (n - 1) : 0;
    const a = a0 + (a1 - a0) * t + (i % 2 ? sway : -sway);
    lock(x, y, a, len * (0.8 + 0.4 * Math.sin(t * Math.PI)), 0.085, true);
  });
}

