// ・addWork10Art(ART) … 物の 絵（'mon:<id>' の NPC）: 川の はじめの 岸の ひっくり返った いかだ・ピラミッドの 岸の ひづめの あとの 岩・
//     わき道の 岸に 流れ着いた 物（はっぱの 舟・古い 木の おけ・赤い ほに 星の もようの おもちゃの いかだ）
//   より道「ムウとムウムウの、あそび道具」の 星わたの きらりは 第90回の 'c9ad_glint' を 使う
// かきかたは work-art.js と おなじ（g … w・h の わりあいで かく。f … 0 か 1 の コマ）。地下の川の 暗い 岸の 上で 見える 色に する

// ───────────── 42. ひっくり返った いかだ（丸太の うら・ちぎれた なわ・ぬれた あと）─────────────
const RF = { L: '#a87a4a', LL: '#d0a070', LD: '#6a4a2a', K: '#3a2814', R: '#d8c890', W: '#7ac8e8', WL: '#d0f0ff' };
function raftFlipArt(g, f) {
  const C = RF;
  // ぬれた あと（水たまり）
  g.ell(0.5, 0.9, 0.46, 0.08, C.W);
  g.ell(f ? 0.32 : 0.68, 0.9, 0.06, 0.02, C.WL);
  // かたむいた 丸太（うらがえし。5本）
  for (let i = 0; i < 5; i++) {
    const y = 0.34 + i * 0.1;
    g.poly([[0.08, y + 0.06], [0.9, y - 0.04], [0.92, y + 0.04], [0.1, y + 0.14]], C.LD);
    g.poly([[0.08, y + 0.05], [0.9, y - 0.05], [0.91, y + 0.01], [0.09, y + 0.11]], i % 2 ? C.L : C.LL);
    g.ell(0.09, y + 0.09, 0.03, 0.04, C.K);
  }
  // よこの 木（うらに 2本）
  g.poly([[0.28, 0.3], [0.34, 0.3], [0.38, 0.84], [0.32, 0.84]], C.LD);
  g.poly([[0.66, 0.26], [0.72, 0.26], [0.76, 0.8], [0.7, 0.8]], C.LD);
  // ちぎれた なわ
  g.line([[0.9, 0.3], [0.96, 0.22], [0.92, 0.14]], C.R, 1.5);
  g.line([[0.12, 0.8], [0.04, 0.86]], C.R, 1.5);
  // しずく
  g.ell(0.5, f ? 0.2 : 0.24, 0.02, 0.03, C.WL);
}

// ───────────── 43. ひづめの あとの ある 岩（角の あとと ひづめの へこみ）─────────────
const HR = { R: '#6a6474', RL: '#8e88a0', RD: '#3e3848', K: '#1e1a26', H: '#2a2432', Y: '#ffe48a' };
function hoofRockArt(g, f) {
  const C = HR;
  g.ell(0.5, 0.93, 0.44, 0.06, C.RD);
  g.poly([[0.06, 0.92], [0.12, 0.46], [0.32, 0.2], [0.62, 0.16], [0.86, 0.34], [0.94, 0.92]], C.R);
  g.poly([[0.2, 0.46], [0.34, 0.24], [0.56, 0.2], [0.4, 0.44]], C.RL);
  // ひづめの あと（2つに われた へこみ。3つ ならぶ）
  for (const [x, y] of [[0.36, 0.56], [0.56, 0.48], [0.7, 0.68]]) {
    g.ell(x - 0.035, y, 0.03, 0.045, C.H);
    g.ell(x + 0.035, y, 0.03, 0.045, C.H);
  }
  // 角で こすった すじ
  g.line([[0.18, 0.72], [0.3, 0.66]], C.K, 1);
  g.line([[0.2, 0.8], [0.34, 0.74]], C.K, 1);
  // ちかちか（音の なごり）
  g.ell(f ? 0.82 : 0.86, f ? 0.2 : 0.16, 0.02, 0.02, C.Y);
}

// ───────────── より道: わき道の 岸に 流れ着いた 物 ─────────────
// はっぱの 舟
const LF = { G: '#5ab868', GL: '#9ae0a0', GD: '#2e7a3a', S: '#a8784a', W: '#6ab0d0' };
function leafArt(g, f) {
  const C = LF;
  g.ell(0.5, 0.82, 0.4, 0.07, C.W);
  g.poly([[0.1, 0.62], [0.9, 0.62], [0.74, 0.8], [0.26, 0.8]], C.GD);
  g.poly([[0.14, 0.6], [0.86, 0.6], [0.72, 0.76], [0.28, 0.76]], C.G);
  g.line([[0.2, 0.66], [0.8, 0.66]], C.GL, 1);
  // 小えだの ほばしら（ほは ない）
  g.rect(0.48, 0.3 + (f ? 0.02 : 0), 0.03, 0.32, C.S);
}
// 古い 木の おけ
const BK = { W: '#9a6a3a', WL: '#c08a52', WD: '#5a3a1e', B: '#5a5a62', BL: '#8a8a94', K: '#2a1a0a' };
function bucketArt(g, f) {
  const C = BK;
  g.ell(0.5, 0.9, 0.34, 0.05, C.K);
  g.poly([[0.2, 0.36], [0.8, 0.36], [0.74, 0.88], [0.26, 0.88]], C.W);
  g.poly([[0.28, 0.4], [0.38, 0.4], [0.36, 0.86], [0.3, 0.86]], C.WL);
  g.ell(0.5, 0.36, 0.3, 0.07, C.WD);
  g.ell(0.5, 0.36, 0.25, 0.05, C.K);
  // たが（2本）
  g.rect(0.22, 0.48, 0.56, 0.04, C.B);
  g.rect(0.25, 0.74, 0.5, 0.04, f ? C.BL : C.B);
}
// おもちゃの いかだ（赤い ほに 黄色い 星）
const TY = { L: '#c08a52', LD: '#7a5028', R: '#e84a4a', RL: '#ff8a7a', Y: '#ffe060', S: '#6a4a2a', W: '#6ab0d0', WL: '#d0f0ff' };
function toyRaftArt(g, f) {
  const C = TY;
  g.ell(0.5, 0.86, 0.42, 0.07, C.W);
  g.ell(f ? 0.3 : 0.7, 0.86, 0.06, 0.02, C.WL);
  // 丸太 4本
  for (let i = 0; i < 4; i++) {
    const x = 0.2 + i * 0.16;
    g.rect(x, 0.66, 0.14, 0.16, C.LD);
    g.rect(x + 0.01, 0.66, 0.12, 0.13, C.L);
  }
  // ほばしらと 赤い ほ（星の もよう）
  g.rect(0.48, 0.14, 0.04, 0.54, C.S);
  const sway = f ? 0.02 : 0;
  g.poly([[0.52, 0.16], [0.86 + sway, 0.36], [0.52, 0.58]], C.R);
  g.poly([[0.52, 0.2], [0.7 + sway, 0.32], [0.52, 0.4]], C.RL);
  g.ell(0.64 + sway / 2, 0.38, 0.05, 0.05, C.Y);
}

export function addWork10Art(ART) {
  ART.fq_raft_flip = { size: [30, 24], field: 30, npc: 1, pal: Object.values(RF), draw: raftFlipArt };
  ART.fq_hoof_rock = { size: [26, 26], field: 26, npc: 1, pal: Object.values(HR), draw: hoofRockArt };
  ART.c9cd_leaf = { size: [18, 16], field: 18, npc: 1, pal: Object.values(LF), draw: leafArt };
  ART.c9cd_bucket = { size: [16, 18], field: 16, npc: 1, pal: Object.values(BK), draw: bucketArt };
  ART.c9cd_toy = { size: [18, 18], field: 18, npc: 1, pal: Object.values(TY), draw: toyRaftArt };
}
