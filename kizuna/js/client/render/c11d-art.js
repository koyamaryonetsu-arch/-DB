const EYE = ['#ffffff', '#1a1026'];
const pal = (P) => [...new Set([...Object.values(P), ...EYE])];

// ───── プリズムナイト（40×48）─────
const KN = {
  A: '#e8ecf8', AD: '#a8b0c8', AL: '#ffffff', // 白い よろい
  P1: '#ff9ac8', P2: '#9ad8ff', P3: '#fff2a0', // にじの かけら
  S: '#c8d0e8', SD: '#7a82a0', // けん
  V: '#2a2a48', K: '#1a1026',
};
function knight(g0, f) {
  const g = fit(g0, 40);
  const C = KN;
  const k = g.w / g.h;
  const up = f ? -0.015 : 0;
  // けん（右手）
  g.poly([[0.8, 0.1 + up], [0.85, 0.1 + up], [0.84, 0.62 + up], [0.81, 0.62 + up]], C.S);
  g.line([[0.82, 0.12 + up], [0.83, 0.6 + up]], C.AL, 1);
  g.poly([[0.74, 0.6 + up], [0.91, 0.6 + up], [0.9, 0.64 + up], [0.75, 0.64 + up]], C.SD);
  // あし
  g.poly([[0.36, 0.72], [0.46, 0.72], [0.46, 0.95], [0.34, 0.95]], C.AD);
  g.poly([[0.54, 0.72], [0.64, 0.72], [0.66, 0.95], [0.54, 0.95]], C.AD);
  // 体（かけらの よろい）
  g.poly([[0.28, 0.32 + up], [0.72, 0.32 + up], [0.68, 0.76], [0.32, 0.76]], C.AD);
  g.poly([[0.3, 0.33 + up], [0.7, 0.33 + up], [0.66, 0.74], [0.34, 0.74]], C.A);
  g.poly([[0.4, 0.4 + up], [0.5, 0.36 + up], [0.46, 0.5 + up]], C.P1);
  g.poly([[0.5, 0.36 + up], [0.6, 0.4 + up], [0.54, 0.52 + up]], C.P2);
  g.poly([[0.42, 0.56], [0.58, 0.56], [0.5, 0.68]], C.P3);
  // うで
  g.poly([[0.2, 0.36 + up], [0.28, 0.34 + up], [0.24, 0.6], [0.16, 0.58]], C.AD);
  g.poly([[0.72, 0.34 + up], [0.8, 0.36 + up], [0.84, 0.58], [0.76, 0.6]], C.AD);
  // かぶと
  g.ell(0.5, 0.2 + up, 0.14, 0.14, C.AD);
  g.ell(0.5, 0.19 + up, 0.12, 0.12, C.A);
  g.poly([[0.4, 0.2 + up], [0.6, 0.2 + up], [0.58, 0.25 + up], [0.42, 0.25 + up]], C.V);
  for (const ex of [0.45, 0.55]) g.ell(ex, 0.225 + up, 0.02, 0.02 * k, C.P3);
  g.poly([[0.5, 0.02 + up], [0.55, 0.1 + up], [0.5, 0.08 + up], [0.45, 0.1 + up]], C.P2);
  void C.K;
}

// ───── かんむりどり（44×40）─────
const CR = {
  B: '#f4f0ff', BD: '#c0b8e0', BL: '#ffffff', // 白い 体
  Y: '#f0b040', // くちばし・あし
  G: '#ffd84a', GD: '#c89a20', GL: '#fff6c0', // かんむり
  R: '#ff7a9a', K: '#1a1026', W: '#ffffff',
};
function crown(g0, f) {
  const g = fit(g0, 44);
  const C = CR;
  const k = g.w / g.h;
  const fl = f ? 0.06 : 0;
  // あし
  g.line([[0.44, 0.78], [0.42, 0.95]], C.Y, 1.4);
  g.line([[0.56, 0.78], [0.58, 0.95]], C.Y, 1.4);
  // 体・つばさ（むねを はる）
  g.ell(0.5, 0.6, 0.25, 0.21, C.BD);
  g.ell(0.5, 0.58, 0.23, 0.19, C.B);
  g.poly([[0.3, 0.56], [0.1, 0.46 + fl], [0.18, 0.7], [0.36, 0.68]], C.BD);
  g.poly([[0.7, 0.56], [0.9, 0.46 + fl], [0.82, 0.7], [0.64, 0.68]], C.BD);
  g.ell(0.5, 0.64, 0.14, 0.11, C.BL);
  // 頭
  g.ell(0.5, 0.38, 0.13, 0.12, C.B);
  for (const ex of [0.45, 0.55]) { g.ell(ex, 0.37, 0.025, 0.025 * k, C.W); g.ell(ex, 0.375, 0.012, 0.012 * k, C.K); }
  g.poly([[0.47, 0.42], [0.53, 0.42], [0.5, 0.5]], C.Y);
  g.ell(0.42, 0.43, 0.025, 0.02, C.R);
  g.ell(0.58, 0.43, 0.025, 0.02, C.R);
  // 光の かんむり
  g.poly([[0.38, 0.27], [0.62, 0.27], [0.62, 0.21], [0.56, 0.15], [0.5, 0.21], [0.44, 0.15], [0.38, 0.21]], C.GD);
  g.poly([[0.39, 0.26], [0.61, 0.26], [0.61, 0.22], [0.56, 0.17], [0.5, 0.22], [0.44, 0.17], [0.39, 0.22]], C.G);
  spark(g, 0.5, 0.1 - (f ? 0.02 : 0), 0.06, C.GL, C.W);
}

// ───── てかがみ（32×36。宙に うかぶ 手鏡）─────
const HM = {
  F: '#e0b040', FD: '#a87e20', FL: '#fff0a0', // 金の ふち
  M: '#cfe8ff', MD: '#8ab8e0', ML: '#ffffff', // 鏡
  E: '#3a3a70', K: '#1a1026',
};
function hmirror(g0, f) {
  const g = fit(g0, 32);
  const C = HM;
  const k = g.w / g.h;
  const up = f ? -0.03 : 0;
  // え（もつ ところ）
  g.poly([[0.46, 0.62 + up], [0.54, 0.62 + up], [0.56, 0.92 + up], [0.44, 0.92 + up]], C.FD);
  g.poly([[0.47, 0.63 + up], [0.53, 0.63 + up], [0.54, 0.9 + up], [0.46, 0.9 + up]], C.F);
  g.ell(0.5, 0.93 + up, 0.06, 0.04, C.FL);
  // 鏡の まる
  g.ell(0.5, 0.36 + up, 0.36, 0.3, C.FD);
  g.ell(0.5, 0.36 + up, 0.33, 0.27, C.F);
  g.ell(0.5, 0.36 + up, 0.27, 0.22, C.MD);
  g.ell(0.48, 0.34 + up, 0.24, 0.19, C.M);
  g.poly([[0.34, 0.26 + up], [0.42, 0.2 + up], [0.48, 0.24 + up], [0.38, 0.32 + up]], C.ML);
  // 目（鏡の 中）
  for (const ex of [0.42, 0.58]) g.ell(ex, 0.4 + up, 0.04, 0.05 * k, C.E);
  g.ell(0.44, 0.39 + up, 0.015, 0.015 * k, C.ML);
  g.ell(0.6, 0.39 + up, 0.015, 0.015 * k, C.ML);
  // ふちの かざり
  for (const [x, y] of [[0.5, 0.06], [0.16, 0.36], [0.84, 0.36]]) g.ell(x, y + up, 0.04, 0.035, C.FL);
  void C.K;
}

// ───── ほしのかけら（32×36。ほうき星の かけらの 精）─────
const SH = {
  S: '#fff2a0', SD: '#e0b840', SL: '#ffffff', // 星の かけら
  T: '#9ad8ff', TL: '#d8f4ff', // しっぽ
  P: '#ff9ac8', K: '#1a1026',
};
function shard(g0, f) {
  const g = fit(g0, 32);
  const C = SH;
  const k = g.w / g.h;
  const sw = f ? 0.05 : -0.05;
  // しっぽ（ひかりの すじ）
  g.poly([[0.5, 0.5], [0.12 + sw, 0.96], [0.3 + sw, 0.96]], C.T);
  g.poly([[0.5, 0.5], [0.7 - sw, 0.96], [0.86 - sw, 0.94]], C.TL);
  g.poly([[0.5, 0.5], [0.42, 0.96], [0.58, 0.96]], C.T);
  // かけらの 体（とがった 星）
  const pts = [];
  for (let i = 0; i < 10; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / 5 + (f ? 0.1 : 0);
    const r = i % 2 ? 0.17 : 0.36;
    pts.push([0.5 + Math.cos(a) * r, 0.42 + Math.sin(a) * r * k]);
  }
  g.poly(pts, C.SD);
  g.poly(pts.map(([x, y]) => [0.5 + (x - 0.5) * 0.86, 0.42 + (y - 0.42) * 0.86]), C.S);
  g.ell(0.44, 0.34, 0.05, 0.04, C.SL);
  // かお
  for (const ex of [0.44, 0.56]) g.ell(ex, 0.44, 0.025, 0.03 * k, C.K);
  g.ell(0.38, 0.5, 0.03, 0.02, C.P);
  g.ell(0.62, 0.5, 0.03, 0.02, C.P);
}

// ───── かがやきの女王ポラリス（2倍。224×256）─────
const QN = {
  D: '#f8f6ff', DD: '#c8c4e0', DL: '#ffffff', // 白い ドレス
  G: '#e8c050', GD: '#a8822a', GL: '#fff4c0', // 金
  B: '#bfe0ff', BL: '#e8f6ff', // 北の 星の 光
  H: '#f4dccc', HD: '#d4b4a0', // かお・手
  R: '#c8d0f0', RD: '#8890c0', // かみ（銀）
  N: '#3a3a78', // ひとみ
  K: '#1a1026', W: '#ffffff',
};
function queen(g0, f) {
  const g = fit(g0, 224);
  const C = QN;
  const k = g.w / g.h;
  const down = f >= 2;
  const fr = f % 2;
  const gl = fr ? 0.012 : 0;
  // うしろの 光（北の 星の かがやき。手を 下ろすと やわらかく）
  if (!down) {
    for (let i = 0; i < 12; i++) {
      const a = (i / 12) * Math.PI * 2 + (fr ? 0.13 : 0);
      g.poly([[0.5, 0.3], [0.5 + Math.cos(a - 0.05) * 0.44, 0.3 + Math.sin(a - 0.05) * 0.32], [0.5 + Math.cos(a + 0.05) * 0.44, 0.3 + Math.sin(a + 0.05) * 0.32]], i % 2 ? C.BL : C.B);
    }
  } else {
    g.ell(0.5, 0.3, 0.3, 0.26, C.BL);
  }
  // かみ（長い 銀の かみ）
  g.poly([[0.38, 0.12], [0.62, 0.12], [0.68, 0.5], [0.32, 0.5]], C.RD);
  g.poly([[0.39, 0.13], [0.61, 0.13], [0.66, 0.48], [0.34, 0.48]], C.R);
  // ドレス（まっすぐ 立つ。すそは 床まで）
  g.poly([[0.38, 0.3], [0.62, 0.3], [0.76, 0.97], [0.24, 0.97]], C.DD);
  g.poly([[0.39, 0.31], [0.61, 0.31], [0.74, 0.96], [0.26, 0.96]], C.D);
  g.poly([[0.47, 0.32], [0.53, 0.32], [0.56, 0.96], [0.44, 0.96]], C.DL);
  // 金の ふち・ベルト
  g.poly([[0.39, 0.42], [0.61, 0.42], [0.62, 0.45], [0.38, 0.45]], C.G);
  g.poly([[0.25, 0.93], [0.75, 0.93], [0.76, 0.96], [0.24, 0.96]], C.GD);
  spark(g, 0.5, 0.435, 0.02, C.GL, C.W);
  // うで と 光の しゃく
  if (!down) {
    // 右手で しゃくを まっすぐ 立てる
    g.poly([[0.6, 0.32], [0.66, 0.33], [0.72, 0.5], [0.67, 0.52]], C.DD);
    g.ell(0.7, 0.52, 0.025, 0.02, C.H);
    g.line([[0.71, 0.08 - gl], [0.7, 0.9]], C.GD, 5);
    g.line([[0.71, 0.08 - gl], [0.7, 0.9]], C.G, 3);
    spark(g, 0.712, 0.06 - gl, 0.06, C.B, C.W);
    // 左手は むねの 前
    g.poly([[0.34, 0.32], [0.4, 0.33], [0.46, 0.46], [0.41, 0.48]], C.DD);
    g.ell(0.45, 0.47, 0.025, 0.02, C.H);
  } else {
    // 手を 下ろす（しゃくは 下に）
    g.poly([[0.6, 0.32], [0.65, 0.33], [0.66, 0.6], [0.61, 0.6]], C.DD);
    g.poly([[0.35, 0.33], [0.4, 0.32], [0.39, 0.6], [0.34, 0.6]], C.DD);
    g.ell(0.635, 0.61, 0.025, 0.02, C.H);
    g.ell(0.365, 0.61, 0.025, 0.02, C.H);
    g.line([[0.64, 0.6], [0.7, 0.94]], C.G, 3);
    spark(g, 0.7, 0.95, 0.03, C.B, C.W);
  }
  // かお（まじめな 顔。ねむって いない 目）
  const hx = 0.5, hy = 0.2;
  g.ell(hx, hy, 0.075, 0.08, C.HD);
  g.ell(hx, hy - 0.003, 0.069, 0.074, C.H);
  for (const ex of [hx - 0.028, hx + 0.028]) {
    if (down) g.line([[ex - 0.014, hy + 0.002], [ex + 0.014, hy + 0.006]], C.N, 2);
    else {
      g.ell(ex, hy, 0.016, 0.016 * k * 1.1, C.W);
      g.ell(ex, hy + 0.002, 0.01, 0.01 * k * 1.1, C.N);
    }
  }
  g.line([[hx - 0.018, hy + 0.045], [hx + 0.018, hy + 0.045]], C.HD, 1.6);
  // まえがみ
  g.poly([[hx - 0.07, hy - 0.05], [hx + 0.07, hy - 0.05], [hx + 0.06, hy - 0.08], [hx - 0.06, hy - 0.08]], C.R);
  // 北の 星の かんむり
  g.poly([[hx - 0.07, hy - 0.07], [hx + 0.07, hy - 0.07], [hx + 0.07, hy - 0.1], [hx + 0.04, hy - 0.14], [hx, hy - 0.1], [hx - 0.04, hy - 0.14], [hx - 0.07, hy - 0.1]], C.GD);
  g.poly([[hx - 0.065, hy - 0.075], [hx + 0.065, hy - 0.075], [hx + 0.065, hy - 0.098], [hx + 0.04, hy - 0.13], [hx, hy - 0.098], [hx - 0.04, hy - 0.13], [hx - 0.065, hy - 0.098]], C.G);
  spark(g, hx, hy - 0.16 - gl, down ? 0.035 : 0.05, C.B, C.W);
  void C.K;
}

export function addC11dArt(ART) {
  // 新しい 絵（ふつうの 魔物）
  ART.c11d_knight = { size: [40, 48], pal: pal(KN), draw: knight };
  ART.c11d_crown = { size: [44, 40], pal: pal(CR), draw: crown };
  ART.c11d_hmirror = { size: [32, 36], pal: pal(HM), draw: hmirror };
  ART.c11d_shard = { size: [32, 36], pal: pal(SH), draw: shard };
  // 色ちがい
  ART.c11d_dawn = { ...ART.c11d_knight, tint: { hueTo: 25, sat: 0.45, light: 1.0 } };
  ART.c11d_nmirror = { ...ART.c11d_hmirror, tint: { hueTo: 250, sat: 0.4, light: 0.75 } };
  if (ART.c11c_bird) ART.c11d_dazzle = { ...ART.c11c_bird, tint: { hueTo: 50, sat: 0.15, light: 1.25 } };
  // 中ボス（今 ある え を そのまま 写す）
  for (const [sp, base] of Object.entries(C11D_DUO_ART)) if (ART[base]) ART[sp] = { ...ART[base] };
  // さいごの ボス（2倍の こまかさ。monsters-c11d.js の artScale 0.5）
  ART.c11d_queen = { size: [224, 256], npc: 0.6, pal: pal(QN), draw: queen };
}
