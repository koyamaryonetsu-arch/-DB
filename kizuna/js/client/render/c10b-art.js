//   サー・ゲッコー … 砂色の 長い コートの トカゲの しんし（みどりの うろこ・黄色い 目・青い ちょうネクタイ）。砂時計の かたちの ステッキ。
//     コートの すそから 砂が さらさら こぼれる。コマ 2・3 … びしょぬれで しょんぼり（コートが こい 色・しずく・しっぽが たれる）
//   かいとう シロフクロウ … 白い 羽の マント・フクロウの 仮面（白に 金の ふち）・羽かざりの ぼうし（ベレーの 形）・うすい 水色の 服。
