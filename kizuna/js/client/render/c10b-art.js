import { fit, spark, bez } from './ch3-draw.js?v=cb02a9b15ddb';

const EYE = ['#ffffff', '#1a1026'];
const pal = (P) => [...new Set([...Object.values(P), ...EYE])];

// ───── しずくウオ（大きな 水の しずくの 中を およぐ 魚）─────
const FS = {
  D: '#5ab8f0', DD: '#2e7ac0', DL: '#bff0ff', // しずく
  F: '#f0a040', FD: '#c06a20', FL: '#ffd890', // 魚
  K: '#1a1026', W: '#ffffff',
};
function fish(g0, f) {
  const g = fit(g0, 48);
  const C = FS;
  const k = g.w / g.h;
  const up = f ? 0.03 : 0;
  // しずく（上が とがる）
  g.poly([[0.5, 0.08 - up], [0.7, 0.4 - up], [0.78, 0.6 - up], [0.72, 0.8 - up], [0.5, 0.9 - up], [0.28, 0.8 - up], [0.22, 0.6 - up], [0.3, 0.4 - up]], C.DD);
  g.poly([[0.5, 0.12 - up], [0.68, 0.42 - up], [0.75, 0.6 - up], [0.7, 0.78 - up], [0.5, 0.87 - up], [0.3, 0.78 - up], [0.25, 0.6 - up], [0.32, 0.42 - up]], C.D);
  g.ell(0.38, 0.5 - up, 0.05, 0.12, C.DL);
  // 魚（中で くるりと およぐ）
  const sw = f ? 0.03 : -0.03;
  g.ell(0.52, 0.62 - up, 0.15, 0.09, C.FD);
  g.ell(0.52, 0.61 - up, 0.14, 0.08, C.F);
  g.poly([[0.66, 0.61 - up], [0.76, 0.52 - up + sw], [0.76, 0.7 - up + sw]], C.FD);
  g.ell(0.5, 0.58 - up, 0.06, 0.03, C.FL);
  g.ell(0.42, 0.59 - up, 0.025, 0.025 * k, C.W);
  g.ell(0.415, 0.595 - up, 0.013, 0.013 * k, C.K);
  g.poly([[0.5, 0.52 - up], [0.56, 0.46 - up], [0.6, 0.53 - up]], C.FD);
  // あわ
  for (const [x, y, r] of [[0.6, 0.32, 0.025], [0.56, 0.24, 0.018], [0.64, 0.4, 0.015]]) g.ell(x, y - up - (f ? 0.02 : 0), r, r * k, C.DL);
}

// ───── すなぼうず（水が ぬけた 所に できる 砂の 山）─────
const SD = {
  S: '#d8b870', SD: '#a88840', SL: '#f0d898', // 砂
  G: '#8a6a30', // つぶ
  K: '#1a1026', W: '#ffffff', M: '#6a3a20',
};
function sandMan(g0, f) {
  const g = fit(g0, 52);
  const C = SD;
  const k = g.w / g.h;
  const up = f ? 0.02 : 0;
  // 砂の 山
  g.poly([[0.08, 0.92], [0.92, 0.92], [0.8, 0.66], [0.66, 0.4 - up], [0.5, 0.22 - up], [0.34, 0.4 - up], [0.2, 0.66]], C.SD);
  g.poly([[0.12, 0.9], [0.88, 0.9], [0.77, 0.66], [0.64, 0.42 - up], [0.5, 0.26 - up], [0.36, 0.42 - up], [0.23, 0.66]], C.S);
  g.poly([[0.36, 0.44 - up], [0.5, 0.28 - up], [0.46, 0.5 - up]], C.SL);
  // うで（砂の かたまり）
  const a = f ? 0.04 : 0;
  g.ell(0.16, 0.6 - a, 0.08, 0.06, C.SD);
  g.ell(0.84, 0.6 + a, 0.08, 0.06, C.SD);
  // 顔
  for (const ex of [0.42, 0.58]) { g.ell(ex, 0.52 - up, 0.04, 0.045 * k, C.W); g.ell(ex + 0.005, 0.53 - up, 0.02, 0.025 * k, C.K); }
  g.line(bez([[0.42, 0.64 - up], [0.5, 0.68 - up], [0.58, 0.64 - up]], 6), C.M, 1.6);
  // こぼれる つぶ
  for (let i = 0; i < 6; i++) g.ell(0.18 + i * 0.13, 0.95 - ((i + f) % 2) * 0.02, 0.012, 0.012 * k, C.G);
}

// ───── 中ボス: サー・ゲッコー（224×224）─────
const GK = {
  C: '#d8b878', CD: '#a8884a', CL: '#f0d8a0', // 砂色の コート
  L: '#6aa858', LD: '#3e7038', LL: '#9ad078', // うろこ
  Y: '#ffd84a', // 目
  T: '#3a6ac8', TD: '#24408a', // ちょうネクタイ
  V: '#5a3a28', VD: '#3a2418', // チョッキ
  H: '#c8a050', HD: '#8a6a2a', G: '#e8f4ff', S: '#e8c880', // ステッキ（金・ガラス・砂）
  R: '#f0d898', // こぼれる 砂
  WET: '#8a7448', WD: '#5ab8f0', WL: '#bff0ff', // ぬれた コート・しずく
  K: '#1a1026', W: '#ffffff', M: '#7a2a2a',
};
function gecko(g0, f) {
  const g = fit(g0, 224);
  const C = GK;
  const k = g.w / g.h;
  const wet = f >= 2;
  const fr = f % 2;
  const up = wet ? -0.02 : fr ? 0.008 : 0;
  const coat = wet ? C.WET : C.C;
  const coatD = wet ? '#5a4a2a' : C.CD;
  // しっぽ（うしろ。ぬれると たれる）
  g.line(bez(wet ? [[0.62, 0.8], [0.8, 0.9], [0.92, 0.94]] : [[0.62, 0.78], [0.84, 0.74], [0.92, 0.56]], 10), C.LD, 9);
  g.line(bez(wet ? [[0.62, 0.8], [0.8, 0.9], [0.92, 0.94]] : [[0.62, 0.78], [0.84, 0.74], [0.92, 0.56]], 10), C.L, 6);
  // 足
  for (const x of [0.4, 0.56]) { g.rect(x - 0.03, 0.82, 0.06, 0.1, C.LD); g.ell(x, 0.93, 0.06, 0.025, C.LD); }
  // 長い コート（すそが ひろがる）
  g.poly([[0.32, 0.4 - up], [0.64, 0.4 - up], [0.74, 0.86], [0.26, 0.86]], coatD);
  g.poly([[0.34, 0.41 - up], [0.62, 0.41 - up], [0.71, 0.84], [0.29, 0.84]], coat);
  if (!wet) g.poly([[0.36, 0.44 - up], [0.42, 0.44 - up], [0.36, 0.8]], C.CL);
  // コートの 前（チョッキ）・ボタン
  g.poly([[0.44, 0.41 - up], [0.52, 0.41 - up], [0.53, 0.7], [0.43, 0.7]], C.V);
  for (const y of [0.5, 0.57, 0.64]) g.ell(0.48, y - up, 0.01, 0.01 * k, C.H);
  // うで（左手は ステッキ）
  g.line([[0.34, 0.46 - up], [0.24, 0.62 - up]], coatD, 7);
  g.line([[0.62, 0.46 - up], [0.7, 0.6 - up]], coatD, 7);
  g.ell(0.24, 0.64 - up, 0.03, 0.03 * k, C.L);
  g.ell(0.7, 0.62 - up, 0.03, 0.03 * k, C.L);
  // 砂時計の かたちの ステッキ（ぬれると 下に つく）
  const sy = wet ? 0.08 : 0;
  g.line([[0.24, 0.62 - up + sy * 0.3], [0.2, 0.92]], C.HD, 3);
  const hx = 0.24, hy = 0.5 - up + sy;
  g.rect(hx - 0.045, hy - 0.08, 0.09, 0.015, C.H);
  g.rect(hx - 0.045, hy + 0.065, 0.09, 0.015, C.H);
  g.poly([[hx - 0.035, hy - 0.065], [hx + 0.035, hy - 0.065], [hx + 0.005, hy], [hx + 0.035, hy + 0.065], [hx - 0.035, hy + 0.065], [hx - 0.005, hy]], C.G);
  g.poly([[hx - 0.025, hy + 0.065], [hx + 0.025, hy + 0.065], [hx, hy + 0.03]], C.S);
  if (!wet) g.poly([[hx - 0.012, hy - 0.04], [hx + 0.012, hy - 0.04], [hx, hy - 0.01]], C.S);
  // 首・顔（トカゲ。前に のびた 口）
  g.rect(0.44, 0.33 - up, 0.08, 0.08, C.L);
  g.ell(0.5, 0.26 - up, 0.13, 0.1, C.LD);
  g.ell(0.5, 0.255 - up, 0.125, 0.095, C.L);
  g.ell(0.38, 0.29 - up, 0.08, 0.05, C.L); // 口の さき（左むき）
  g.line([[0.31, 0.3 - up], [0.45, 0.31 - up]], C.LD, 1.6);
  for (const [x, y] of [[0.5, 0.2], [0.56, 0.24], [0.6, 0.2], [0.46, 0.24]]) g.ell(x, y - up, 0.012, 0.01, C.LL);
  // 目（黄色・たての ひとみ。ぬれると 半分 とじる）
  g.ell(0.47, 0.22 - up, 0.035, 0.035 * k, C.LD);
  g.ell(0.47, 0.22 - up, 0.03, 0.03 * k, C.Y);
  if (wet) g.rect(0.44, 0.2 - up, 0.06, 0.02, C.L);
  else g.rect(0.467, 0.205 - up, 0.007, 0.03, C.K);
  // 青い ちょうネクタイ
  g.poly([[0.48, 0.4 - up], [0.43, 0.37 - up], [0.43, 0.43 - up]], C.TD);
  g.poly([[0.48, 0.4 - up], [0.53, 0.37 - up], [0.53, 0.43 - up]], C.TD);
  g.ell(0.48, 0.4 - up, 0.015, 0.015 * k, C.T);
  if (wet) {
    // びしょぬれ: しずく・頭の 上の 水たまり
    for (const [x, y] of [[0.34, 0.5], [0.66, 0.56], [0.4, 0.74], [0.6, 0.8], [0.56, 0.16], [0.3, 0.36]]) {
      g.ell(x, y + (fr ? 0.015 : 0), 0.012, 0.02, C.WD);
      g.ell(x - 0.004, y - 0.006 + (fr ? 0.015 : 0), 0.005, 0.008, C.WL);
    }
    g.ell(0.5, 0.95, 0.3, 0.03, C.WD);
  } else {
    // すそから こぼれる 砂
    for (let i = 0; i < 7; i++) g.ell(0.3 + i * 0.065, 0.88 + ((i + fr) % 3) * 0.025, 0.008, 0.008 * k, C.R);
    spark(g, 0.24, 0.42 + (fr ? 0.01 : 0), 0.018, C.S, '#ffffff');
  }
}

// ───── 中ボス: かいとう シロフクロウ（160×192）─────
const OW = {
  F: '#f4f6fa', FD: '#c8d0dc', FL: '#ffffff', // 白い 羽の マント
  B: '#a8c8e0', BD: '#7a9ab8', // 水色の 服
  M: '#ffffff', MG: '#d8b040', // 仮面（白・金の ふち）
  E: '#2a3a6a', // 目の あな
  P: '#c8a870', // くちばし
  H: '#5a6a9a', HD: '#3a4870', HF: '#e8eef8', // 羽かざりの ぼうし
  L: '#8a8aa8', // 足・手ぶくろ
  K: '#1a1026', W: '#ffffff',
};
function owl(g0, f) {
  const g = fit(g0, 160);
  const C = OW;
  const k = g.w / g.h;
  const bow = f >= 2;
  const fr = f % 2;
  const up = fr ? 0.008 : 0;
  const lean = bow ? 0.08 : 0; // おじぎ（上の 体が 前に たおれる）
  // マント（左右に ひろがる 羽）
  const sp = bow ? 0 : fr ? 0.02 : 0;
  g.poly([[0.5, 0.3 + lean], [0.12 - sp, 0.5], [0.06 - sp, 0.86], [0.28, 0.8], [0.38, 0.92], [0.5, 0.86], [0.62, 0.92], [0.72, 0.8], [0.94 + sp, 0.86], [0.88 + sp, 0.5]], C.FD);
  g.poly([[0.5, 0.32 + lean], [0.15 - sp, 0.52], [0.1 - sp, 0.82], [0.3, 0.77], [0.4, 0.88], [0.5, 0.83], [0.6, 0.88], [0.7, 0.77], [0.9 + sp, 0.82], [0.85 + sp, 0.52]], C.F);
  // 羽の すじ
  for (const x of [0.2, 0.3, 0.7, 0.8]) g.line([[x, 0.55], [x + (x < 0.5 ? -0.04 : 0.04), 0.8]], C.FD, 1.2);
  // 体（水色の 服）・足
  g.poly([[0.42, 0.4 + lean], [0.58, 0.4 + lean], [0.6, 0.82], [0.4, 0.82]], C.BD);
  g.poly([[0.43, 0.41 + lean], [0.57, 0.41 + lean], [0.58, 0.8], [0.42, 0.8]], C.B);
  for (const x of [0.46, 0.54]) { g.rect(x - 0.02, 0.8, 0.04, 0.1, C.L); g.ell(x, 0.91, 0.04, 0.02, C.L); }
  // 頭（白い 羽毛）
  const hy = 0.26 + lean - up;
  g.ell(0.5, hy, 0.13, 0.11, C.FD);
  g.ell(0.5, hy - 0.005, 0.125, 0.105, C.F);
  // フクロウの 仮面（白・金の ふち・大きな まるい 目の あな・小さな くちばし）
  g.poly([[0.38, hy - 0.02], [0.5, hy - 0.06], [0.62, hy - 0.02], [0.6, hy + 0.05], [0.5, hy + 0.07], [0.4, hy + 0.05]], C.MG);
  g.poly([[0.39, hy - 0.015], [0.5, hy - 0.05], [0.61, hy - 0.015], [0.59, hy + 0.045], [0.5, hy + 0.06], [0.41, hy + 0.045]], C.M);
  for (const ex of [0.45, 0.55]) {
    g.ell(ex, hy + 0.005, 0.035, 0.035 * k, C.MG);
    g.ell(ex, hy + 0.005, 0.028, 0.028 * k, C.E);
    if (!bow) g.ell(ex - 0.008, hy - 0.002, 0.008, 0.008 * k, C.W);
  }
  g.poly([[0.48, hy + 0.04], [0.52, hy + 0.04], [0.5, hy + 0.07]], C.P);
  if (bow) {
    // ぼうしを 取って むねに あてる（手に もつ）
    g.ell(0.62, 0.5 + lean, 0.08, 0.04, C.HD);
    g.ell(0.62, 0.49 + lean, 0.07, 0.035, C.H);
    g.line(bez([[0.6, 0.47 + lean], [0.66, 0.38 + lean], [0.74, 0.36 + lean]], 8), C.HF, 2.5);
    g.line([[0.56, 0.46 + lean], [0.6, 0.5 + lean]], C.L, 3);
    // 頭の 羽毛（ぼうしの ない 頭）
    for (const x of [0.46, 0.5, 0.54]) g.poly([[x - 0.02, hy - 0.09], [x + 0.02, hy - 0.09], [x, hy - 0.14]], C.F);
  } else {
    // 羽かざりの ぼうし（ベレーの 形。シルクハットでは ない）
    g.ell(0.5, hy - 0.1, 0.14, 0.04, C.HD);
    g.ell(0.52, hy - 0.115, 0.12, 0.045, C.H);
    g.line(bez([[0.58, hy - 0.13], [0.66, hy - 0.22], [0.76, hy - 0.24]], 8), C.HF, 3);
    g.line(bez([[0.58, hy - 0.13], [0.64, hy - 0.2], [0.72, hy - 0.2]], 8), C.FD, 1.2);
    // ひらひら まう 白い 羽
    for (const [x, y] of [[0.08, 0.3], [0.9, 0.24], [0.14, 0.12]]) {
      const yy = y + (fr ? 0.02 : 0);
      g.poly([[x, yy], [x + 0.03, yy - 0.03], [x + 0.05, yy - 0.01], [x + 0.02, yy + 0.02]], C.FL);
    }
  }
}

export function addC10bArt(ART) {
  // 色ちがい（今の 絵。新しい 絵では ない）
  if (ART.water_spirit) ART.c10b_spirit = { ...ART.water_spirit, tint: { hueTo: 190, sat: 0.6, light: 1.15 } };
  if (ART.sand_crab) ART.c10b_crab = { ...ART.sand_crab, tint: { hueTo: 220, sat: 0.9, light: 0.85 } };
  if (ART.star_owl) ART.c10b_iceowl = { ...ART.star_owl, tint: { hueTo: 195, sat: 0.7, light: 1.7 } };
  if (ART.frost_wolf) ART.c10b_wolf = { ...ART.frost_wolf, tint: { hueTo: 230, sat: 0.3, light: 1.15 } };
  if (ART.castle_armor) ART.c10b_armor = { ...ART.castle_armor, tint: { hueTo: 190, sat: 1.0, light: 1.4 } };
  // 新しい 絵（しずくウオ・すなぼうず）
  ART.c10b_fish = { size: [48, 48], pal: pal(FS), draw: fish };
  ART.c10b_sand = { size: [52, 48], pal: pal(SD), draw: sandMan };
  // 中ボス（2倍の こまかさ。monsters-c10b.js の artScale 0.5。台本の showMon でも 大きく）
  ART.c10b_gecko = { size: [224, 224], npc: 0.6, pal: pal(GK), draw: gecko };
  // シロフクロウの まぼろしも おなじ え（え では 見分けられない）
  ART.c10b_owl = { size: [160, 192], npc: 0.6, pal: pal(OW), draw: owl };
  ART.c10b_owl_fake = ART.c10b_owl;
}
