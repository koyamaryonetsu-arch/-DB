// ・色ちがい 5しゅ … みかがみの精（水の精）・うら砂ガニ（砂ガニ）・つららフクロウ（星読みフクロウ）・ゆきあかりオオカミ（こおりオオカミ）・氷のよろい（古城のよろい）
