//   コマ1・3 … 口を あけて 火を ちらす・うでを ふり上げる
function bowserBody(g0, ox, oy, s, up, giga) {
  const P = ([x, y]) => [ox + x * s, oy + y * s];
  const g = {
    w: g0.w, h: g0.h,
    ell: (x, y, rx, ry, c) => g0.ell(ox + x * s, oy + y * s, rx * s, ry * s, c),
    poly: (pts, c) => g0.poly(pts.map(P), c),
    line: (pts, c, lw = 1) => g0.line(pts.map(P), c, lw * s),
    rect: (x, y, w, h, c) => g0.rect(ox + x * s, oy + y * s, w * s, h * s, c),
  };
  const C = BW;
  const k = g0.w / g0.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // マント（うしろ）
  g.poly([[0.3, 0.3], [0.7, 0.3], [0.86, 0.98], [0.14, 0.98]], C.PD);
  g.poly([[0.32, 0.31], [0.68, 0.31], [0.82, 0.97], [0.18, 0.97]], C.P);
  // こうら（うしろ。とげ）
  g.ell(0.62, 0.56, 0.3, 0.3, C.GD);
  g.ell(0.63, 0.55, 0.27, 0.27, C.G);
  for (const [x, y] of [[0.6, 0.36], [0.78, 0.44], [0.86, 0.6], [0.8, 0.76], [0.66, 0.72], [0.7, 0.56]]) {
    R(x, y, 0.045, C.TD);
    g.poly([[x - 0.03, y], [x, y - 0.08], [x + 0.03, y]], C.T);
  }
  g.ell(0.63, 0.83, 0.26, 0.04, C.W);
  // 足（太い）・つめ
  for (const x of [0.36, 0.6]) {
    g.ell(x, 0.86, 0.1, 0.1, C.SD);
    g.ell(x, 0.85, 0.09, 0.09, C.S);
    for (const d of [-0.05, 0, 0.05]) g.poly([[x + d - 0.015, 0.93], [x + d, 0.99], [x + d + 0.015, 0.93]], C.T);
  }
  // おなか
  g.ell(0.44, 0.62, 0.2, 0.24, C.SD);
  g.ell(0.44, 0.61, 0.18, 0.22, C.W);
  for (let i = 0; i < 4; i++) g.line([[0.3, 0.48 + i * 0.07], [0.58, 0.48 + i * 0.07]], C.TD, 1.6);
  // 黒い 星の かけら（むね。ギガの ときは 大きく 光る）
  const gr = giga ? 0.07 : 0.04;
  R(0.44, 0.44, gr * 1.6, C.V);
  spark(g, 0.44, 0.44, gr, C.K, C.VL);
  // うで（コマ1 … ふり上げる）・うでわ
  const armL = up ? [[0.3, 0.42], [0.16, 0.3], [0.1, 0.16]] : [[0.3, 0.42], [0.14, 0.5], [0.12, 0.64]];
  const armR = up ? [[0.58, 0.42], [0.74, 0.3], [0.82, 0.18]] : [[0.58, 0.42], [0.72, 0.52], [0.74, 0.64]];
  for (const pts of [armL, armR]) {
    g.line(pts, C.SD, 20);
    g.line(pts, C.S, 15);
    const [x, y] = pts[1];
    R(x, y, 0.05, C.K);
    for (let i = 0; i < 4; i++) {
      const a = (i / 4) * Math.PI * 2;
      g.poly([[x + Math.cos(a) * 0.04, y + Math.sin(a) * 0.04 * k], [x + Math.cos(a) * 0.08, y + Math.sin(a) * 0.08 * k], [x + Math.cos(a + 0.5) * 0.045, y + Math.sin(a + 0.5) * 0.045 * k]], C.KL);
    }
    const [hx, hy] = pts[2];
    R(hx, hy, 0.045, C.S);
    for (const d of [-0.03, 0, 0.03]) g.poly([[hx + d - 0.012, hy - 0.03], [hx + d, hy - 0.075], [hx + d + 0.012, hy - 0.03]], C.T);
  }
  // 頭
  const hx = 0.42, hy = 0.22;
  g.ell(hx, hy, 0.16, 0.14, C.SD);
  g.ell(hx - 0.005, hy - 0.005, 0.15, 0.13, C.S);
  // 口（大きな あご）
  g.ell(hx - 0.06, hy + 0.08, 0.13, up ? 0.08 : 0.06, C.W);
  if (up) {
    g.ell(hx - 0.07, hy + 0.1, 0.09, 0.05, C.M);
    flame(g, hx - 0.2, hy + 0.12, 0.08, -0.08, -0.04, [C.F, C.FL]);
  } else g.line([[hx - 0.17, hy + 0.08], [hx - 0.06, hy + 0.11], [hx + 0.04, hy + 0.09]], C.M, 2);
  for (const d of [-0.14, 0.02]) g.poly([[hx + d, hy + 0.06], [hx + d + 0.02, hy + 0.11], [hx + d + 0.04, hy + 0.06]], C.T);
  // 鼻・目（つり上がった 目と 赤い まゆ）
  R(hx - 0.13, hy + 0.01, 0.025, C.SD);
  for (const dx of [-0.06, 0.04]) {
    g.ell(hx + dx, hy - 0.03, 0.035, 0.04, '#ffffff');
    g.ell(hx + dx - 0.01, hy - 0.025, 0.015, 0.025, '#1a1026');
  }
  g.poly([[hx - 0.12, hy - 0.1], [hx + 0.1, hy - 0.08], [hx + 0.1, hy - 0.05], [hx - 0.11, hy - 0.06]], C.HD);
  // 赤い かみ（うしろへ ぼうぼう）
  for (let i = 0; i < 4; i++) g.poly([[hx + 0.02 + i * 0.03, hy - 0.12], [hx + 0.16 + i * 0.03, hy - 0.2 + i * 0.05], [hx + 0.08 + i * 0.03, hy - 0.04]], i % 2 ? C.HD : C.H);
  // つの
  for (const dx of [-0.08, 0.08]) g.poly([[hx + dx - 0.03, hy - 0.11], [hx + dx + (dx < 0 ? -0.05 : 0.05), hy - 0.24], [hx + dx + 0.03, hy - 0.1]], C.T);
  // 古い おうかん
  g.poly([[hx - 0.07, hy - 0.11], [hx - 0.08, hy - 0.2], [hx - 0.04, hy - 0.15], [hx, hy - 0.22], [hx + 0.04, hy - 0.15], [hx + 0.08, hy - 0.2], [hx + 0.07, hy - 0.11]], C.CD);
  g.poly([[hx - 0.06, hy - 0.115], [hx - 0.07, hy - 0.18], [hx - 0.04, hy - 0.14], [hx, hy - 0.2], [hx + 0.04, hy - 0.14], [hx + 0.07, hy - 0.18], [hx + 0.06, hy - 0.115]], C.C);
  R(hx, hy - 0.13, 0.012, C.V);
}
function bowser(g0, f) {
  const g = fit(g0, 248);
  const C = BW;
  const giga = f >= 2;
  const up = f % 2;
  if (giga) {
    // ギガ: むらさきの 光の もや（うしろ）と え いっぱいの 体
    for (const [x, y, r] of [[0.2, 0.3, 0.12], [0.84, 0.24, 0.1], [0.12, 0.7, 0.1], [0.9, 0.66, 0.12]]) g.ell(x, y, r, r, C.PD);
    for (const [x, y] of [[0.1, 0.12], [0.9, 0.1], [0.06, 0.48], [0.95, 0.42]]) spark(g, x, y, 0.035, C.V, C.VL);
    bowserBody(g, 0.02, 0.02, 0.96, up, true);
  } else bowserBody(g, 0.18, 0.3, 0.7, up, false);
}

// ───── 橋のオノ（ようさいの 大橋を ささえる 大きな オノ）─────
const AX = {
  W: '#8a5a2a', WD: '#5a3a1a', // 木の 柱
  M: '#c8ccd8', MD: '#7a8090', ML: '#f4f6fa', // オノの 刃
  N: '#5a5a6a', // くさり
  R: '#c83a3a', // 赤い ひも
};
// 橋のオノ: 木の 柱に ささった 大きな オノ・くさりで 橋に つながる。コマ1 … オノが きらりと 光る
function bridgeAxe(g0, f) {
  const g = fit(g0, 36);
  const C = AX;
  const up = f ? 1 : 0;
  // 柱
  g.rect(0.42, 0.3, 0.16, 0.7, C.WD);
  g.rect(0.45, 0.3, 0.08, 0.7, C.W);
  // くさり（橋へ）
  for (let i = 0; i < 4; i++) g.ell(0.32 - i * 0.08, 0.62 + i * 0.08, 0.05, 0.025, C.N);
  // オノの え と 刃
  g.line([[0.5, 0.36], [0.5, 0.04]], C.WD, 3);
  g.poly([[0.5, 0.06], [0.94, 0.0], [0.98, 0.18], [0.92, 0.34], [0.5, 0.28]], C.MD);
  g.poly([[0.52, 0.08], [0.9, 0.03], [0.94, 0.18], [0.88, 0.3], [0.52, 0.25]], C.M);
  g.poly([[0.86, 0.04], [0.94, 0.18], [0.88, 0.3], [0.9, 0.16]], C.ML);
  g.rect(0.44, 0.12, 0.12, 0.06, C.R);
  if (up) spark(g, 0.9, 0.1, 0.1, C.ML, '#ffffff');
}

