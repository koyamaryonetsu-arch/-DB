function question(g, x, y, s, c) {
  g.line(bez([[x - s * 0.5, y - s * 0.5], [x - s * 0.4, y - s * 1.1], [x + s * 0.5, y - s * 1.0], [x + s * 0.4, y - s * 0.4], [x, y - s * 0.1], [x, y + s * 0.3]], 10), c, 2.4);
  g.ell(x, y + s * 0.65, s * 0.12, s * 0.12 * (g.w / g.h), c);
}
function nazokake(g0, f) {
  const g = fit(g0, 224);
  const C = NK;
  const k = g.w / g.h;
  const sway = f % 2 ? 0.008 : -0.008;
  // 天じょうの 石（大きな 板）
  g.rect(0.02, 0.0, 0.96, 0.1, C.TD);
  g.rect(0.03, 0.0, 0.94, 0.08, C.T);
  for (let i = 0; i < 6; i++) g.rect(0.06 + i * 0.16, 0.02, 0.1, 0.012, C.TL);
  g.line([[0.3, 0.08], [0.34, 0.04], [0.4, 0.07]], C.TD, 1.4);
  // しっぽ（天じょうへ くるり）
  g.line(bez([[0.78, 0.36], [0.94, 0.3], [0.9, 0.14], [0.8, 0.12]], 12), C.SD, 6);
  g.line(bez([[0.78, 0.36], [0.94, 0.3], [0.9, 0.14], [0.8, 0.12]], 12), C.S, 3.6);
  g.ell(0.8, 0.12, 0.03, 0.03 * k, C.SD);
  // うしろ足（天じょうに つく）
  for (const x of [0.28, 0.72]) {
    g.rect(x - 0.07, 0.08, 0.14, 0.14, C.SD);
    g.rect(x - 0.06, 0.08, 0.12, 0.13, C.S);
    for (let i = -1; i <= 1; i++) g.ell(x + i * 0.035, 0.09, 0.022, 0.016, C.SL);
  }
  // 体（さかさに すわる。上が おしり・下が むね）
  g.ell(0.5 + sway, 0.36, 0.3, 0.2, C.SD);
  g.ell(0.5 + sway, 0.35, 0.28, 0.19, C.S);
  g.ell(0.4 + sway, 0.28, 0.12, 0.06, C.SL);
  // 石の われめ
  g.line([[0.62 + sway, 0.3], [0.66 + sway, 0.36], [0.63 + sway, 0.42]], C.SX, 1.4);
  // 前足（下へ のびて、つめ）
  for (const x of [0.32, 0.68]) {
    g.rect(x - 0.05 + sway, 0.44, 0.1, 0.2, C.SD);
    g.rect(x - 0.04 + sway, 0.44, 0.08, 0.19, C.S);
    g.ell(x + sway, 0.66, 0.065, 0.04, C.SD);
    for (let i = -1; i <= 1; i++) g.poly([[x + i * 0.025 - 0.01 + sway, 0.68], [x + i * 0.025 + 0.01 + sway, 0.68], [x + i * 0.025 + sway, 0.72]], C.GD);
  }
  // かぶりもの（顔の まわり。青と 金の すじ）
  const hx = 0.5 + sway, hy = 0.66;
  g.poly([[hx - 0.2, hy - 0.16], [hx + 0.2, hy - 0.16], [hx + 0.24, hy + 0.14], [hx - 0.24, hy + 0.14]], C.GD);
  for (let i = 0; i < 6; i++) {
    const y = hy - 0.14 + i * 0.05;
    g.rect(hx - 0.22, y, 0.44, 0.025, i % 2 ? C.B : C.G);
  }
  // 顔（こちらを 向く。おだやか）
  g.ell(hx, hy + 0.0, 0.13, 0.14, C.FD);
  g.ell(hx, hy - 0.005, 0.12, 0.13, C.F);
  // おでこの 金の かざり（三角 … さかさの ピラミッド）
  g.poly([[hx - 0.04, hy - 0.11], [hx + 0.04, hy - 0.11], [hx, hy - 0.05]], C.G);
  // 目（光る）
  const glow = f % 2 ? C.EL : C.E;
  for (const d of [-1, 1]) {
    g.poly([[hx + d * 0.025, hy - 0.02], [hx + d * 0.085, hy - 0.035], [hx + d * 0.08, hy - 0.005], [hx + d * 0.03, hy + 0.0]], C.K);
    g.ell(hx + d * 0.055, hy - 0.016, 0.022, 0.012, glow);
  }
  // 鼻と 口（にっこり なぞめいた）
  g.line([[hx, hy - 0.0], [hx - 0.012, hy + 0.05], [hx + 0.01, hy + 0.055]], C.FD, 1.6);
  g.line(bez([[hx - 0.05, hy + 0.08], [hx, hy + 0.1], [hx + 0.05, hy + 0.08]], 8), C.SX, 2);
  // あごひげ（金）
  g.rect(hx - 0.02, hy + 0.12, 0.04, 0.08, C.GD);
  g.rect(hx - 0.015, hy + 0.12, 0.03, 0.07, C.G);
  // ？の 光（ふわふわ）
  const qy = f % 2 ? 0.0 : 0.02;
  question(g, 0.12, 0.6 + qy, 0.05, C.Q);
  question(g, 0.88, 0.56 - qy, 0.04, C.Q);
  if (f % 2) spark(g, 0.86, 0.78, 0.03, C.Q, '#ffffff');
  else spark(g, 0.14, 0.82, 0.03, C.Q, '#ffffff');
}

