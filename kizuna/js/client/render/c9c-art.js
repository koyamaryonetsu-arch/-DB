// 上下 さかさに かく（ひっくり返った メカ）
function flipY(g) {
  const w = Object.create(g);
  const fy = (pts) => pts.map(([x, y]) => [x, 1 - y]);
  w.ell = (x, y, rx, ry, c) => g.ell(x, 1 - y, rx, ry, c);
  w.rect = (x, y, rw, rh, c) => g.rect(x, 1 - y - rh, rw, rh, c);
  w.poly = (pts, c) => g.poly(fy(pts), c);
  w.line = (pts, c, lw) => g.line(fy(pts), c, lw);
  return w;
}

