function mecha(g, f, dizzy) {
  const C = HK;
  const k = g.w / g.h;
  const up = f % 2 ? 0.008 : 0;
  // 足
  for (const x of [0.32, 0.68]) {
    g.rect(x - 0.05, 0.86, 0.1, 0.08, C.ID);
    g.ell(x, 0.95, 0.09, 0.03, C.I);
  }
  // 下の ふた
  g.ell(0.5, 0.86, 0.36, 0.05, C.WD);
  g.rect(0.14, 0.8, 0.72, 0.06, C.W);
  g.rect(0.14, 0.8, 0.72, 0.015, C.WL);
  // 金の はしら（左右）
  for (const x of [0.16, 0.84]) {
    g.rect(x - 0.025, 0.24, 0.05, 0.56, C.MD);
    g.rect(x - 0.015, 0.24, 0.03, 0.56, C.M);
    g.ell(x, 0.52, 0.035, 0.02, C.ML);
  }
  // ガラス（上の ふくらみ・下の ふくらみ）
  g.poly([[0.22, 0.26], [0.78, 0.26], [0.72, 0.42], [0.54, 0.52], [0.46, 0.52], [0.28, 0.42]], C.GD);
  g.poly([[0.24, 0.27], [0.76, 0.27], [0.7, 0.41], [0.53, 0.51], [0.47, 0.51], [0.3, 0.41]], C.G);
  g.poly([[0.46, 0.52], [0.54, 0.52], [0.72, 0.62], [0.78, 0.79], [0.22, 0.79], [0.28, 0.62]], C.GD);
  g.poly([[0.47, 0.53], [0.53, 0.53], [0.7, 0.63], [0.76, 0.78], [0.24, 0.78], [0.3, 0.63]], C.G);
  // 上の 砂（へって いる）と 下の 砂の 山
  g.poly([[0.33, 0.38], [0.67, 0.38], [0.54, 0.49], [0.46, 0.49]], C.N);
  g.poly([[0.3, 0.78], [0.7, 0.78], [0.6, 0.7], [0.5, 0.64], [0.4, 0.7]], C.ND);
  g.poly([[0.34, 0.77], [0.66, 0.77], [0.5, 0.67]], C.N);
  // 落ちる 砂の すじ
  for (let i = 0; i < 4; i++) g.rect(0.495, 0.52 + ((i * 0.04 + (f % 2 ? 0.02 : 0)) % 0.14), 0.01, 0.02, C.N);
  // ガラスの 光
  g.line([[0.28, 0.3], [0.32, 0.38]], C.GL, 2);
  g.line([[0.28, 0.66], [0.3, 0.74]], C.GL, 2);
  // 上の ふた（まど。3人組が 乗る）
  g.rect(0.12, 0.16 - up, 0.76, 0.1, C.WD);
  g.rect(0.13, 0.16 - up, 0.74, 0.08, C.W);
  g.rect(0.22, 0.04 - up, 0.56, 0.14, C.WD);
  g.rect(0.24, 0.05 - up, 0.52, 0.12, C.V);
  // 3人組（小さく。左 キラジョ … リボン・まん中 ボヤッチ … 長い 鼻と めがね・右 ズラッカ … 大きな 顔と はちまき）
  const heads = [[0.33, C.H1], [0.5, C.H2], [0.67, C.H3]];
  heads.forEach(([x, hair], i) => {
    const hy = 0.12 - up + (i === 1 ? -0.005 : 0);
    const r = i === 2 ? 0.05 : 0.04;
    g.ell(x, hy, r, r * k, C.S);
    g.ell(x, hy - r * 0.6 * k, r * 0.95, r * 0.5 * k, hair);
    if (dizzy) {
      for (const d of [-1, 1]) g.line(bez([[x + d * 0.018, hy], [x + d * 0.028, hy - 0.01], [x + d * 0.012, hy - 0.012], [x + d * 0.016, hy + 0.004]], 6), C.K, 1);
    } else {
      for (const d of [-1, 1]) g.ell(x + d * 0.016, hy, 0.006, 0.008 * k, C.K);
    }
    if (i === 0) { g.ell(x - 0.04, hy - 0.035, 0.022, 0.016, C.P); g.ell(x - 0.012, hy - 0.04, 0.016, 0.014, C.P); }
    if (i === 1) { g.line([[x - 0.02, hy - 0.002], [x + 0.02, hy - 0.002]], C.IL, 1); g.poly([[x, hy + 0.004], [x + 0.03, hy + 0.016], [x, hy + 0.02]], C.S); }
    if (i === 2) g.rect(x - 0.05, hy - 0.03, 0.1, 0.012, C.R);
  });
  // ホシドロ一味の 星の しるし（上の ふた）
  spark(g, 0.5, 0.21 - up, 0.03, C.Y, '#fff8d0');
  // うで: 左は ドリル・右は パンチ
  g.rect(0.04, 0.44, 0.1, 0.05, C.ID);
  g.poly([[0.02, 0.4], [0.08, 0.4], [0.05, 0.3 + (f % 2 ? -0.01 : 0)]], C.IL);
  g.poly([[0.02, 0.4], [0.05, 0.3 + (f % 2 ? -0.01 : 0)], [0.04, 0.4]], C.I);
  g.rect(0.86, 0.44, 0.1, 0.05, C.ID);
  g.ell(0.95, 0.42, 0.045, 0.045 * k, C.R);
  g.ell(0.94, 0.41, 0.02, 0.02 * k, C.RD);
  // 赤い ボタン（ポチッとね）
  g.ell(0.84, 0.82, 0.04, 0.02, C.RD);
  g.ell(0.84, 0.81, 0.035, 0.016, C.R);
}
function hikkuri(g0, f) {
  const g = fit(g0, 232);
  if (f >= 2) {
    // ひっくり返って 目を 回す（上下 さかさ・星が くるくる）
    mecha(flipY(g), f, true);
    const s = f % 2 ? 0.02 : -0.02;
    for (const [x, y] of [[0.3, 0.98], [0.5, 0.94], [0.7, 0.98]]) spark(g, x + s, y - 0.04, 0.025, '#fff4a0', '#ffffff');
    return;
  }
  mecha(g, f, false);
}

