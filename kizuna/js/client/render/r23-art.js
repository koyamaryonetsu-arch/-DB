// まるい ゼリーの からだ（ぷるりん なかま）。cx・cy … まんなか、rx・ry … 大きさ、sq … つぶれ
function jellyBody(g, cx, cy, rx, ry, sq, c, cD, cL, tip = true) {
  g.ell(cx, cy + 0.02, rx + sq + 0.01, ry - sq + 0.01, cD);
  g.ell(cx, cy, rx + sq, ry - sq, c);
  if (tip) g.poly([[cx - rx * 0.28, cy - ry * 0.8 + sq], [cx, cy - ry * 1.55 + sq * 2], [cx + rx * 0.28, cy - ry * 0.8 + sq]], c);
  g.ell(cx - rx * 0.4, cy - ry * 0.4 + sq, rx * 0.24, ry * 0.18, cL);
  g.ell(cx - rx * 0.58, cy - ry * 0.05 + sq, rx * 0.08, ry * 0.12, cL);
}
// ゼリーの かお（め・くち）
function jellyFace(g, cx, cy, r, sq, mouth, tongue) {
  g.eye(cx - r * 2.9, cy + sq, r, 0.3);
  g.eye(cx + r * 2.9, cy + sq, r, 0.3);
  g.poly([[cx - r * 0.9, cy + r * 1.9 + sq], [cx + r * 0.9, cy + r * 1.9 + sq], [cx, cy + r * 3 + sq]], mouth);
  g.ell(cx, cy + r * 2.65 + sq, r * 0.45, r * 0.3, tongue);
}

