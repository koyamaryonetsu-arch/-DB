// 水の精: しずくの 形の 体の 少女の ような 精。かみの毛は 水の ながれ（上へ ゆらめく）、うでは 水の リボン（左右に ひろがる）、
// 下は うずを まいて 細く なる。手の 先に いやしの 光。コマ1で リボンが 上がり、光が つよく なる
function waterSpirit(g0, f) {
  const g = fit(g0, 52);
  const C = SPIRIT;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const up = f ? -0.04 : 0;
  // うでの 水の リボン（左右に 大きく。ゆらゆら）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    const rib = bez([[X(0.08), 0.42], [X(0.22), 0.36 + up], [X(0.34), 0.5 - up], [X(0.47), 0.4 + up]], 14);
    taper(g, rib, 0.075, 0.02, C.WD);
    taper(g, rib, 0.05, 0.012, C.W);
    taper(g, rib.slice(2, 10), 0.02, 0.008, C.WL);
    const [ex, ey] = rib[14];
    R(ex, ey, 0.035, C.G);
    R(ex, ey, 0.018, C.GL);
  }
  // 下の うず（細く なって まく）
  const tail = bez([[0.5, 0.62], [0.58, 0.78], [0.4, 0.86], [0.52, 0.97]], 14);
  taper(g, tail, 0.2, 0.02, C.WDD);
  taper(g, tail, 0.16, 0.012, C.WD);
  taper(g, tail.slice(0, 9), 0.1, 0.03, C.W);
  // 体（しずくの 形）
  g.poly([[0.5, 0.26], [0.62, 0.36], [0.66, 0.5], [0.6, 0.64], [0.5, 0.68], [0.4, 0.64], [0.34, 0.5], [0.38, 0.36]], C.WDD);
  g.poly([[0.5, 0.28], [0.6, 0.37], [0.63, 0.5], [0.58, 0.62], [0.5, 0.655], [0.42, 0.62], [0.37, 0.5], [0.4, 0.37]], C.W);
  g.poly([[0.44, 0.38], [0.5, 0.33], [0.47, 0.52], [0.41, 0.56], [0.395, 0.46]], C.WL);
  g.line([[0.43, 0.42], [0.42, 0.52]], C.WH, 1.2);
  // むねの いやしの 玉
  R(0.5, 0.48, 0.03, C.G);
  R(0.495, 0.474, 0.012, C.GL);
  // かみの毛（水の ながれ。頭の 上から 左右へ ながれ落ちて、かたの 下で はねる）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    for (const [dx, w, len] of [[0.04, 0.09, 1], [0.08, 0.06, 0.8]]) {
      const hair = bez([[X(dx), 0.12], [X(0.2 + dx * 0.4), 0.06 + up * 0.5], [X(0.26), 0.26], [X(0.2 + dx), 0.3 + 0.12 * len]], 12);
      taper(g, hair, w, 0.012, C.WD);
      taper(g, hair, w * 0.55, 0.006, C.WL);
    }
  }
  // 頭の 上の しずくの まげ
  g.poly([[0.46, 0.12], [0.5, 0.0 + up * 0.5], [0.54, 0.12]], C.WD);
  g.poly([[0.475, 0.11], [0.5, 0.03 + up * 0.5], [0.525, 0.11]], C.WL);
  // 頭
  g.ell(0.5, 0.2, 0.11, 0.1, C.WD);
  g.ell(0.5, 0.205, 0.095, 0.085, C.W);
  g.ell(0.47, 0.18, 0.04, 0.03, C.WH);
  // 目（やさしく ほそい）と 口
  g.ell(0.46, 0.22, 0.018, 0.012, C.EY);
  g.ell(0.54, 0.22, 0.018, 0.012, C.EY);
  R(0.455, 0.216, 0.005, C.WH);
  R(0.535, 0.216, 0.005, C.WH);
  g.line([[0.485, 0.26], [0.5, 0.265], [0.515, 0.26]], C.WDD, 1);
  // まわりの しずく
  const drops = f ? [[0.2, 0.2], [0.82, 0.24], [0.28, 0.72], [0.74, 0.7], [0.14, 0.58]] : [[0.22, 0.25], [0.8, 0.18], [0.3, 0.68], [0.72, 0.76], [0.86, 0.56]];
  drops.forEach(([x, y], i) => {
    R(x, y, i % 2 ? 0.014 : 0.02, C.WL);
    R(x - 0.004, y - 0.006, 0.006, C.WH);
  });
  if (f) spark(g, 0.5, 0.47, 0.06, C.GL, C.GL);
}

