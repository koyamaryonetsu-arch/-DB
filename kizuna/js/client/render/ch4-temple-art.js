const CRAB = {
  S: '#c8904a', SL: '#e2b070', SH: '#f4d49a', SD: '#8e5e2a', SDD: '#5a3818', // こうら（砂いろ）
  R: '#b85a3a', RL: '#d8805a', // はさみの 先
  E: '#1a1026', EW: '#f8f0d8', // 目
  N: '#d8b878', // 足もとの 砂
};
// 砂ガニ: 砂から 半分 出た 大きな カニ。2本の 大きな はさみを 上げ、目は ぴょこんと 立つ。こうらに 砂の もよう。
// コマ1で はさみを ひらく
function sandCrab(g0, f) {
  const g = fit(g0, 54);
  const C = CRAB;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const op = f ? 0.06 : 0.02;
  // 足もとの 砂
  g.ell(0.5, 0.93, 0.46, 0.06, C.SD);
  g.ell(0.5, 0.92, 0.42, 0.045, C.N);
  // あし（左右 3本ずつ）
  for (const s of [-1, 1]) {
    for (let i = 0; i < 3; i++) {
      const X = (x) => 0.5 + s * x;
      const leg = [[X(0.2), 0.68 + i * 0.03], [X(0.33 + i * 0.03), 0.62 + i * 0.05], [X(0.4 + i * 0.03), 0.86]];
      g.line(leg, C.SDD, 3);
      g.line(leg, C.SD, 1.8);
    }
  }
  // こうら
  g.ell(0.5, 0.66, 0.3, 0.2, C.SDD);
  g.ell(0.5, 0.645, 0.28, 0.18, C.S);
  g.ell(0.44, 0.6, 0.15, 0.08, C.SL);
  g.ell(0.4, 0.58, 0.06, 0.03, C.SH);
  for (const [x, y] of [[0.36, 0.7], [0.5, 0.74], [0.64, 0.7], [0.58, 0.6]]) R(x, y, 0.018, C.SD);
  g.line([[0.24, 0.68], [0.36, 0.76], [0.5, 0.79], [0.64, 0.76], [0.76, 0.68]], C.SD, 1.2);
  // 目（ぴょこんと 立つ）
  for (const x of [0.43, 0.57]) {
    g.line([[x, 0.5], [x + (x - 0.5) * 0.5, 0.36]], C.SDD, 2.2);
    R(x + (x - 0.5) * 0.5, 0.34, 0.032, C.EW);
    R(x + (x - 0.5) * 0.5 + 0.004, 0.342, 0.016, C.E);
  }
  // はさみ（左右。上げて ひらく）
  for (const s of [-1, 1]) {
    const X = (x) => 0.5 + s * x;
    g.line([[X(0.24), 0.6], [X(0.34), 0.48], [X(0.36), 0.36]], C.SDD, 4);
    g.line([[X(0.24), 0.6], [X(0.34), 0.48], [X(0.36), 0.36]], C.SD, 2.6);
    // はさみの 本体
    g.ell(X(0.37), 0.28, 0.1, 0.1, C.SDD);
    g.ell(X(0.37), 0.275, 0.085, 0.085, C.S);
    g.ell(X(0.35), 0.25, 0.035, 0.03, C.SL);
    // 上の は（ひらく）
    g.poly([[X(0.3), 0.22], [X(0.38), 0.04 - op], [X(0.44), 0.08 - op], [X(0.42), 0.22]], C.SDD);
    g.poly([[X(0.32), 0.21], [X(0.385), 0.07 - op], [X(0.425), 0.1 - op], [X(0.405), 0.21]], C.R);
    g.line([[X(0.33), 0.2], [X(0.38), 0.09 - op]], C.RL, 1);
    // 下の は
    g.poly([[X(0.42), 0.24], [X(0.47), 0.1 + op], [X(0.48), 0.2]], C.SDD);
    g.poly([[X(0.425), 0.23], [X(0.462), 0.13 + op], [X(0.47), 0.2]], C.R);
  }
  // 口もとの あわ
  if (f) for (const [x, y] of [[0.47, 0.5], [0.53, 0.49], [0.5, 0.46]]) R(x, y, 0.012, C.SH);
}

