const WDRAGON = {
  B: '#2e6aa8', BL: '#4a8ccc', BH: '#8cc4ec', BD: '#1c4472', BDD: '#0e2848', // うろこ（青）
  U: '#c8e6d8', UD: '#8ab8a8', // おなか
  F: '#3ab0a0', FL: '#7ad8c8', // ひれ・とさか
  E: '#ffd040', P: '#1a1026', T: '#f4f0e0', M: '#5a1a2a', // 目・歯・口
  W: '#5ab8e8', WH: '#e0f6ff', // 水
};
// 水竜: 水面から S字に 首を もたげた 竜（左むき）。せなかに ひれの とさか・2本の つの・ひげ。口を あけて 水を はく。
// 下は 水の わと しぶき。コマ1で 首が 上がり、口が 大きく あく
function waterDragon(g0, f) {
  const g = fit(g0, 64);
  const C = WDRAGON;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const lift = f ? -0.03 : 0;
  // 水面（うしろ）
  g.ell(0.62, 0.89, 0.38, 0.08, C.BDD);
  g.ell(0.62, 0.885, 0.35, 0.065, C.W);
  // しっぽ（右の 水面から 出る）
  const tail = bez([[0.86, 0.86], [0.96, 0.74], [0.92, 0.6], [0.84, 0.62]], 10);
  taper(g, tail, 0.08, 0.02, C.BDD);
  taper(g, tail, 0.06, 0.012, C.B);
  g.poly([[0.84, 0.62], [0.78, 0.54], [0.86, 0.57], [0.8, 0.66]], C.F);
  // からだ（S字）
  const sp = bez([[0.72, 0.9], [0.8, 0.66], [0.5, 0.62], [0.5, 0.44], [0.48, 0.28 + lift], [0.32, 0.2 + lift]], 22);
  taper(g, sp, 0.3, 0.15, C.BDD);
  taper(g, sp, 0.26, 0.13, C.B);
  // おなか（内がわ）
  taper(g, sp.slice(2, 20).map(([x, y]) => [x - 0.045, y + 0.01]), 0.1, 0.06, C.UD);
  taper(g, sp.slice(3, 19).map(([x, y]) => [x - 0.048, y + 0.012]), 0.065, 0.04, C.U);
  for (let i = 4; i < 19; i += 2) {
    const [x, y] = sp[i];
    g.line([[x - 0.06, y], [x - 0.005, y + 0.012]], C.UD, 0.9);
  }
  // うろこの もよう・明るい ふち
  for (let i = 3; i < 20; i += 3) {
    const [x, y] = sp[i];
    R(x + 0.04, y - 0.01, 0.018, C.BL);
    R(x + 0.035, y - 0.016, 0.008, C.BH);
  }
  // せなかの ひれの とさか
  for (let i = 4; i < 20; i += 3) {
    const [x, y] = sp[i];
    const [x2, y2] = sp[i + 1];
    const nx = (y2 - y) * 2.2, ny = -(x2 - x) * 2.2;
    g.poly([[x + 0.06, y], [x + 0.06 + nx * 0.5 + 0.06, y + ny * 0.5 - 0.06], [x2 + 0.06, y2]], C.F);
    g.line([[x + 0.06, y], [x + 0.08 + nx * 0.4, y + ny * 0.4 - 0.04]], C.FL, 0.9);
  }
  // 頭（左むき）
  const [hx, hy] = sp[22];
  const open = f ? 0.06 : 0.035;
  g.poly([[hx + 0.1, hy - 0.08], [hx - 0.04, hy - 0.09], [hx - 0.16, hy - 0.04], [hx - 0.2, hy + 0.01], [hx - 0.08, hy + 0.02], [hx + 0.1, hy + 0.06]], C.BDD);
  g.poly([[hx + 0.09, hy - 0.07], [hx - 0.04, hy - 0.08], [hx - 0.15, hy - 0.035], [hx - 0.185, hy + 0.005], [hx - 0.08, hy + 0.012], [hx + 0.09, hy + 0.05]], C.B);
  g.line([[hx + 0.06, hy - 0.065], [hx - 0.1, hy - 0.05]], C.BH, 1);
  // 下あご（あける）
  g.poly([[hx + 0.06, hy + 0.04], [hx - 0.08, hy + 0.02 + open], [hx - 0.17, hy + 0.025 + open], [hx - 0.1, hy + 0.06 + open], [hx + 0.06, hy + 0.08]], C.BD);
  g.poly([[hx - 0.16, hy + 0.012], [hx - 0.06, hy + 0.018], [hx - 0.08, hy + 0.018 + open], [hx - 0.16, hy + 0.022 + open]], C.M);
  for (let i = 0; i < 4; i++) {
    const x = hx - 0.15 + i * 0.026;
    g.poly([[x, hy + 0.012], [x + 0.014, hy + 0.012], [x + 0.007, hy + 0.034]], C.T);
  }
  // つの・ひげ
  g.poly([[hx + 0.02, hy - 0.08], [hx + 0.1, hy - 0.17], [hx + 0.07, hy - 0.08]], C.UD);
  g.poly([[hx + 0.07, hy - 0.07], [hx + 0.17, hy - 0.16], [hx + 0.11, hy - 0.06]], C.U);
  g.line([[hx - 0.16, hy + 0.005], [hx - 0.22, hy + 0.06], [hx - 0.2, hy + 0.12]], C.FL, 1);
  // 目
  R(hx - 0.04, hy - 0.04, 0.028, C.BDD);
  R(hx - 0.04, hy - 0.042, 0.02, C.E);
  R(hx - 0.044, hy - 0.044, 0.008, C.P);
  // 口から あふれる 水
  if (f) {
    R(hx - 0.22, hy + 0.05, 0.03, C.W);
    R(hx - 0.27, hy + 0.08, 0.02, C.WH);
  }
  // 手前の 水の わと しぶき（からだが 水から 出る）
  g.ell(0.62, 0.93, 0.36, 0.06, C.BD);
  g.ell(0.62, 0.935, 0.33, 0.045, C.W);
  for (const [x0, x1, y] of [[0.34, 0.46, 0.935], [0.56, 0.7, 0.95], [0.76, 0.88, 0.935]]) g.line([[x0, y], [(x0 + x1) / 2, y - 0.012], [x1, y]], C.WH, 1.2);
  const spl = f ? [[0.62, 0.8], [0.8, 0.82], [0.4, 0.84]] : [[0.6, 0.84], [0.82, 0.86], [0.38, 0.86]];
  for (const [x, y] of spl) R(x, y, 0.016, C.WH);
}

