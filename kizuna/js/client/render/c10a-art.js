function kabiMecha(g, C, f, stop) {
  const k = g.w / g.h;
  const y0 = stop ? 0.08 : f ? -0.012 : 0;
  // かげ
  g.ell(0.5, 0.94, stop ? 0.3 : 0.22, 0.03, '#00000033');
  // 横の プロペラ（2つ。止まると 下を むく）
  for (const s of [-1, 1]) {
    const x = 0.5 + s * 0.34;
    g.rect(x - 0.01, 0.62 + y0, 0.02, 0.08, C.PD);
    if (stop) g.poly([[x - 0.02, 0.7 + y0], [x + 0.02, 0.7 + y0], [x + s * 0.03, 0.82 + y0]], C.P);
    else if (f) g.ell(x, 0.6 + y0, 0.1, 0.018, C.P);
    else { g.ell(x, 0.6 + y0, 0.04, 0.018, C.P); g.line([[x - 0.1, 0.6 + y0], [x + 0.1, 0.6 + y0]], C.PD, 1); }
  }
  // 丸い 玉
  g.ell(0.5, 0.7 + y0, 0.28, 0.22, C.BD);
  g.ell(0.5, 0.69 + y0, 0.27, 0.21, C.B);
  g.ell(0.4, 0.62 + y0, 0.08, 0.05, C.BL);
  // まんなかの おび と ねじ
  g.line([[0.24, 0.72 + y0], [0.76, 0.72 + y0]], C.BD, 2);
  for (const x of [0.3, 0.42, 0.58, 0.7]) g.ell(x, 0.72 + y0, 0.01, 0.01 * k, C.BL);
  // ほうしの ふき出し口（下に 3つ）
  for (const x of [0.4, 0.5, 0.6]) { g.ell(x, 0.88 + y0, 0.03, 0.02, C.BD); g.ell(x, 0.885 + y0, 0.02, 0.012, stop ? '#5a5a4a' : C.N); }
  // ほうし（動いて いる 時だけ）
  if (!stop) for (const [x, y] of [[0.36, 0.95], [0.5, 0.97], [0.64, 0.94], [0.44, 0.99]]) g.ell(x + (f ? 0.01 : -0.01), y, 0.012, 0.012 * k, C.NL);
  return y0;
}
function moldBody(g, C, f, stop, y0) {
  const k = g.w / g.h;
  const up = stop ? -0.04 : f ? 0.008 : 0;
  // しめった マント（玉の 上から 出る 上半身）
  g.poly([[0.32, 0.56 + y0], [0.68, 0.56 + y0], [0.62, 0.38 - up], [0.38, 0.38 - up]], C.CD);
  g.poly([[0.34, 0.55 + y0], [0.66, 0.55 + y0], [0.6, 0.39 - up], [0.4, 0.39 - up]], C.C);
  g.line([[0.44, 0.42 - up], [0.42, 0.54 + y0]], C.CL, 1.4);
  // しずく
  for (const [x, y] of [[0.36, 0.58], [0.64, 0.6], [0.52, 0.6]]) g.ell(x, y + y0 + (f ? 0.01 : 0), 0.01, 0.016, C.DR);
  // むねの 金の ボタン
  g.ell(0.5, 0.46 - up, 0.012, 0.012 * k, C.MO);
  // 顔
  g.ell(0.5, 0.3 - up, 0.1, 0.1, C.SD);
  g.ell(0.5, 0.295 - up, 0.095, 0.095, C.S);
  // 目（左は かためがね）
  g.ell(0.46, 0.3 - up, 0.034, 0.034 * k, C.MOD);
  g.ell(0.46, 0.3 - up, 0.028, 0.028 * k, C.MW);
  g.line([[0.49, 0.32 - up], [0.5, 0.42 - up]], C.MO, 1);
  if (stop) {
    g.line([[0.445, 0.305 - up], [0.475, 0.305 - up]], C.K, 1.4);
    g.line([[0.525, 0.305 - up], [0.555, 0.305 - up]], C.K, 1.4);
    g.line(bez([[0.47, 0.36 - up], [0.5, 0.345 - up], [0.53, 0.36 - up]], 6), C.M, 1.4);
  } else {
    g.ell(0.46, 0.3 - up, 0.012, 0.016 * k, C.K);
    g.ell(0.54, 0.3 - up, 0.012, 0.016 * k, C.K);
    g.line(bez([[0.47, 0.35 - up], [0.5, 0.37 - up], [0.54, 0.345 - up]], 6), C.M, 1.4);
  }
  // きのこの かさの ぼうし（ひろい かさ・クリームの 水玉。止まると かたむく）
  const tilt = stop ? 0.03 : 0;
  g.poly([[0.28, 0.22 - up + tilt], [0.72, 0.22 - up - tilt], [0.66, 0.14 - up], [0.58, 0.08 - up], [0.42, 0.08 - up], [0.34, 0.14 - up]], C.HD);
  g.poly([[0.3, 0.21 - up + tilt], [0.7, 0.21 - up - tilt], [0.64, 0.14 - up], [0.57, 0.09 - up], [0.43, 0.09 - up], [0.36, 0.14 - up]], C.H);
  g.ell(0.42, 0.12 - up, 0.04, 0.02, C.HL);
  for (const [x, y, r] of [[0.4, 0.16, 0.022], [0.52, 0.12, 0.02], [0.62, 0.17, 0.018], [0.48, 0.19, 0.014]]) g.ell(x, y - up, r, r * k, C.HS);
  // ステッキ（右手）
  if (!stop) {
    g.line([[0.64, 0.5 - up], [0.74, 0.34 - up]], C.CD, 3);
    g.line([[0.74, 0.34 - up], [0.78, 0.18 - up]], C.MOD, 1.6);
    g.ell(0.78, 0.17 - up, 0.016, 0.016 * k, C.MO);
  } else {
    g.line([[0.62, 0.52 + y0], [0.72, 0.6 + y0]], C.CD, 3);
  }
}
function mold(g0, f) {
  const g = fit(g0, 224);
  const C = MD;
  const stop = f >= 2;
  const y0 = kabiMecha(g, C, f % 2, stop);
  moldBody(g, C, f % 2, stop, y0);
  if (stop) {
    // けむり（メカが 止まった）
    for (const [x, y, r] of [[0.2, 0.62, 0.05], [0.84, 0.6, 0.05], [0.78, 0.5, 0.04]]) g.ell(x, y - (f % 2 ? 0.02 : 0), r, r * 0.8, C.SM);
  } else {
    // まわりの ほうし
    for (const [x, y] of [[0.16, 0.3], [0.86, 0.26], [0.2, 0.46], [0.82, 0.44]]) spark(g, x, y + (f ? 0.02 : 0), 0.022, C.N, C.NL);
  }
}

