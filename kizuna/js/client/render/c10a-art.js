// ───── はっぱミノムシ（大きな 葉を まいて 根から ぶら下がる）─────
const BG = {
  G: '#5aa84a', GD: '#3a7a32', GL: '#9ad87a', // 葉
  T: '#8a6a44', // 糸と 根
  F: '#ffe0b0', K: '#1a1026', W: '#ffffff', P: '#ff9ab0',
};
function bag(g0, f) {
  const g = fit(g0, 44);
  const C = BG;
  const k = g.w / g.h;
  const sw = f ? 0.03 : -0.03;
  // 上の 根と 糸
  g.rect(0, 0, 1, 0.05, C.T);
  g.line([[0.5, 0.04], [0.5 + sw, 0.2]], C.T, 1.2);
  // みの（葉を かさねる）
  const cx = 0.5 + sw;
  g.ell(cx, 0.58, 0.24, 0.36, C.GD);
  for (const [dx, y, r] of [[-0.08, 0.36, 0.14], [0.08, 0.42, 0.14], [-0.1, 0.56, 0.15], [0.1, 0.62, 0.15], [0, 0.78, 0.13]]) {
    g.ell(cx + dx, y, r, r * 0.9, C.G);
    g.line([[cx + dx - r * 0.6, y], [cx + dx + r * 0.6, y]], C.GD, 1);
  }
  g.ell(cx - 0.08, 0.34, 0.05, 0.03, C.GL);
  // 顔（みのの 上から のぞく）
  g.ell(cx, 0.26, 0.1, 0.08, C.F);
  for (const ex of [-0.04, 0.04]) g.ell(cx + ex, 0.26, 0.018, 0.024 * k, C.K);
  g.ell(cx - 0.065, 0.3, 0.02, 0.012, C.P);
  g.ell(cx + 0.065, 0.3, 0.02, 0.012, C.P);
}

