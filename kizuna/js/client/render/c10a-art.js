  g.ell(0.14, 0.59 - up, 0.1, 0.09, C.B);
  g.ell(0.1, 0.55 - up, 0.025, 0.03 * k, C.W);
  g.ell(0.095, 0.56 - up, 0.014, 0.02 * k, C.K);
  g.line([[0.06, 0.64 - up], [0.12, 0.66 - up]], C.BD, 1.2);
