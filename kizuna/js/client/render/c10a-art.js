function drillMecha(g, C, f, stop) {
  const k = g.w / g.h;
  // キャタピラ
  g.ell(0.42, 0.86, 0.36, 0.08, C.BRD);
  g.rect(0.08, 0.8, 0.68, 0.12, C.BRD);
  g.ell(0.1, 0.86, 0.06, 0.06 * k, C.BR);
  g.ell(0.74, 0.86, 0.06, 0.06 * k, C.BR);
  for (let i = 0; i < 8; i++) g.rect(0.12 + i * 0.08 + (stop ? 0 : f ? 0.04 : 0), 0.8, 0.03, 0.12, C.BR);
  // 本体（黄色い 箱）
  g.poly([[0.1, 0.8], [0.74, 0.8], [0.78, 0.56], [0.14, 0.52]], C.YD);
  g.poly([[0.12, 0.78], [0.72, 0.78], [0.75, 0.58], [0.16, 0.55]], C.Y);
  g.poly([[0.16, 0.58], [0.72, 0.6], [0.72, 0.64], [0.16, 0.62]], C.YL);
  // リベット・ランプ
  for (const x of [0.2, 0.32, 0.44, 0.56, 0.68]) g.ell(x, 0.74, 0.012, 0.012 * k, C.YD);
  g.ell(0.22, 0.66, 0.025, 0.025 * k, stop ? '#6a6a6a' : C.R);
  // あつさの メーター（え の 中の かざり）
  g.ell(0.4, 0.68, 0.04, 0.04 * k, C.W);
  g.line([[0.4, 0.68], [0.4 + (stop ? 0.03 : 0.01), 0.68 - (stop ? 0.01 : 0.03)]], C.K, 1.6);
  // ドリル（右に のびる。うずまきの すじ）
  g.poly([[0.74, 0.58], [0.74, 0.78], [0.98, 0.68]], C.DD);
  g.poly([[0.75, 0.6], [0.75, 0.74], [0.96, 0.67]], C.D);
  for (let i = 0; i < 4; i++) {
    const x0 = 0.76 + i * 0.05 + (stop ? 0 : f ? 0.025 : 0);
    const h = 0.09 * (1 - (x0 - 0.74) / 0.25);
    g.line([[x0, 0.68 - h], [x0 + 0.03, 0.68 + h * 0.6]], C.DL, 1.6);
  }
  // 回る 線（動いて いる 時だけ）
  if (!stop) for (let i = 0; i < 3; i++) g.line([[0.99, 0.6 + i * 0.05], [1.0, 0.62 + i * 0.05]], C.DL, 1);
  // 席（上の まるい くぼみ）
  g.ell(0.44, 0.54, 0.2, 0.05, C.YD);
}
function tamagonBody(g, C, f, stop) {
  const k = g.w / g.h;
  const up = stop ? 0 : f ? 0.008 : 0;
  // 白衣（ミント）
  g.ell(0.44, 0.5 - up, 0.17, 0.08, C.CTD);
  g.ell(0.44, 0.49 - up, 0.16, 0.07, C.CT);
  // たまごの 体（たて長）
  g.ell(0.44, 0.33 - up, 0.15, 0.2, C.ED);
  g.ell(0.44, 0.32 - up, 0.145, 0.195, C.E);
  g.ell(0.38, 0.22 - up, 0.04, 0.06, C.EL);
  for (const [x, y] of [[0.5, 0.2], [0.53, 0.3], [0.36, 0.4], [0.5, 0.42], [0.42, 0.16]]) g.ell(x, y - up, 0.012, 0.01, C.ES);
  // 大きな ゴーグル（2つの まるい レンズ。金の ふち）
  for (const ex of [0.39, 0.49]) {
    g.ell(ex, 0.28 - up, 0.05, 0.05 * k, C.GRD);
    g.ell(ex, 0.28 - up, 0.043, 0.043 * k, C.GR);
    g.ell(ex, 0.28 - up, 0.034, 0.034 * k, C.GG);
    g.ell(ex - 0.012, 0.268 - up, 0.012, 0.012 * k, C.GW);
    g.ell(ex + 0.004, 0.284 - up, 0.012, 0.014 * k, C.K);
  }
  g.line([[0.29, 0.28 - up], [0.34, 0.28 - up]], C.GRD, 2);
  g.line([[0.54, 0.28 - up], [0.59, 0.28 - up]], C.GRD, 2);
  g.rect(0.43, 0.275 - up, 0.02, 0.01, C.GRD);
  // ばねの ひげ（左右に ぐるぐる。銀）
  for (const s of [-1, 1]) {
    const pts = [];
    for (let i = 0; i <= 24; i++) {
      const t = i / 24;
      const a = t * Math.PI * 6;
      pts.push([0.44 + s * (0.02 + t * 0.12), 0.36 - up + Math.sin(a) * 0.012 + (stop ? t * 0.03 : 0)]);
    }
    g.line(pts, C.SPD, 2.2);
    g.line(pts, C.SP, 1.2);
  }
  // 口（ひげの 下）
  g.ell(0.44, 0.4 - up, stop ? 0.02 : 0.025, stop ? 0.012 : 0.015, C.M);
  // 手（レバーを にぎる）
  g.line([[0.32, 0.5 - up], [0.28, 0.46 - up]], C.CTD, 3);
  g.line([[0.56, 0.5 - up], [0.6, 0.46 - up]], C.CTD, 3);
  g.ell(0.28, 0.45 - up, 0.02, 0.02 * k, C.E);
  g.ell(0.6, 0.45 - up, 0.02, 0.02 * k, C.E);
  g.line([[0.6, 0.46 - up], [0.62, 0.52]], C.BRD, 1.6);
}
function tamagon(g0, f) {
  const g = fit(g0, 224);
  const C = TM;
  const stop = f >= 2;
  drillMecha(g, C, f % 2, stop);
  tamagonBody(g, C, f % 2, stop);
  if (stop) {
    // けむりと あせ（勝った あと … メカが 止まった。科学者は たおれない）
    for (const [x, y, r] of [[0.7, 0.42, 0.06], [0.78, 0.32, 0.07], [0.68, 0.22, 0.05], [0.16, 0.44, 0.05]]) {
      g.ell(x, y - (f % 2 ? 0.02 : 0), r, r * 0.8, C.SM);
      g.ell(x - r * 0.3, y - r * 0.3 - (f % 2 ? 0.02 : 0), r * 0.5, r * 0.4, C.SML);
    }
    g.ell(0.6, 0.2, 0.014, 0.024, C.SW);
    g.ell(0.27, 0.24, 0.012, 0.02, C.SW);
  } else {
    // 火花（ドリルの 先）
    spark(g, 0.97, 0.62 + (f ? 0.04 : 0), 0.03, '#ffd040', '#ffffff');
  }
}

