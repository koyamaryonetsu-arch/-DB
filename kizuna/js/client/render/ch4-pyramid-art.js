// ほうたいの まきすじ（x0〜x1 の はばで ななめに）
function wraps(g, x0, x1, y0, y1, n, c, lw = 0.8, tilt = 0.02) {
  for (let i = 0; i < n; i++) {
    const y = y0 + ((y1 - y0) * (i + 0.5)) / n;
    g.line([[x0, y + tilt], [x1, y - tilt]], c, lw);
  }
}

