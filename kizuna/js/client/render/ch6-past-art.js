// こけむしツノジカ: こけの 生えた 大きな ツノの シカ（左むき）。コマ1で 頭を 下げて ツノを 前へ
function mossDeer(g0, f) {
  const g = fit(g0, 64);
  const C = DEER;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  const dy = f ? 0.06 : 0;
  // うしろ足・前足
  for (const [x, c] of [[0.74, C.BD], [0.64, C.B], [0.38, C.BD], [0.3, C.B]]) {
    g.line([[x, 0.62], [x + 0.01, 0.8], [x, 0.94]], c, 3.4);
    g.ell(x, 0.95, 0.03, 0.02, C.E);
  }
  // 体
  g.ell(0.54, 0.56, 0.27, 0.16, C.BD);
  g.ell(0.54, 0.54, 0.26, 0.15, C.B);
  g.ell(0.5, 0.62, 0.18, 0.06, C.BL);
  // 背中の こけ
  for (const [x, r] of [[0.42, 0.06], [0.52, 0.07], [0.62, 0.06], [0.71, 0.05]]) g.ell(x, 0.41, r, r * 0.6, C.M);
  for (const [x, r] of [[0.46, 0.03], [0.6, 0.035]]) g.ell(x, 0.39, r, r * 0.6, C.ML);
  // しっぽ
  g.ell(0.8, 0.48, 0.04, 0.05, C.W);
  // くび・頭（コマ1で 下がる）
  g.poly([[0.32, 0.5], [0.24, 0.3 + dy], [0.32, 0.26 + dy], [0.4, 0.46]], C.B);
  g.ell(0.24, 0.3 + dy, 0.09, 0.07, C.B);
  g.poly([[0.17, 0.3 + dy], [0.07, 0.36 + dy], [0.1, 0.4 + dy], [0.2, 0.36 + dy]], C.BL);
  R(0.08, 0.37 + dy, 0.02, C.E);
  R(0.22, 0.28 + dy, 0.018, C.E);
  g.poly([[0.28, 0.24 + dy], [0.33, 0.18 + dy], [0.31, 0.27 + dy]], C.BD);
  // ツノ（えだわかれ。こけと 小さな 葉）
  const ax = 0.26, ay = 0.24 + dy;
  const tip = f ? -0.1 : 0;
  for (const s of [0, 1]) {
    const x0 = ax - s * 0.04;
    g.line([[x0, ay], [x0 - 0.04 + tip, ay - 0.1], [x0 - 0.1 + tip, ay - 0.16]], s ? C.AD : C.A, 2.2);
    g.line([[x0 - 0.04 + tip, ay - 0.1], [x0 + 0.02 + tip, ay - 0.18]], s ? C.AD : C.A, 1.6);
    g.line([[x0 - 0.07 + tip, ay - 0.13], [x0 - 0.06 + tip, ay - 0.2]], s ? C.AD : C.A, 1.2);
  }
  for (const [x, y] of [[0.2, 0.12], [0.27, 0.08], [0.15, 0.1]]) g.ell(x + tip, y + dy, 0.03, 0.02, C.M);
  g.ell(0.24 + tip, 0.1 + dy, 0.015, 0.012, C.ML);
}

