const GD = {
  I: '#6a7a8a', IL: '#9aaabb', ID: '#3e4a56', IDD: '#232b33', // 鉄の 体
  B: '#c08a3a', BL: '#e8b860', BD: '#7a5420', // 真ちゅうの 歯車
  E: '#ff6a2a', EL: '#ffe0a0', // 目
  K: '#2a1a10', W: '#f0e8d0', R: '#c83a2a', // 針・文字ばん・赤い ランプ
};
// ギアドン: ゼンマイの 番兵。どっしりした 鉄の からくり（正面）。むねに 時計の ついた 大歯車、せなかに 大きな ぜんまいの かぎ、
//   かたに 歯車。コマ0 … 両うでを 下げる / コマ1 … 右うでを ふり上げ、大歯車と かぎが 回り、目が 光る
function geardon(g0, f) {
  const g = fit(g0, 124);
  const C = GD;
  const k = g.w / g.h;
  const R = (x, y, r, c) => g.ell(x, y, r, r * k, c);
  // せなかの ぜんまいの かぎ（コマで 回る）
  const ka = f ? 0.6 : 0;
  g.line([[0.5, 0.2], [0.5, 0.06]], C.ID, 5);
  for (const s of [-1, 1]) {
    const ex = 0.5 + s * Math.cos(ka) * 0.12, ey = 0.075 + s * Math.sin(ka) * 0.03;
    g.ell(ex, ey, 0.06 * Math.max(0.4, Math.cos(ka)), 0.045, C.BD);
    g.ell(ex, ey, 0.04 * Math.max(0.4, Math.cos(ka)), 0.03, C.B);
  }
  // 足（太い 鉄の 柱）
  for (const s of [-1, 1]) {
    g.rect(0.5 + s * 0.13 - 0.08, 0.74, 0.16, 0.2, C.IDD);
    g.rect(0.5 + s * 0.13 - 0.07, 0.74, 0.14, 0.18, C.ID);
    g.rect(0.5 + s * 0.13 - 0.1, 0.92, 0.2, 0.05, C.IDD);
    gear(g, 0.5 + s * 0.13, 0.8, 0.05, 8, f ? 0.3 : 0, C.BD, C.B, C.IDD);
  }
  // 体（大きな 鉄の むね）
  g.poly([[0.24, 0.28], [0.76, 0.28], [0.72, 0.76], [0.28, 0.76]], C.IDD);
  g.poly([[0.26, 0.29], [0.74, 0.29], [0.7, 0.74], [0.3, 0.74]], C.I);
  g.poly([[0.28, 0.3], [0.5, 0.3], [0.48, 0.5], [0.3, 0.5]], C.IL);
  for (const [x, y] of [[0.3, 0.32], [0.7, 0.32], [0.32, 0.72], [0.68, 0.72]]) R(x, y, 0.012, C.IDD);
  // むねの 大歯車と 時計（コマで 回る）
  gear(g, 0.5, 0.52, 0.17, 12, f ? 0.26 : 0, C.BD, C.B, C.BD);
  R(0.5, 0.52, 0.1, C.W);
  for (let i = 0; i < 12; i++) {
    const a = (i * Math.PI) / 6;
    R(0.5 + Math.cos(a) * 0.085, 0.52 + Math.sin(a) * 0.085 * k, 0.006, C.K);
  }
  const hand = f ? -0.4 : -1.57;
  g.line([[0.5, 0.52], [0.5 + Math.cos(hand) * 0.08, 0.52 + Math.sin(hand) * 0.08 * k]], C.K, 2);
  g.line([[0.5, 0.52], [0.5 + Math.cos(hand + 2.2) * 0.05, 0.52 + Math.sin(hand + 2.2) * 0.05 * k]], C.R, 1.6);
  R(0.5, 0.52, 0.015, C.BL);
  // かたの 歯車
  for (const s of [-1, 1]) gear(g, 0.5 + s * 0.28, 0.3, 0.09, 10, (f ? 0.4 : 0) * s, C.BD, C.BL, C.ID);
  // うで（左は 下げる・右は コマ1で ふり上げる）
  g.line([[0.22, 0.36], [0.12, 0.54], [0.1, 0.7]], C.IDD, 10);
  g.line([[0.22, 0.36], [0.12, 0.54], [0.1, 0.7]], C.ID, 7);
  g.ell(0.1, 0.74, 0.07, 0.06, C.IDD);
  g.ell(0.1, 0.73, 0.06, 0.05, C.IL);
  const [hx, hy] = f ? [0.88, 0.1] : [0.9, 0.7];
  g.line([[0.78, 0.36], [0.88, f ? 0.26 : 0.54], [hx, hy + (f ? 0.05 : 0)]], C.IDD, 10);
  g.line([[0.78, 0.36], [0.88, f ? 0.26 : 0.54], [hx, hy + (f ? 0.05 : 0)]], C.ID, 7);
  g.ell(hx, hy, 0.07, 0.06, C.IDD);
  g.ell(hx, hy - 0.005, 0.06, 0.05, C.IL);
  // うでの ぜんまい（ばね）
  for (let i = 0; i < 3; i++) g.line([[0.14 - i * 0.008, 0.48 + i * 0.05], [0.2 - i * 0.008, 0.5 + i * 0.05]], C.B, 1.6);
  // 頭（四角い 鉄の 頭・目・赤い ランプ）
  g.rect(0.39, 0.12, 0.22, 0.16, C.IDD);
  g.rect(0.4, 0.13, 0.2, 0.14, C.I);
  g.rect(0.42, 0.18, 0.16, 0.05, C.IDD);
  for (const s of [-1, 1]) R(0.5 + s * 0.045, 0.205, f ? 0.022 : 0.016, f ? C.EL : C.E);
  R(0.5, 0.12, 0.02, C.R);
  for (let i = 0; i < 3; i++) g.rect(0.44 + i * 0.045, 0.245, 0.025, 0.015, C.ID);
  // じょうき（コマ1で 出る）
  if (f) for (const [x, y, r] of [[0.32, 0.18, 0.03], [0.27, 0.12, 0.022], [0.7, 0.16, 0.026]]) R(x, y, r, C.W);
}

