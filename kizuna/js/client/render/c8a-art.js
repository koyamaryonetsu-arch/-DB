const SB = {
  G: '#5ab04a', GD: '#3a8030', GL: '#9ad87a', // サボテンの たま
  W: '#f8f0d0', // とげ
  F: '#f86a8a', FL: '#ffd0dc', FC: '#ffd66b', // 花
  M: '#5a2a1a', // 口
  A: '#e8c47a', AD: '#c8a05a', // 砂
};
// サンボ: まるい サボテンが 4つ つみかさなる。いちばん 上に 顔と 花。コマ1 … たまが 左右に ゆれる
function sanbo(g0, f) {
  const g = fit(g0, 36);
  const C = SB;
  const k = g.w / g.h;
  // 足もとの 砂
  g.ell(0.5, 0.95, 0.4, 0.05, C.AD);
  g.ell(0.5, 0.94, 0.36, 0.035, C.A);
  const balls = [[0.5, 0.82, 0.3], [0.5, 0.62, 0.29], [0.5, 0.43, 0.28], [0.5, 0.24, 0.3]];
  balls.forEach(([x, y, r], i) => {
    const dx = (i % 2 ? 1 : -1) * (f ? 0.06 : 0.02) * (i ? 1 : 0.3);
    const cx = x + dx;
    const ry = r * k * 0.9;
    g.ell(cx, y, r, ry, C.GD);
    g.ell(cx - 0.01, y - 0.01, r * 0.93, ry * 0.92, C.G);
    // たての すじ
    for (const s of [-0.5, 0, 0.5]) g.line([[cx + s * r, y - ry * 0.8], [cx + s * r * 1.1, y], [cx + s * r, y + ry * 0.8]], C.GD, 0.8);
    g.ell(cx - r * 0.4, y - ry * 0.4, r * 0.18, ry * 0.15, C.GL);
    // とげ
    for (let j = 0; j < 6; j++) {
      const a = (j / 6) * Math.PI * 2 + i;
      const px = cx + Math.cos(a) * r * 0.95, py = y + Math.sin(a) * ry * 0.95;
      g.line([[px, py], [px + Math.cos(a) * 0.06, py + Math.sin(a) * 0.06 * k]], C.W, 0.8);
    }
  });
  // 顔（いちばん 上の たま）
  const [hx0, hy] = balls[3];
  const hx = hx0 + (f ? 0.06 : 0.02);
  g.eye(hx - 0.1, hy, 0.07, 0.2);
  g.eye(hx + 0.1, hy, 0.07, 0.2);
  g.poly([[hx - 0.1, hy + 0.08], [hx + 0.1, hy + 0.08], [hx + 0.06, hy + 0.13 + (f ? 0.02 : 0)], [hx - 0.06, hy + 0.13 + (f ? 0.02 : 0)]], C.M);
  // 頭の 花
  for (let j = 0; j < 5; j++) {
    const a = (j / 5) * Math.PI * 2;
    g.ell(hx + Math.cos(a) * 0.07, 0.05 + Math.sin(a) * 0.045, 0.06, 0.04, j % 2 ? C.FL : C.F);
  }
  g.ell(hx, 0.05, 0.04, 0.03, C.FC);
}

